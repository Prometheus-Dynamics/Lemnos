#!/usr/bin/env python3
"""Regenerates lemnosd's list of built-in drivers from drivers/*/Cargo.toml.

A driver crate names its type under [package.metadata.lemnos], as
`driver = "Type"`, or `driver = ["TypeA", "TypeB"]` for a crate with more than
one; this writes the marked block in service/lemnosd/Cargo.toml and
service/lemnosd/src/builtin.rs.
A maintainer runs it after merging driver PRs, so a driver PR edits no service
file. With --check it only reports whether the files are current.
"""
import pathlib
import re
import sys
import tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "service/lemnosd/Cargo.toml"
TABLE = ROOT / "service/lemnosd/src/builtin.rs"


def drivers():
    """(crate name, folder, [driver types]) for every crate that names one."""
    found = []
    for path in sorted((ROOT / "drivers").glob("*/Cargo.toml")):
        data = tomllib.loads(path.read_text())
        kinds = data["package"].get("metadata", {}).get("lemnos", {}).get("driver")
        if isinstance(kinds, str):
            kinds = [kinds]
        if kinds is None:
            continue
        if not isinstance(kinds, list) or not kinds or not all(
            isinstance(k, str) and re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", k) for k in kinds
        ):
            sys.exit(f"{path}: [package.metadata.lemnos] driver must be a type name or a list of them")
        if len(set(kinds)) != len(kinds):
            sys.exit(f"{path}: [package.metadata.lemnos] driver names a type twice")
        found.append((data["package"]["name"], path.parent.name, kinds))
    return found


def main():
    found = drivers()
    deps = "".join(f'{name} = {{ path = "../../drivers/{folder}" }}\n' for name, folder, _ in found)
    manifest = re.sub(
        r"(# generated: begin drivers\n).*?(# generated: end drivers)",
        lambda m: m.group(1) + deps + m.group(2),
        MANIFEST.read_text(),
        flags=re.S,
    )
    entries = "".join(
        f"        entry::<{name.replace('-', '_')}::{kind}>(),\n" for name, _, kinds in found for kind in kinds
    )
    table = (
        "//! Generated by `scripts/generate-builtins.py`. Do not edit.\n\n"
        "use lemnos_host::{DriverEntry, entry};\n\n"
        "/// Every driver compiled into this service.\n"
        "pub fn drivers() -> Vec<DriverEntry> {\n"
        f"    vec![\n{entries}    ]\n"
        "}\n"
    )
    if "--check" in sys.argv:
        current = MANIFEST.read_text() == manifest and TABLE.exists() and TABLE.read_text() == table
        print("up to date" if current else "out of date: run scripts/generate-builtins.py")
        sys.exit(0 if current else 1)
    MANIFEST.write_text(manifest)
    TABLE.write_text(table)


main()
