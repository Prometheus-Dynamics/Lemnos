#!/usr/bin/env bash
# Regenerates crates/lemnos-rkisp-sys/src/isp3x.rs (ISP30), .../isp21.rs (ISP21)
# and .../isp32.rs (ISP32, RV1106 and RK3562) from the Rockchip ISP uAPI headers in
# crates/lemnos-rkisp-sys/headers (rockchip-linux/kernel develop-5.10 include/uapi/linux;
# their own include of rk-camera-module.h is cut). Needs bindgen-cli and clang. The structures
# derive bytemuck's Pod and Zeroable; the bitfield unit's impls are hand-written in
# isp32_layout.rs.
set -euo pipefail
cd "$(dirname "$0")/.."
inc="$(mktemp -d)"
trap 'rm -rf "$inc"' EXIT
mkdir -p "$inc/linux"
for h in crates/lemnos-rkisp-sys/headers/*.h; do
    sed '/#include <linux\/rk-camera-module.h>/d' "$h" >"$inc/linux/$(basename "$h")"
done
out=crates/lemnos-rkisp-sys/src/isp3x.rs
{
    echo '//! @generated by bindgen from `headers/rk-isp3-config.h` (and the `rk-isp21`/`rk-isp2`'
    echo '//! headers it includes), Rockchip kernel `develop-5.10`, licensed'
    echo '//! `(GPL-2.0+ WITH Linux-syscall-note) OR MIT`; used here under MIT. Regenerate with'
    echo '//! `scripts/rkisp-bindgen.sh`; do not edit.'
    echo
    echo '#![allow(non_camel_case_types, non_upper_case_globals, dead_code, clippy::all, missing_docs)]'
    echo
    bindgen "$inc/linux/rk-isp3-config.h" --use-core --no-layout-tests --no-doc-comments \
        --with-derive-custom-struct '.*=bytemuck::Pod,bytemuck::Zeroable' \
        --allowlist-type 'isp3x_.*|rkisp3x_.*' \
        --allowlist-var 'ISP3X_.*|ISP2X_RAWAE.*|ISP2X_RAWHIST.*|ISP2X_HIST.*' \
        -- -I "$inc" -target aarch64-linux-gnu | sed -e '1d' -e 's/bytemuck :: /bytemuck::/g'
} >"$out"
rustfmt --edition 2024 "$out"

# ISP21 has its own LSC (8 sector sizes, no 16x16 flag), gamma (45 samples) and statistics
# wrapper, so its module is generated apart from ISP30's: the isp2x types it shares with
# ISP30 are generated again in it.
out=crates/lemnos-rkisp-sys/src/isp21.rs
{
    echo '//! @generated by bindgen from `headers/rk-isp21-config.h` (and the `rk-isp2` header it'
    echo '//! includes), Rockchip kernel `develop-5.10`, licensed'
    echo '//! `(GPL-2.0+ WITH Linux-syscall-note) OR MIT`; used here under MIT. Regenerate with'
    echo '//! `scripts/rkisp-bindgen.sh`; do not edit.'
    echo
    echo '#![allow(non_camel_case_types, non_upper_case_globals, dead_code, clippy::all, missing_docs)]'
    echo
    bindgen "$inc/linux/rk-isp21-config.h" --use-core --no-layout-tests --no-doc-comments \
        --with-derive-custom-struct '.*=bytemuck::Pod,bytemuck::Zeroable' \
        --allowlist-type 'isp21_.*|rkisp_isp21_.*' \
        --allowlist-var 'ISP21_.*|ISP2X_GAMMA_OUT_MAX_SAMPLES' \
        -- -I "$inc" -target aarch64-linux-gnu | sed -e '1d' -e 's/bytemuck :: /bytemuck::/g'
} >"$out"
rustfmt --edition 2024 "$out"

# ISP32 (rk-isp32-config.h, identical in develop-5.10 and develop-6.1; it includes the ISP3
# headers above).
out=crates/lemnos-rkisp-sys/src/isp32.rs
{
    echo '//! @generated by bindgen from `headers/rk-isp32-config.h` (and the ISP3, ISP21 and ISP2'
    echo '//! headers it includes), Rockchip kernel `develop-5.10`, licensed'
    echo '//! `(GPL-2.0+ WITH Linux-syscall-note) OR MIT`; used here under MIT. Regenerate with'
    echo '//! `scripts/rkisp-bindgen.sh`; do not edit.'
    echo '//!'
    echo '//! This is bindgen output for the uAPI structures'"'"' bitfields: `raw_get`, `raw_set` and'
    echo '//! `raw_get_const` are unsafe by bindgen'"'"'s design. The types the ISP32 structures contain from'
    echo '//! the ISP3 headers are generated again here, so this module stands alone.'
    echo
    echo '#![allow(non_camel_case_types, non_upper_case_globals, dead_code, clippy::all, missing_docs)]'
    # The bitfield accessors (`raw_get`, `raw_set`, `raw_get_const`) are unsafe blocks with several
    # operations each and no SAFETY comments: bindgen's code, not edited here.
    echo '#![allow(clippy::undocumented_unsafe_blocks, clippy::multiple_unsafe_ops_per_block)]'
    echo
    bindgen "$inc/linux/rk-isp32-config.h" --use-core --no-layout-tests --no-doc-comments \
        --with-derive-custom-struct '.*=bytemuck::Pod,bytemuck::Zeroable' \
        --allowlist-type 'isp32_.*|rkisp32_.*' \
        --allowlist-var 'ISP32_.*|ISP32L_.*' \
        -- -I "$inc" -target aarch64-linux-gnu | sed -e '1d' -e 's/bytemuck :: /bytemuck::/g'
} >"$out"
rustfmt --edition 2024 "$out"

# ISP35 (RV1126B, the driver's `ISP_V35`). Its headers come from develop-6.1 (headers/develop-6.1:
# rk-isp35 includes rk-isp33, which includes rk-isp39, on top of the ISP32 chain, and develop-6.1's
# rk-isp2 differs from the develop-5.10 one above), so they are laid over a copy.
inc61="$inc/61"
mkdir -p "$inc61/linux"
cp "$inc"/linux/*.h "$inc61/linux/"
for h in crates/lemnos-rkisp-sys/headers/develop-6.1/*.h; do
    sed '/#include <linux\/rk-camera-module.h>/d' "$h" >"$inc61/linux/$(basename "$h")"
done
out=crates/lemnos-rkisp-sys/src/isp35.rs
{
    echo '//! @generated by bindgen from `headers/develop-6.1/rk-isp35-config.h` (and the ISP33, ISP39,'
    echo '//! ISP32, ISP3, ISP21 and ISP2 headers it includes), Rockchip kernel `develop-6.1`, licensed'
    echo '//! `(GPL-2.0+ WITH Linux-syscall-note) OR MIT`; used here under MIT. Regenerate with'
    echo '//! `scripts/rkisp-bindgen.sh`; do not edit.'
    echo '//!'
    echo '//! Bindgen output for the uAPI structures'"'"' bitfields: the accessors are unsafe by bindgen'"'"'s'
    echo '//! design. The types the ISP35 structures contain from the other headers are generated again'
    echo '//! here, so this module stands alone.'
    echo
    echo '#![allow(non_camel_case_types, non_snake_case, non_upper_case_globals, dead_code, clippy::all, missing_docs)]'
    echo '#![allow(clippy::undocumented_unsafe_blocks, clippy::multiple_unsafe_ops_per_block)]'
    echo
    bindgen "$inc61/linux/rk-isp35-config.h" --use-core --no-layout-tests --no-doc-comments \
        --with-derive-custom-struct '.*=bytemuck::Pod,bytemuck::Zeroable' \
        --allowlist-type 'isp35_.*|rkisp35_.*' \
        --allowlist-var 'ISP35_.*' \
        -- -I "$inc61" -target aarch64-linux-gnu | sed -e '1d' -e 's/bytemuck :: /bytemuck::/g'
} >"$out"
rustfmt --edition 2024 "$out"
