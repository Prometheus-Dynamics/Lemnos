//! The `/etc/mdev.conf` lines that give the daemon's device nodes to its group, made from the same
//! facts as the udev rules ([`crate::permissions`]). `lemnos-ctl tree BOARD --mdev FILE` writes them.
//!
//! The syntax is BusyBox's `mdev.conf`. The gate runs the output against BusyBox 1.37.0 and 1.38.0
//! (`testing/mdev/check.sh`, which builds both from their release tarballs and checks the nodes they
//! create), so those are the versions the lines are known to work with. The source read for the rules
//! below is `util-linux/mdev.c` and `docs/mdev.txt` of the two release tarballs (the BusyBox mirror on
//! GitHub has no tags for these two releases, so the tarballs are the source). The two files are the
//! same bytes in both releases; the tarballs are sha256-pinned in `testing/mdev/build-busybox.sh`.
//! Line numbers are that file's.
//!
//! - `util-linux/mdev.c:603-625` (`make_device`, which starts at line 574): a device's name is its `DEVNAME=` from the uevent
//!   file (`mdev -s`) or the environment (hotplug). For a dma-heap that is the path, `dma_heap/<name>`.
//!   Only without `DEVNAME` does mdev fall back to the basename, which the rule below then does not
//!   match. The kernel writes `DEVNAME=dma_heap/<name>` for dma-heaps (checked on a running system).
//! - `util-linux/mdev.c:675-690`: a rule's regex is matched against that whole name, and the match
//!   must span it. So each pattern is anchored and its meta-characters escaped.
//! - `util-linux/mdev.c:352-375` (`parse_envmatch_pfx`) and `508-520` (`env_matches`), and
//!   `docs/mdev.txt` ("`[-][envmatch]<device regex>`"): a rule may start with `ENVVAR=regex;`, which
//!   matches the environment variable before the device regex is tried. `SUBSYSTEM` is set from the
//!   device's sysfs `subsystem` link (`mdev.c:871-879`) and by the kernel's hotplug environment. So
//!   `SUBSYSTEM=^misc$;` is the udev `SUBSYSTEM=="misc"` condition, and both versions read it.
//! - `util-linux/mdev.c:825-829`: the first matching line wins unless it starts with `-`. The lines written here cover distinct nodes, so their order among themselves does not
//!   matter; they must come before a catch-all line (`.* 0:0 660`) in `/etc/mdev.conf`.
//!
//! What this form does not check: the device's name is matched in full and its subsystem is matched
//! in full, which is what the udev rule says. Nothing else the udev rule says is missing; the packaged
//! kinds are in `packaging/init/mdev.conf.fragment`, not here.

use std::fmt::Write as _;

use lemnos_host::board::BoardFile;

use crate::permissions::{Fact, Name, sections};

/// The regex of one fact: the node's path under `/dev`, anchored at both ends. Every character that
/// is special in an extended regex is escaped, and a glob's `*` becomes `.*`.
#[must_use]
pub fn regex(fact: &Fact) -> String {
    let mut out = String::from("^");
    push_escaped(&mut out, fact.dir);
    match &fact.name {
        Name::Exact(name) => push_escaped(&mut out, name),
        Name::Glob(glob) => {
            for (i, part) in glob.split('*').enumerate() {
                if i > 0 {
                    out.push_str(".*");
                }
                push_escaped(&mut out, part);
            }
        }
    }
    out.push('$');
    out
}

fn push_escaped(out: &mut String, text: &str) {
    for c in text.chars() {
        if matches!(
            c,
            '\\' | '.' | '^' | '$' | '|' | '(' | ')' | '[' | ']' | '{' | '}' | '*' | '+' | '?'
        ) {
            out.push('\\');
        }
        out.push(c);
    }
}

/// One line of `/etc/mdev.conf` for a fact: `SUBSYSTEM=^<subsystem>$;<regex> <owner>:<group> <mode>`,
/// without the newline. The subsystem is matched in full, as udev's `SUBSYSTEM==` is.
#[must_use]
pub fn line(fact: &Fact) -> String {
    let mut subsystem = String::from("^");
    push_escaped(&mut subsystem, fact.subsystem);
    subsystem.push('$');
    format!(
        "SUBSYSTEM={subsystem};{} {}:{} {}",
        regex(fact),
        fact.owner,
        fact.group,
        fact.mode
    )
}

/// The fragment for a board: a header, then each section's title and lines. Ends with a newline.
#[must_use]
pub fn fragment(board: &BoardFile) -> String {
    let mut out = String::new();
    out.push_str(
        "# Device nodes the Lemnos daemon opens, given to its group. Generated by `lemnos-ctl tree\n\
         # --mdev` from the board file: do not edit. Append to /etc/mdev.conf after the image's\n\
         # init/mdev.conf.fragment and before any catch-all line (mdev takes the first line that matches).\n\
         # Each line is a BusyBox mdev.conf line: SUBSYSTEM=^subsystem$; (the udev SUBSYSTEM== condition,\n\
         # an env match) and the device regex, matched in full against the device's DEVNAME (a dma-heap\n\
         # is dma_heap/<name>), then owner:group and an octal mode. Run against BusyBox 1.37.0 and 1.38.0\n\
         # (testing/mdev/check.sh). The daemon checks each node it opens after its drop and names one that\n\
         # is not readable and writable by its group.\n",
    );
    for section in sections(board) {
        out.push('\n');
        for title_line in section.title.split('\n') {
            let _ = writeln!(out, "# {}", title_line.trim_start());
        }
        for fact in &section.facts {
            let _ = writeln!(out, "{}", line(fact));
        }
    }
    out
}
