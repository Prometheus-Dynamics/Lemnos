//! The `/etc/mdev.conf` lines that give the daemon's device nodes to its group, made from the same
//! facts as the udev rules ([`crate::permissions`]). `lemnos-ctl tree BOARD --mdev FILE` writes them.
//!
//! The syntax is BusyBox's `mdev.conf`, as its `docs/mdev.txt` describes it (read from the BusyBox
//! master tree, `docs/mdev.txt` and `util-linux/mdev.c`, version 1.37.0 in development; the lines
//! here use only the form `<device regex> <uid>:<gid> <permissions>`, which that file gives first, with
//! no `ENV=regex;` prefix and no `>path`, `=path`, `!`, `@` or `$` option). The renderer relies on:
//!
//! - the device regex is matched against the whole device name (`regexec`, and the match must span
//!   it), so each pattern is anchored and its meta-characters escaped;
//! - the first matching line wins unless it starts with `-`. The lines written here cover distinct
//!   nodes, so their order among themselves does not matter, but they must come before a catch-all
//!   line (`.* 0:0 660`) in `/etc/mdev.conf`;
//! - the device name of a dma-heap is `dma_heap/<name>`: mdev reads it from the device's `uevent`
//!   `DEVNAME=`, which is also how it names the node's directory.
//!
//! What udev's rule says and this form does not: the `SUBSYSTEM==` condition. mdev matches the device
//! name only, so a rule here applies to any device of that name in any subsystem. The names are the
//! kernel's own (`lemnos`, `lemnos-<receiver>` and the dma-heaps), and the daemon checks each node it
//! opens after its drop and names one that is not readable and writable by its group. The header of
//! the file says so.

use std::fmt::Write as _;

use lemnos_host::board::BoardFile;

use crate::permissions::{Fact, Name, sections};

/// The regex of one fact: the node's path under `/dev`, anchored at both ends. Every character that
/// is special in an extended regex is escaped, and a glob's `*` becomes `.*`.
#[must_use]
pub fn regex(fact: &Fact) -> String {
    let mut out = String::from("^");
    push_escaped(&mut out, fact.dir);
    match &fact.name {
        Name::Exact(name) => push_escaped(&mut out, name),
        Name::Glob(glob) => {
            for (i, part) in glob.split('*').enumerate() {
                if i > 0 {
                    out.push_str(".*");
                }
                push_escaped(&mut out, part);
            }
        }
    }
    out.push('$');
    out
}

fn push_escaped(out: &mut String, text: &str) {
    for c in text.chars() {
        if matches!(
            c,
            '\\' | '.' | '^' | '$' | '|' | '(' | ')' | '[' | ']' | '{' | '}' | '*' | '+' | '?'
        ) {
            out.push('\\');
        }
        out.push(c);
    }
}

/// One line of `/etc/mdev.conf` for a fact: `<regex> <owner>:<group> <mode>`, without the newline.
#[must_use]
pub fn line(fact: &Fact) -> String {
    format!(
        "{} {}:{} {}",
        regex(fact),
        fact.owner,
        fact.group,
        fact.mode
    )
}

/// The fragment for a board: a header, then each section's title and lines. Ends with a newline.
#[must_use]
pub fn fragment(board: &BoardFile) -> String {
    let mut out = String::new();
    out.push_str(
        "# Device nodes the Lemnos daemon opens, given to its group. Generated by `lemnos-ctl tree\n\
         # --mdev` from the board file: do not edit. Append to /etc/mdev.conf after the image's\n\
         # init/mdev.conf.fragment and before any catch-all line (mdev takes the first line that matches).\n\
         # Each line is a BusyBox mdev.conf line: the device name as a regex matched in full, owner:group,\n\
         # octal mode. mdev matches the name only, not the subsystem (udev's SUBSYSTEM==): the names are\n\
         # the kernel's own, and the daemon checks each node it opens and names one that is not readable\n\
         # and writable by its group.\n",
    );
    for section in sections(board) {
        out.push('\n');
        for title_line in section.title.split('\n') {
            let _ = writeln!(out, "# {}", title_line.trim_start());
        }
        for fact in &section.facts {
            let _ = writeln!(out, "{}", line(fact));
        }
    }
    out
}
