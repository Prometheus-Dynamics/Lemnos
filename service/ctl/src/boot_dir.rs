//! What `lemnos-ctl boot-partition` takes from the board and the repository for the boot partition's
//! text: the layout contract embedded in the image (`slot-layout.toml`) and its reader, the header of
//! both firmware config files, the overlay marker's text, the boot script, and the U-Boot form's
//! environment locator. The retired `tree --boot-dir` builder (which wrote these as a directory for the
//! image builder to place) is gone: `boot-partition` writes the volume itself.
//!
//! The board's firmware lines are the boot fragment (`gpio=` holds, see `--boot`): they are added
//! after the fixed text in both config files, inside `[all]` in `config.txt`, where they apply to
//! every boot. The board file has no other firmware line to express.

use lemnos_host::board::BoardFile;
use lemnos_slot_store::boot_raw::RECORD_BYTES;
use lemnos_slot_store::twocopy::Kind;

/// The slot layout contract: the list of every boot file of a slot, with its firmware kinds and
/// whether it is required. The boot partition carries a copy as `slot-layout.toml`.
pub const LAYOUT: &str = include_str!("../../../contracts/slot-layout.toml");

/// The header of both config files: generated, and what is not yet verified on a board.
pub const HEADER: &str = "# Generated by lemnos-ctl boot-partition. Do not edit.\n\
# From the documentation only, not yet run on a board (testing/board-runs/I5i6.md): the boot_count\n\
# filter and the kernel watchdog keys; and the slot lines below. The slot lines name the slot's files\n\
# with fixed names (slot-layout.toml). os_prefix (raspberrypi/documentation, config_txt/boot.adoc)\n\
# is prepended to kernels, initramfs, cmdline.txt, .dtbs and overlays; overlays only when\n\
# overlays/README exists there. device_tree=<file> loads that DTB (computers/configuration/\n\
# reference.adoc, part 5.3); whether os_prefix applies to it is not stated there and is unverified.\n\
# The firmware drops a missing kernel, dtb or overlay silently (it falls back), so the overlay marker\n\
# is checked at boot.\n";

/// One `[[record]]` of the layout contract: a record file the image builder pre-creates at the boot
/// partition's root, under its visible name.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RecordFile {
    /// The visible name (`trial.rec`): lower case, 8.3 with a dot, no space.
    pub name: String,
    /// The record it holds: `trial`, `reason` or `episodes`.
    pub role: String,
    /// The firmware kinds that use it.
    pub firmware: Vec<String>,
    /// The file's size in bytes.
    pub bytes: u64,
}

/// The slot-store kind a `[[record]]` role names.
pub fn kind_of_role(role: &str) -> Result<Kind, String> {
    match role {
        "trial" => Ok(Kind::TRIAL),
        "reason" => Ok(Kind::REASON),
        "episodes" => Ok(Kind::EPISODES),
        other => Err(format!(
            "slot-layout.toml: record role {other:?} is not trial, reason or episodes"
        )),
    }
}

/// Reads the `[[record]]` entries of the contract. A record must be `source = "generated"`, a
/// known role, and [`RECORD_BYTES`] long; its visible name must be the kind's `visible_name`.
pub fn read_records(text: &str) -> Result<Vec<RecordFile>, String> {
    let table: toml::Table = toml::from_str(text).map_err(|e| format!("slot-layout.toml: {e}"))?;
    let Some(entries) = table.get("record") else {
        return Ok(Vec::new());
    };
    let entries = entries
        .as_array()
        .ok_or("slot-layout.toml: [[record]] is not an array of tables")?;
    entries
        .iter()
        .map(|entry| {
            let entry = entry
                .as_table()
                .ok_or("slot-layout.toml: a [[record]] is not a table")?;
            for key in entry.keys() {
                if !["name", "role", "firmware", "bytes", "source", "scope"].contains(&key.as_str()) {
                    return Err(format!("slot-layout.toml: unknown key {key:?} in a [[record]]"));
                }
            }
            // A set-scope record (bayinfo.rec) is in each bay set, not at the root: the bays own it.
            if entry.get("scope").and_then(toml::Value::as_str) == Some("set") {
                return Ok(None);
            }
            let text = |key: &str| {
                entry
                    .get(key)
                    .and_then(toml::Value::as_str)
                    .map(str::to_string)
                    .ok_or_else(|| format!("slot-layout.toml: a [[record]] has no string {key:?}"))
            };
            let source = text("source")?;
            if source != "generated" {
                return Err(format!(
                    "slot-layout.toml: a [[record]]'s source is {source:?}, and records are generated"
                ));
            }
            let bytes = entry
                .get("bytes")
                .and_then(toml::Value::as_integer)
                .and_then(|n| u64::try_from(n).ok())
                .ok_or("slot-layout.toml: a [[record]] has no integer \"bytes\"")?;
            if bytes != RECORD_BYTES {
                return Err(format!(
                    "slot-layout.toml: a [[record]] is {bytes} bytes; a record is {RECORD_BYTES}"
                ));
            }
            let firmware = entry
                .get("firmware")
                .and_then(toml::Value::as_array)
                .ok_or("slot-layout.toml: a [[record]] has no firmware list")?
                .iter()
                .map(|v| {
                    v.as_str()
                        .map(str::to_string)
                        .ok_or("slot-layout.toml: a firmware kind is not a string")
                })
                .collect::<Result<Vec<_>, _>>()?;
            let name = text("name")?;
            let role = text("role")?;
            let kind = kind_of_role(&role)?;
            if kind.visible_name() != Some(name.as_str()) {
                return Err(format!(
                    "slot-layout.toml: record {name:?} is not the visible name of role {role:?}"
                ));
            }
            Ok(Some(RecordFile {
                name,
                role,
                firmware,
                bytes,
            }))
        })
        .collect::<Result<Vec<Option<RecordFile>>, String>>()
        .map(|records| records.into_iter().flatten().collect())
}

/// One entry of the layout contract.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LayoutFile {
    /// The path under the slot's directory.
    pub name: String,
    /// What the file is for (`kernel`, `initramfs`, ...).
    pub role: String,
    /// The firmware kinds that use it.
    pub firmware: Vec<String>,
    /// Whether a slot of those kinds must have it.
    pub required: bool,
    /// Who makes it: `build` (the bundle supplies it) or `generated` (`boot-partition` writes it).
    pub source: String,
}

/// The `[bay]` and `[volume]` tables of version 5 must state the values the code uses (bays::SETS,
/// the bay record and pointer sizes, FAT16 with two copies, the cluster-count limits of bootfat).
pub fn check_bay_and_volume(text: &str) -> Result<(), String> {
    let table: toml::Table = toml::from_str(text).map_err(|e| format!("slot-layout.toml: {e}"))?;
    let int = |t: &str, k: &str| {
        table
            .get(t)
            .and_then(|v| v.as_table())
            .and_then(|t| t.get(k))
            .and_then(toml::Value::as_integer)
    };
    let want = [
        ("bay", "sets", lemnos_slot_store::bays::SETS as i64),
        (
            "bay",
            "info_bytes",
            lemnos_slot_store::bays::INFO_BYTES as i64,
        ),
        (
            "bay",
            "pointer_bytes",
            lemnos_slot_store::bays::POINTER_BYTES as i64,
        ),
        ("volume", "fat", 16),
        ("volume", "fats", 2),
        ("volume", "min_clusters", 4085),
        ("volume", "max_clusters", 65524),
    ];
    for (t, k, v) in want {
        match int(t, k) {
            Some(got) if got == v => {}
            other => {
                return Err(format!(
                    "slot-layout.toml: [{t}] {k} is {other:?}; this reader needs {v}"
                ));
            }
        }
    }
    Ok(())
}

/// Reads the layout contract. It refuses any version but 5, any key it does not know (at the top
/// level or in an entry), a `source` other than `build` or `generated`, and an entry without the
/// fields it needs.
pub fn read_layout(text: &str) -> Result<Vec<LayoutFile>, String> {
    check_bay_and_volume(text)?;
    let table: toml::Table = toml::from_str(text).map_err(|e| format!("slot-layout.toml: {e}"))?;
    for key in table.keys() {
        if !["version", "file", "record", "bay", "volume"].contains(&key.as_str()) {
            return Err(format!("slot-layout.toml: unknown key {key:?}"));
        }
    }
    match table.get("version").and_then(toml::Value::as_integer) {
        Some(5) => {}
        other => {
            return Err(format!(
                "slot-layout.toml: version {other:?}; this reader reads 5"
            ));
        }
    }
    let files = table
        .get("file")
        .and_then(toml::Value::as_array)
        .ok_or("slot-layout.toml: no [[file]] entries")?;
    files
        .iter()
        .map(|entry| {
            let entry = entry
                .as_table()
                .ok_or("slot-layout.toml: a [[file]] is not a table")?;
            for key in entry.keys() {
                if !["name", "role", "firmware", "required", "source", "scope"]
                    .contains(&key.as_str())
                {
                    return Err(format!(
                        "slot-layout.toml: unknown key {key:?} in a [[file]]"
                    ));
                }
            }
            let text = |key: &str| {
                entry
                    .get(key)
                    .and_then(toml::Value::as_str)
                    .map(str::to_string)
                    .ok_or_else(|| format!("slot-layout.toml: a [[file]] has no string {key:?}"))
            };
            let firmware = entry
                .get("firmware")
                .and_then(toml::Value::as_array)
                .ok_or("slot-layout.toml: a [[file]] has no firmware list")?
                .iter()
                .map(|v| {
                    v.as_str()
                        .map(str::to_string)
                        .ok_or("slot-layout.toml: a firmware kind is not a string")
                })
                .collect::<Result<Vec<_>, _>>()?;
            let required = entry
                .get("required")
                .and_then(toml::Value::as_bool)
                .ok_or("slot-layout.toml: a [[file]] has no boolean \"required\"")?;
            let source = text("source")?;
            if source != "build" && source != "generated" {
                return Err(format!(
                    "slot-layout.toml: source {source:?} is neither \"build\" nor \"generated\""
                ));
            }
            Ok(LayoutFile {
                name: text("name")?,
                role: text("role")?,
                firmware,
                required,
                source,
            })
        })
        .collect()
}

/// The text of [`OVERLAY_README`], one line.
pub const OVERLAY_README_TEXT: &str = "Generated by lemnos-ctl boot-partition: this file makes os_prefix apply to overlays (raspberrypi/documentation config_txt/config_txt_boot.adoc, overlay_prefix).\n";

/// The `boot` table of a slot manifest that the generator is the authority for, as `--manifest-boot`
/// writes it: one JSON object, newline-terminated, with its keys in this order. A board whose
/// overlay carries the marker gets `{"overlay":{"board":ID,"sha256":DIGEST}}`, where ID is the
/// marker's `lemnos,board` and DIGEST its `lemnos,overlay-sha256`, byte for byte. A board whose
/// overlay has no marker (a `fragment` form, so no overlay is loaded) gets `{}`: the manifest's
/// `boot.overlay` is optional. The other `boot` keys (`files`) are the build's, not written here.
pub fn manifest_boot(board_id: &str, overlay_sha256: Option<&str>) -> Result<String, String> {
    let Some(digest) = overlay_sha256 else {
        return Ok("{}\n".to_string());
    };
    let plain_id = !board_id.is_empty()
        && board_id
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_' || b == b'.');
    if !plain_id {
        return Err(format!(
            "board id {board_id:?} is not a plain id (letters, digits, '-', '_', '.')"
        ));
    }
    let hex = digest.len() == 64
        && digest
            .bytes()
            .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b));
    if !hex {
        return Err("the overlay marker's digest is not 64 lowercase hex digits".into());
    }
    Ok(format!(
        "{{\"overlay\":{{\"board\":\"{board_id}\",\"sha256\":\"{digest}\"}}}}\n"
    ))
}

/// The record a board's `system-slots` device names: `tryboot` when it names none.
pub fn record_of(board: &BoardFile) -> Result<String, String> {
    let device = board
        .devices
        .iter()
        .find(|device| device.driver == "system-slots")
        .ok_or("this board has no system-slots device, so there are no boot files to write")?;
    match device.config.get("record") {
        None => Ok("tryboot".to_string()),
        Some(value) => value
            .as_str()
            .map(str::to_string)
            .ok_or_else(|| "system-slots: record must be a string".to_string()),
    }
}

/// The slot's kernel command-line words for `--cmdline-slot`, one line: `<prefix>.slot=<ID>
/// <prefix>.roothash=@roothash@ <prefix>.src.<source>=<path> ... panic=5`. `<prefix>` is the
/// system-slots `boot_args` of the board file: the words the slot-init program reads from the line.
/// `@roothash@` is the one value the installer fills in (the manifest's root hash). There is one
/// `.src.` word per `boot_sources` entry, in the table's order, the entry itself after `.src.`: the
/// slot's initramfs finds its boot disk from them, and the install refuses a bundle without each.
/// There is no `.disk=` word. `panic=5` is a fixed word: the fallback depends on a panic restarting
/// the board, so it is never left out or changed.
pub fn cmdline_slot(board: &BoardFile, slot: &str) -> Result<String, String> {
    let device = board
        .devices
        .iter()
        .find(|device| device.driver == "system-slots")
        .ok_or(
            "this board has no system-slots device, so there is no slot to name on a command line",
        )?;
    let prefix = match device.config.get("boot_args") {
        None => {
            return Err(
                "system-slots: boot_args is not set, so the command line has no prefix for the slot"
                    .to_string(),
            );
        }
        Some(value) => value
            .as_str()
            .ok_or_else(|| "system-slots: boot_args must be a string".to_string())?,
    };
    if prefix.is_empty()
        || !prefix
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-')
    {
        return Err(format!(
            "system-slots: boot_args {prefix:?} must be letters, digits, '_' or '-'"
        ));
    }
    if slot.is_empty() || slot.chars().any(char::is_whitespace) {
        return Err(format!(
            "slot {slot:?} is not a slot id a command line can carry"
        ));
    }
    let mut words = format!("{prefix}.slot={slot} {prefix}.roothash=@roothash@");
    // `record = "ubi"` (raw NAND) boots from no disk and has no table.
    let record = device
        .config
        .get("record")
        .and_then(|value| value.as_str())
        .unwrap_or("tryboot");
    match device.config.get("boot_sources") {
        Some(value) => {
            let items: Vec<&str> = value
                .as_array()
                .ok_or("system-slots: boot_sources must be a list of strings")?
                .iter()
                .map(|item| {
                    item.as_str()
                        .ok_or("system-slots: boot_sources must be a list of strings")
                })
                .collect::<Result<_, _>>()?;
            // The table's own parse: the same refusals as the driver's, by name.
            lemnos_slot_store::disk::Table::parse(&items)
                .map_err(|why| format!("system-slots: {why}"))?;
            for item in items {
                words.push_str(&format!(" {prefix}.src.{item}"));
            }
        }
        None if record == "ubi" => {}
        None => {
            return Err(
                "system-slots: boot_sources is not set, so the command line cannot name the boot source"
                    .to_string(),
            );
        }
    }
    words.push_str(" panic=5\n");
    Ok(words)
}

/// The U-Boot script's source, which the image builder compiles with `mkimage` into `boot.scr`.
pub const BOOT_CMD: &str = include_str!("../../../packaging/uboot/boot.cmd");

/// The contract this tool embeds is the one the code writes, read before an image is built: the
/// reader's version and key rules, the `[bay]` and `[volume]` tables, the `rpi-tryboot` list is the
/// slot-store constants, the volume-scope records are the image builder's, and the U-Boot form's
/// environment file is the slot-store locator's name.
pub fn check_contract() -> Result<(), String> {
    let layout = read_layout(LAYOUT)?;
    let required: Vec<&str> = layout
        .iter()
        .filter(|f| f.required && f.firmware.iter().any(|k| k == "rpi-tryboot"))
        .map(|f| f.name.as_str())
        .collect();
    if required != lemnos_slot_store::layout::RPI_TRYBOOT_REQUIRED {
        return Err("slot-layout.toml's rpi-tryboot list isn't the slot-store constants".into());
    }
    let records: Vec<String> = read_records(LAYOUT)?
        .into_iter()
        .map(|r| r.name.to_ascii_lowercase())
        .collect();
    if records != lemnos_slot_store::bootimage::RECORDS {
        return Err("slot-layout.toml's records aren't the image builder's".into());
    }
    let named = layout
        .iter()
        .find(|f| f.role == "uboot-env")
        .ok_or("slot-layout.toml lists no uboot-env file")?;
    if named.name != lemnos_slot_store::uboot_env::LOCATOR {
        return Err("slot-layout.toml's uboot file isn't the slot-store locator name".into());
    }
    Ok(())
}

/// The `system-slots` device's settings of a `uboot` board.
fn slots_config(board: &BoardFile) -> Result<&toml::Table, String> {
    let device = board
        .devices
        .iter()
        .find(|device| device.driver == "system-slots")
        .ok_or("this board has no system-slots device")?;
    Ok(&device.config)
}

/// A refusal about the `system-slots` device's settings, with the device named: `system-slots: <what>`
/// becomes `system-slots device "<id>": <what>`, so a board with several devices says which one.
fn name_device(board: &BoardFile, error: String) -> String {
    match (
        board.devices.iter().find(|d| d.driver == "system-slots"),
        error.strip_prefix("system-slots: "),
    ) {
        (Some(device), Some(rest)) => format!("system-slots device \"{}\": {rest}", device.id),
        _ => error,
    }
}

/// A non-negative integer setting, or `default` when it is not given (`None`: it is required).
fn setting(config: &toml::Table, key: &str, default: Option<u64>) -> Result<u64, String> {
    match config.get(key) {
        None => default.ok_or_else(|| {
            format!("system-slots: {key} is needed for the \"uboot\" record (an integer)")
        }),
        Some(value) => value
            .as_integer()
            .and_then(|n| u64::try_from(n).ok())
            .ok_or_else(|| format!("system-slots: {key} must be a non-negative integer")),
    }
}

/// Where the environment is, from the board file: the GPT form (only `uboot_env_size`), or with
/// `uboot_env_device` the fixed-offset form. `uboot_env_partuuid` is refused by name.
pub fn uboot_place(board: &BoardFile) -> Result<lemnos_slot_store::uboot_env::Place, String> {
    uboot_place_inner(board).map_err(|e| name_device(board, e))
}

fn uboot_place_inner(board: &BoardFile) -> Result<lemnos_slot_store::uboot_env::Place, String> {
    use lemnos_slot_store::uboot_env::Place;
    let config = slots_config(board)?;
    if config.contains_key("uboot_env_partuuid") {
        return Err(format!(
            "system-slots: uboot_env_partuuid is not a key: the environment is found by its GPT partition type GUID {} on the boot disk (uboot_env_device with offsets names one outside the GPT)",
            lemnos_slot_store::gpt::ENV_TYPE_GUID
        ));
    }
    let size = usize::try_from(setting(config, "uboot_env_size", None)?)
        .map_err(|_| "system-slots: uboot_env_size is out of range".to_string())?;
    match config.get("uboot_env_device") {
        None => {
            for key in ["uboot_env_offset", "uboot_env_offset_redund"] {
                if config.contains_key(key) {
                    return Err(format!(
                        "system-slots: {key} needs uboot_env_device: the GPT form places both copies itself"
                    ));
                }
            }
            Place::gpt(size).map_err(|e| format!("system-slots: uboot_env_size: {e}"))
        }
        Some(device) => {
            let device = device
                .as_str()
                .ok_or("system-slots: uboot_env_device must be a string")?;
            Place::device(
                device,
                size,
                setting(config, "uboot_env_offset", None)?,
                setting(config, "uboot_env_offset_redund", None)?,
            )
            .map_err(|e| format!("system-slots: uboot_env_device: {e}"))
        }
    }
}

/// The boot script of a `uboot` board as the image carries it: the board's USB controller and LED
/// set before `packaging/uboot/boot.cmd`. Refused by name when a key is not one the script takes.
pub fn uboot_script(board: &BoardFile) -> Result<String, String> {
    uboot_script_inner(board).map_err(|e| name_device(board, e))
}

fn uboot_script_inner(board: &BoardFile) -> Result<String, String> {
    let config = slots_config(board)?;
    let usb = setting(config, "uboot_fastboot_usb", Some(0))?;
    let led = match config.get("uboot_led") {
        None => String::new(),
        Some(value) => {
            let label = value
                .as_str()
                .ok_or("system-slots: uboot_led must be a string")?;
            if label.is_empty()
                || !label
                    .bytes()
                    .all(|b| b.is_ascii_alphanumeric() || b"_-:.".contains(&b))
            {
                return Err(format!(
                    "system-slots: uboot_led {label:?} is not a U-Boot LED label (letters, digits, `_-:.`)"
                ));
            }
            format!("setenv lemnos_led {label}\n")
        }
    };
    Ok(format!(
        "# Written by lemnos-ctl boot-partition from the board file: the USB controller the download\n\
         # mode uses and the LED it lights. The script follows.\n\
         setenv lemnos_usb {usb}\n{led}{BOOT_CMD}"
    ))
}

/// The U-Boot configuration fragment the board's U-Boot is built with, for `record = "uboot"`:
/// Kconfig lines the image builder includes verbatim (`scripts/kconfig/merge_config.sh`). Every name
/// is a U-Boot v2026.10 option, with the file and line that define it in the comment above its
/// group. The board's own storage, USB device controller, watchdog and LED drivers
/// (`CONFIG_MMC_*`, `CONFIG_USB_GADGET_*` for the controller, `CONFIG_WDT_*`, `CONFIG_LED_*`) are the
/// board's defconfig and are not named here.
pub fn uboot_config(board: &BoardFile) -> Result<String, String> {
    uboot_config_inner(board).map_err(|e| name_device(board, e))
}

fn uboot_config_inner(board: &BoardFile) -> Result<String, String> {
    use lemnos_slot_store::uboot_env::Place;
    if record_of(board)? != "uboot" {
        return Err(format!(
            "this board's record is {:?}: the U-Boot configuration is for \"uboot\"",
            record_of(board)?
        ));
    }
    let config = slots_config(board)?;
    let place = uboot_place(board)?;
    let mmc = setting(config, "uboot_env_mmc_index", Some(0))?;
    let usb = setting(config, "uboot_fastboot_usb", Some(0))?;
    let mut out = String::from(
        "# Written by lemnos-ctl tree --uboot-config from the board file. Include it verbatim in the\n\
         # U-Boot build for this board (U-Boot v2026.10 Kconfig names). Do not edit.\n\n",
    );
    let mut group = |title: &str, lines: &[String]| {
        out.push_str(&format!("# {title}\n"));
        for line in lines {
            out.push_str(line);
            out.push('\n');
        }
        out.push('\n');
    };
    group(
        "The environment: in the MMC device, redundant, saved by `saveenv` (env/Kconfig:229 ENV_IS_IN_MMC,\n\
         # :522 ENV_REDUNDANT, :700 ENV_SIZE, :781 ENV_MMC_DEVICE_INDEX; cmd/Kconfig:727 CMD_SAVEENV).\n\
         # CONFIG_ENV_SIZE is uboot_env_size: both copies are that many bytes, and slot-init and lemnosd\n\
         # refuse an environment whose copies do not check at that size.",
        &[
            "CONFIG_ENV_IS_IN_MMC=y".into(),
            format!("CONFIG_ENV_MMC_DEVICE_INDEX={mmc}"),
            "CONFIG_ENV_REDUNDANT=y".into(),
            format!("CONFIG_ENV_SIZE=0x{:x}", place.size()),
            "CONFIG_CMD_SAVEENV=y".into(),
        ],
    );
    match &place {
        Place::Gpt { .. } => group(
            "Where the copies are: at the top of the one GPT partition of type\n\
             # 3de21764-95bd-54bd-a5c3-4abe786f38a8 (env/mmc.c:114-148, GUID in include/part_efi.h:61),\n\
             # which needs the GPT reader and the control device tree (env/mmc.c:51 OF_CONTROL;\n\
             # disk/Kconfig:165 PARTITION_TYPE_GUID). The image has exactly one such partition, at least\n\
             # two copies long; the offsets are not configured.",
            &[
                "CONFIG_EFI_PARTITION=y".into(),
                "CONFIG_PARTITION_TYPE_GUID=y".into(),
                "CONFIG_OF_CONTROL=y".into(),
            ],
        ),
        Place::Device { geometry, .. } => group(
            "Where the copies are: fixed byte offsets of the MMC device (env/Kconfig:644 ENV_OFFSET,\n\
             # :675 ENV_OFFSET_REDUND), uboot_env_offset and uboot_env_offset_redund.",
            &[
                format!("CONFIG_ENV_OFFSET=0x{:x}", geometry.offset),
                format!("CONFIG_ENV_OFFSET_REDUND=0x{:x}", geometry.offset_redund),
            ],
        ),
    }
    group(
        "The boot script: hush with while and for, sysboot, fdt, sleep (cmd/Kconfig:574 CMD_FDT,\n\
         # :2545 CMD_SLEEP, :2574 CMD_SYSBOOT; common/cli_hush.c:2383-2388).",
        &[
            "CONFIG_HUSH_PARSER=y".into(),
            "CONFIG_CMD_FDT=y".into(),
            "CONFIG_CMD_SLEEP=y".into(),
            "CONFIG_CMD_SYSBOOT=y".into(),
        ],
    );
    let mut fastboot = vec![
        "CONFIG_USB_GADGET=y".into(),
        "CONFIG_USB_FUNCTION_FASTBOOT=y".into(),
        "CONFIG_CMD_FASTBOOT=y".into(),
        format!("CONFIG_FASTBOOT_USB_DEV={usb}"),
        "CONFIG_FASTBOOT_FLASH=y".into(),
        "CONFIG_FASTBOOT_FLASH_MMC=y".into(),
        format!("CONFIG_FASTBOOT_FLASH_MMC_DEV={mmc}"),
    ];
    match (
        config.get("uboot_usb_vendor"),
        config.get("uboot_usb_product"),
    ) {
        (None, None) => {}
        (Some(_), Some(_)) => {
            for (key, name) in [
                ("uboot_usb_vendor", "CONFIG_USB_GADGET_VENDOR_NUM"),
                ("uboot_usb_product", "CONFIG_USB_GADGET_PRODUCT_NUM"),
            ] {
                let id = setting(config, key, None)?;
                if id > 0xffff {
                    return Err(format!("system-slots: {key} must be 0 to 65535"));
                }
                fastboot.push(format!("{name}=0x{id:04x}"));
            }
        }
        _ => {
            return Err(
                "system-slots: uboot_usb_vendor and uboot_usb_product are given together or not at all"
                    .into(),
            );
        }
    }
    group(
        "Download mode: the fastboot gadget (drivers/fastboot/Kconfig:20 USB_FUNCTION_FASTBOOT, :82\n\
         # FASTBOOT_USB_DEV, :91 FASTBOOT_FLASH, :115 FASTBOOT_FLASH_MMC; cmd/Kconfig:1199 CMD_FASTBOOT;\n\
         # drivers/usb/gadget/Kconfig:59 and :71 for the VID and PID). The VID and PID are only emitted\n\
         # when the board file gives uboot_usb_vendor and uboot_usb_product; otherwise U-Boot's own\n\
         # defaults for the SoC stay, a placeholder the project replaces with its own. The buffer\n\
         # (FASTBOOT_BUF_ADDR, FASTBOOT_BUF_SIZE) is the board's defconfig: it is RAM the board knows.",
        &fastboot,
    );
    let mut watchdog = vec!["CONFIG_WDT=y".into(), "CONFIG_WATCHDOG=y".into()];
    if config.contains_key("uboot_watchdog_ms") {
        watchdog.push(format!(
            "CONFIG_WATCHDOG_TIMEOUT_MSECS={}",
            setting(config, "uboot_watchdog_ms", None)?
        ));
    }
    watchdog.push("CONFIG_WATCHDOG_AUTOSTART=y".into());
    group(
        "The watchdog, started at init and serviced by U-Boot itself, also inside the fastboot loop\n\
         # (drivers/watchdog/Kconfig:3 WATCHDOG, :14 WATCHDOG_AUTOSTART, :30 WATCHDOG_TIMEOUT_MSECS, :82\n\
         # WDT; cmd/fastboot.c:115 schedule()): a flash in progress is not reset, a U-Boot that hangs is.\n\
         # The board's own watchdog driver (CONFIG_WDT_*) is its defconfig.",
        &watchdog,
    );
    if config.contains_key("uboot_led") {
        group(
            "The download-mode LED (drivers/led/Kconfig:3 LED; cmd/Kconfig:2479 CMD_LED, cmd/led.c:121).\n\
             # The board's LED driver and its device-tree node with the label are the board's.",
            &["CONFIG_LED=y".into(), "CONFIG_CMD_LED=y".into()],
        );
    }
    while out.ends_with("\n\n") {
        out.pop();
    }
    Ok(out)
}

/// The header, the fixed text, then the board's lines, one per line.
pub(crate) fn with_fragment(header: &str, fixed: &str, fragment: &str) -> Vec<u8> {
    let mut text = format!("{header}{fixed}");
    let fragment = fragment.trim_end();
    if !fragment.is_empty() {
        text.push_str(fragment);
        text.push('\n');
    }
    text.into_bytes()
}
