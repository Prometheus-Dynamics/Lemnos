//! `lemnos-ctl tree BOARD --bridge-env FILE` and `--bridge-dropin FILE`: the bridge's settings, written
//! from the board file so that an image cannot forget one or disagree with itself.
//!
//! The bridge (`lemnos-orion`) offers a gadget's bulk pair to the comm core as a link only when
//! `LEMNOS_ORION_LINKS` names it as `<device id>=<link name>`. The device is the board file's
//! usb-gadget device, and the link name is the composition's own: the name on the first
//! `interface` line of the gadget's `interfaces` (the managed default's is `orion-link`), the
//! string the host reads from the link's interface. The comm core has to know a USB link by that
//! same name; that is its configuration, not written here.
//!
//! It takes files pushed to a device only when `LEMNOS_ORION_FILES` names the device and the
//! directory its files go into, and streams the names `LEMNOS_ORION_STREAMS` gives it. A device
//! takes files when its driver has the files protocol's methods
//! ([`lemnos_wire::text::takes_files`], the bridge's own rule). The directory is the driver's: a
//! slot device's `<data>/slots/.incoming`, a flash device's
//! [`lemnos_driver_system_flash::PUSHED_FILES_DIR`]. Under systemd the bridge can write only the
//! directories its unit grants, so `--bridge-dropin` writes the unit drop-in that grants exactly
//! those, from the same list.

use std::fmt::Write as _;

use lemnos_core::Manifest;
use lemnos_driver_usb_gadget::DEFAULT_INTERFACES;
use lemnos_driver_usb_gadget::description::{Fault, link_name};
use lemnos_host::board::{BoardFile, DeviceSpec};

/// The driver a gadget device names in the board file.
const DRIVER: &str = "usb-gadget";
/// The environment variable for the links.
pub const VARIABLE: &str = "LEMNOS_ORION_LINKS";
/// The environment variable for the devices that take files, and their directories.
pub const FILES: &str = "LEMNOS_ORION_FILES";
/// The environment variable for the names a device takes as a stream.
pub const STREAMS: &str = "LEMNOS_ORION_STREAMS";

/// The first words of the file, so a reader knows where it came from.
pub const HEADER: &str =
    "# Generated by lemnos-ctl tree --bridge-env from the board file. Do not edit.\n";

/// The first words of the drop-in.
pub const DROPIN_HEADER: &str = "# Generated by lemnos-ctl tree --bridge-dropin from the board file. Do not edit.\n\
     # Install as /etc/systemd/system/lemnos-orion.service.d/files.conf, with the env file\n\
     # --bridge-env writes from the same board file.\n";

/// A device that takes files, where they go, and the names it takes as a stream.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Pushed {
    pub device: String,
    pub dir: String,
    pub streams: Vec<String>,
}

/// The text of the env file for `board`: the `LEMNOS_ORION_LINKS` line for its gadget devices (each
/// `<device id>=<link name>`, comma-separated), the `LEMNOS_ORION_FILES` and
/// `LEMNOS_ORION_STREAMS` lines for its devices that take files, or comments saying there are none.
/// `drivers` are the manifests of the drivers the image has.
///
/// # Errors
///
/// A gadget whose `interfaces` do not parse or do not put the link first, whose first interface
/// has no name, or whose `interfaces_file` cannot be read; and a device that takes files whose
/// driver gives no place for them.
pub fn text(board: &BoardFile, drivers: &[Manifest]) -> Result<String, String> {
    let mut entries = Vec::new();
    for device in board
        .devices
        .iter()
        .filter(|d| d.driver == DRIVER && !d.disabled)
    {
        let name = link_of(device)?;
        entries.push(format!("{}={name}", device.id));
    }
    let mut out = String::from(HEADER);
    if entries.is_empty() {
        out.push_str(
            "# This board has no usb-gadget device, so no USB link is offered and the bridge has\n\
             # nothing to set.\n",
        );
    } else {
        out.push_str(
            "# The bridge offers each gadget's bulk endpoints to the comm core as the link named\n\
             # after the `=`. The comm core must know a USB link by the same name.\n",
        );
        let _ = writeln!(out, "{VARIABLE}={}", entries.join(","));
    }
    let pushed = pushed(board, drivers)?;
    if pushed.is_empty() {
        out.push_str("# No device on this board takes files, so the bridge takes none.\n");
        return Ok(out);
    }
    out.push_str(
        "# The devices that take files pushed through Orion, and where each one's go. The unit\n\
         # drop-in --bridge-dropin writes grants exactly these directories.\n",
    );
    let files: Vec<String> = pushed
        .iter()
        .map(|p| format!("{}={}", p.device, p.dir))
        .collect();
    let _ = writeln!(out, "{FILES}={}", files.join(","));
    let streams: Vec<String> = pushed
        .iter()
        .filter(|p| !p.streams.is_empty())
        .map(|p| format!("{}={}", p.device, p.streams.join("+")))
        .collect();
    if !streams.is_empty() {
        out.push_str(
            "# The names each device takes as a stream, fed to its write job as they arrive.\n",
        );
        let _ = writeln!(out, "{STREAMS}={}", streams.join(","));
    }
    Ok(out)
}

/// The systemd drop-in for the bridge's unit on `board`: `ReadWritePaths=` for each directory the
/// env file's `LEMNOS_ORION_FILES` names, each optional (`-`), so a directory that is not there yet
/// does not fail the unit's namespace. A board with no device that takes files gets a comment.
///
/// # Errors
///
/// As [`text`], for a device that takes files whose driver gives no place for them.
pub fn dropin(board: &BoardFile, drivers: &[Manifest]) -> Result<String, String> {
    let pushed = pushed(board, drivers)?;
    let mut out = String::from(DROPIN_HEADER);
    if pushed.is_empty() {
        out.push_str("# No device on this board takes files: the bridge writes nothing.\n");
        return Ok(out);
    }
    out.push_str("[Service]\n");
    let dirs: Vec<String> = pushed.iter().map(|p| format!("-{}", p.dir)).collect();
    let _ = writeln!(out, "ReadWritePaths={}", dirs.join(" "));
    Ok(out)
}

/// Every device on `board` that takes files, in board order, with where its files go.
///
/// # Errors
///
/// A device that takes files whose driver lemnos-ctl does not know a place for.
pub fn pushed(board: &BoardFile, drivers: &[Manifest]) -> Result<Vec<Pushed>, String> {
    let mut out = Vec::new();
    for device in board.devices.iter().filter(|d| !d.disabled) {
        let Some(manifest) = drivers.iter().find(|m| m.name == device.driver) else {
            continue;
        };
        let takes = lemnos_wire::text::takes_files(|name| {
            manifest
                .provides
                .iter()
                .any(|contract| contract.methods.iter().any(|method| method.name == name))
        });
        if !takes {
            continue;
        }
        let id = &device.id;
        let (dir, streams) = match device.driver.as_str() {
            "system-slots" => {
                let data =
                    match device.config.get("data") {
                        None => None,
                        Some(value) => Some(value.as_str().ok_or_else(|| {
                            format!("device {id:?}: `data` is a path, as a string")
                        })?),
                    };
                let dir = lemnos_driver_system_slots::pushed_files_dir(data);
                (dir.display().to_string(), Vec::new())
            }
            "system-flash" => (
                lemnos_driver_system_flash::PUSHED_FILES_DIR.to_owned(),
                lemnos_driver_system_flash::PUSHED_STREAMS
                    .iter()
                    .map(|name| (*name).to_owned())
                    .collect(),
            ),
            driver => {
                return Err(format!(
                    "device {id:?}: its driver {driver:?} takes files, and lemnos-ctl does not know where they go: the driver must say so here (service/ctl/src/bridge_env.rs)"
                ));
            }
        };
        out.push(Pushed {
            device: id.clone(),
            dir,
            streams,
        });
    }
    Ok(out)
}

/// The link name of a gadget device: the name on the first interface of its composition.
fn link_of(device: &DeviceSpec) -> Result<String, String> {
    let id = &device.id;
    let given = device.config.get("interfaces");
    let file = device.config.get("interfaces_file");
    let from_file;
    let interfaces = match (given, file) {
        (Some(_), Some(_)) => {
            return Err(format!(
                "device {id:?}: `interfaces` and `interfaces_file` are both given"
            ));
        }
        (Some(text), None) => text
            .as_str()
            .ok_or_else(|| format!("device {id:?}: `interfaces` is a string"))?,
        (None, Some(path)) => {
            let path = path.as_str().ok_or_else(|| {
                format!("device {id:?}: `interfaces_file` is a path, as a string")
            })?;
            from_file = std::fs::read_to_string(path)
                .map_err(|error| format!("device {id:?}: interfaces_file {path}: {error}"))?;
            &from_file
        }
        (None, None) => DEFAULT_INTERFACES,
    };
    match link_name(interfaces) {
        Ok(Some(name)) => Ok(name.to_owned()),
        Ok(None) => Err(format!(
            "device {id:?}: the first interface of `interfaces` has no name, and the comm core knows the link by its name: give it one"
        )),
        Err(Fault::LinkNotFirst) => Err(format!(
            "device {id:?}: the first interface of `interfaces` is not the vendor-class link (class 0xff)"
        )),
        Err(other) => Err(format!("device {id:?}: `interfaces`: {other:?}")),
    }
}
