//! `lemnos-ctl tree BOARD --bridge-env FILE`: the setting that makes the bridge offer the USB link,
//! written from the board file so that an image cannot forget it.
//!
//! The bridge (`lemnos-orion`) offers a gadget's bulk pair to the comm core as a link only when
//! `LEMNOS_ORION_LINKS` names it as `<device id>=<link name>`. The device is the board file's
//! usb-gadget device, and the link name is the composition's own: the name on the first
//! `interface` line of the gadget's `interfaces` (the managed default's is `orion-link`), the
//! string the host reads from the link's interface. The comm core has to know a USB link by that
//! same name; that is its configuration, not written here.

use std::fmt::Write as _;

use lemnos_driver_usb_gadget::DEFAULT_INTERFACES;
use lemnos_driver_usb_gadget::description::{Fault, link_name};
use lemnos_host::board::{BoardFile, DeviceSpec};

/// The driver a gadget device names in the board file.
const DRIVER: &str = "usb-gadget";
/// The environment variable the bridge reads.
pub const VARIABLE: &str = "LEMNOS_ORION_LINKS";

/// The first words of the file, so a reader knows where it came from.
pub const HEADER: &str =
    "# Generated by lemnos-ctl tree --bridge-env from the board file. Do not edit.\n";

/// The text of the file for `board`: the `LEMNOS_ORION_LINKS` line for its gadget devices (each
/// `<device id>=<link name>`, comma-separated), or a comment saying there is none.
///
/// # Errors
///
/// A gadget whose `interfaces` do not parse or do not put the link first, whose first interface
/// has no name, or whose `interfaces_file` cannot be read.
pub fn text(board: &BoardFile) -> Result<String, String> {
    let mut entries = Vec::new();
    for device in board
        .devices
        .iter()
        .filter(|d| d.driver == DRIVER && !d.disabled)
    {
        let name = link_of(device)?;
        entries.push(format!("{}={name}", device.id));
    }
    let mut out = String::from(HEADER);
    if entries.is_empty() {
        out.push_str(
            "# This board has no usb-gadget device, so no USB link is offered and the bridge has\n\
             # nothing to set.\n",
        );
    } else {
        out.push_str(
            "# The bridge offers each gadget's bulk endpoints to the comm core as the link named\n\
             # after the `=`. The comm core must know a USB link by the same name.\n",
        );
        let _ = writeln!(out, "{VARIABLE}={}", entries.join(","));
    }
    Ok(out)
}

/// The link name of a gadget device: the name on the first interface of its composition.
fn link_of(device: &DeviceSpec) -> Result<String, String> {
    let id = &device.id;
    let given = device.config.get("interfaces");
    let file = device.config.get("interfaces_file");
    let from_file;
    let interfaces = match (given, file) {
        (Some(_), Some(_)) => {
            return Err(format!(
                "device {id:?}: `interfaces` and `interfaces_file` are both given"
            ));
        }
        (Some(text), None) => text
            .as_str()
            .ok_or_else(|| format!("device {id:?}: `interfaces` is a string"))?,
        (None, Some(path)) => {
            let path = path.as_str().ok_or_else(|| {
                format!("device {id:?}: `interfaces_file` is a path, as a string")
            })?;
            from_file = std::fs::read_to_string(path)
                .map_err(|error| format!("device {id:?}: interfaces_file {path}: {error}"))?;
            &from_file
        }
        (None, None) => DEFAULT_INTERFACES,
    };
    match link_name(interfaces) {
        Ok(Some(name)) => Ok(name.to_owned()),
        Ok(None) => Err(format!(
            "device {id:?}: the first interface of `interfaces` has no name, and the comm core knows the link by its name: give it one"
        )),
        Err(Fault::LinkNotFirst) => Err(format!(
            "device {id:?}: the first interface of `interfaces` is not the vendor-class link (class 0xff)"
        )),
        Err(other) => Err(format!("device {id:?}: `interfaces`: {other:?}")),
    }
}
