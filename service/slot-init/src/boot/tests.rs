struct Root(PathBuf);

impl Drop for Root {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}

fn hash(id: &str) -> String {
    let digit = id.chars().last().unwrap();
    std::iter::repeat_n(digit, 64).collect()
}

/// The boot partition's bays: small, so an image builds in microseconds. Each payload file of a set
/// is pre-created at its bay size, and a slot's stored bytes are less than or equal to it.
fn test_bays() -> bay::Layout {
    bay::Layout::new([8192, 4096, 4096, 4096, 4096]).unwrap()
}

/// The Pi firmware's parts: the firmware text stand-ins and the layout copy at the root, the extra
/// root files the test names, and three bay sets.
fn tryboot_parts(extra: Vec<(&'static str, Vec<u8>)>) -> Parts {
    let mut root = vec![
        ("config.txt", b"kernel_watchdog_timeout=15\n".to_vec()),
        ("tryboot.txt", b"# Generated by lemnos-ctl test\n".to_vec()),
        ("slot-layout.toml", b"version = 5\n".to_vec()),
    ];
    root.extend(extra);
    Parts {
        family: Family::Tryboot,
        layout: test_bays(),
        root,
        fixed: Vec::new(),
    }
}

/// The U-Boot form's parts: the locator the environment is found by at the root, and no pointers.
fn uboot_parts(locator: &str) -> Parts {
    Parts {
        family: Family::UbootBlock,
        layout: test_bays(),
        root: vec![
            (uboot_env::LOCATOR, locator.as_bytes().to_vec()),
            ("slot-layout.toml", b"version = 5\n".to_vec()),
        ],
        // The composed extlinux file's bay, as the real builder declares it (padded, then written).
        fixed: vec![lemnos_slot_store::bootimage::Fixed {
            path: lemnos_slot_store::bootimage::EXTLINUX,
            bytes: Vec::new(),
            size: lemnos_slot_store::bootimage::EXTLINUX_BYTES,
        }],
    }
}

/// A slot's five payloads in the roles' order. The command line names the slot and its root hash, so
/// the manifest's hash of the command line is the hash of these bytes.
fn payloads(id: &str) -> [Vec<u8>; 5] {
    [
        format!("kernel {id}\n").repeat(400).into_bytes(),
        format!("initramfs {id}\n").into_bytes(),
        format!("device tree {id}\n").repeat(16).into_bytes(),
        format!(
            "console=tty1 rootwait os.slot={id} os.roothash={} os.src./soc/mmc@7e202000=/soc/mmc@7e202000 panic=5\n",
            hash(id)
        )
        .into_bytes(),
        format!("overlay {id}\n").into_bytes(),
    ]
}

/// The manifest's `boot.files` object for `id`: each bay file's name (its role's path) and the hash of its
/// payload, the bytes the bay holds before its padding.
fn boot_manifest_files(id: &str) -> String {
    let p = payloads(id);
    let pairs: Vec<String> = bay::ROLES
        .iter()
        .enumerate()
        .map(|(i, r)| format!("\"{}\":\"{}\"", r.path, sha256_hex(&p[i])))
        .collect();
    format!("{{\"files\":{{{}}}}}", pairs.join(","))
}

fn refs(p: &[Vec<u8>; 5]) -> [&[u8]; 5] {
    std::array::from_fn(|i| p[i].as_slice())
}

/// The Pi firmware's image: `os-1` installed in bay 0, which the pointers name. Built by the image
/// builder, the same code `lemnos-ctl boot-partition` runs.
fn tryboot_image(extra: Vec<(&'static str, Vec<u8>)>) -> Vec<u8> {
    let parts = tryboot_parts(extra);
    let size = bootimage::min_size(&parts).unwrap();
    bootimage::build(&parts, size, "os-1", &refs(&payloads("os-1"))).unwrap()
}

/// The U-Boot form's image: `os-1` in bay 0 with its composed extlinux file, and the locator.
fn uboot_image(locator: &str) -> Vec<u8> {
    let parts = uboot_parts(locator);
    let size = bootimage::min_size(&parts).unwrap();
    bootimage::build(&parts, size, "os-1", &refs(&payloads("os-1"))).unwrap()
}

/// What the fake was asked, and which calls it refuses (by prefix).
struct Fake {
    root: PathBuf,
    calls: RefCell<Vec<String>>,
    logs: RefCell<Vec<String>>,
    refuse: Vec<&'static str>,
    /// On a NAND board, the UBI device.
    nand: Option<ubi::Fake>,
    /// The device-mapper targets the kernel has; `None` when there is no control node.
    dm: Option<Vec<String>>,
    /// The next U-Boot environment write keeps this many bytes and fails, as a power cut does.
    cut: Cell<Option<usize>>,
}

/// A U-Boot environment device on a file: the first write is cut after the bytes `cut` allows.
struct CutEnv {
    inner: FileEnv,
    cut: Option<usize>,
}

impl EnvDev for CutEnv {
    fn read_at(&mut self, offset: u64, buf: &mut [u8]) -> io::Result<()> {
        self.inner.read_at(offset, buf)
    }

    fn write_at(&mut self, offset: u64, bytes: &[u8]) -> io::Result<()> {
        match self.cut.take() {
            Some(keep) if keep < bytes.len() => {
                if keep > 0 {
                    self.inner.write_at(offset, &bytes[..keep])?;
                }
                Err(io::Error::other("power cut"))
            }
            _ => self.inner.write_at(offset, bytes),
        }
    }
}

impl Fake {
    fn short(&self, path: &Path) -> String {
        path.strip_prefix(&self.root)
            .map_or_else(|_| path.display().to_string(), |p| p.display().to_string())
    }

    fn call(&self, text: String) -> Result<(), String> {
        let refused = self.refuse.iter().any(|r| text.starts_with(r));
        self.calls.borrow_mut().push(text);
        if refused {
            Err("refused by the test".into())
        } else {
            Ok(())
        }
    }

    fn calls(&self) -> Vec<String> {
        self.calls.borrow().clone()
    }

    fn called(&self, prefix: &str) -> bool {
        self.calls.borrow().iter().any(|c| c.starts_with(prefix))
    }

    fn last(&self) -> String {
        self.calls.borrow().last().cloned().unwrap_or_default()
    }
}

impl Ops for Fake {
    fn log(&self, line: &str) {
        self.logs.borrow_mut().push(line.to_string());
    }

    fn mount(&self, fstype: &str, opts: &str, source: &Path, target: &Path) -> Result<(), String> {
        self.call(format!(
            "mount {fstype} {opts} {} {}",
            self.short(source),
            self.short(target)
        ))
    }

    fn move_mount(&self, source: &Path, target: &Path) -> Result<(), String> {
        self.call(format!(
            "move {} {}",
            self.short(source),
            self.short(target)
        ))
    }

    fn umount(&self, target: &Path) {
        let _ = self.call(format!("umount {}", self.short(target)));
    }

    fn dm_targets(&self) -> Result<Vec<String>, String> {
        self.call("dm_targets".into())?;
        self.dm.clone().ok_or_else(|| "no control node".into())
    }

    fn open_verity(&self, image: &Path, name: &str, verity: &Verity) -> Result<String, String> {
        self.call(format!(
            "verity {} {name} {}",
            self.short(image),
            verity.table("loop")
        ))
        .map(|()| "/dev/dm-0".to_string())
    }

    fn ubi_block(&self, ubi: &Ubi, name: &str) -> Result<PathBuf, String> {
        self.call(format!("ubiblock {} {name}", ubi.device))?;
        let device = self.nand.as_ref().ok_or("no UBI device")?;
        device.block(name).map_err(|e| e.to_string())
    }

    fn ubi_replace(&self, ubi: &Ubi, name: &str, bytes: &[u8]) -> Result<(), String> {
        self.call(format!("ubi replace {name}"))?;
        let device = self.nand.as_ref().ok_or("no UBI device")?;
        ubi::replace(ubi, device, name, bytes).map_err(|e| e.to_string())
    }

    fn kernel_log(&self) -> String {
        "the kernel's log\n".into()
    }

    fn sync(&self) {}

    fn restart(&self, argument: Option<&str>) {
        let _ = self.call(match argument {
            Some(argument) => format!("restart {argument}"),
            None => "restart".into(),
        });
    }

    fn switch_root(&self, new_root: &Path) -> Result<(), String> {
        self.call(format!("switch_root {}", self.short(new_root)))
    }

    fn sleep(&self, time: Duration) {
        if time >= Duration::from_secs(1) {
            let _ = self.call(format!("sleep {}", time.as_secs()));
        }
    }

    fn request_flash_mode(&self) -> Result<(), String> {
        self.call("flash mode".into())
    }

    /// The environment partition is a plain file here; its next write may be cut.
    fn open_uboot_env(&self, node: &Path) -> Result<(Box<dyn EnvDev>, u64), String> {
        let (inner, bytes) =
            FileEnv::open_sized(node).map_err(|error| format!("{}: {error}", node.display()))?;
        let cut = CutEnv {
            inner,
            cut: self.cut.take(),
        };
        Ok((Box::new(cut), bytes))
    }
}

/// A board: one disk with a boot partition and a data partition (PARTUUID `1234abcd-02`,
/// labelled `lemnos-data`), slots `os-1` (previous) and `os-2` (default), booting `os-2`.
struct Board {
    _dir: Root,
    env: Env,
    layout: Layout,
    /// On raw NAND: the UBI device's description.
    nand: Option<Ubi>,
    /// The device-mapper targets the kernel has (`None`: no control node).
    dm_targets: Option<Vec<String>>,
    /// The U-Boot form: no pointers or records on the boot partition, the environment names the default.
    uboot: bool,
}

impl Board {
    /// The boot partition's image file: the node the board reads and writes raw.
    fn node(&self) -> PathBuf {
        self.env.at("dev/mmcblk0p1")
    }

    /// The slot a pointer names, read raw from the image's record of its bay; `None` when it is torn.
    fn pointer(&self, which: Pointer) -> Option<String> {
        Boot::open(&self.node()).ok()?.pointer(which).ok().flatten()
    }

    fn set_pointer(&self, which: Pointer, slot: &str) {
        Boot::open(&self.node())
            .unwrap()
            .set_pointer(which, slot)
            .unwrap();
    }

    /// The pending trial, as the raw record holds it.
    fn trial(&self) -> Option<(String, u8)> {
        let trial = Boot::open(&self.node()).ok()?.trial().ok()??;
        Some((trial.slot, trial.attempts))
    }

    fn set_trial(&self, slot: &str, attempts: u8) {
        Boot::open(&self.node())
            .unwrap()
            .set_trial(slot, attempts)
            .unwrap();
    }

    /// Installs `id`'s payloads into a bay, unless a bay already holds the slot. The Pi form goes
    /// through [`Boot`], the U-Boot form (no pointers, no records) through [`BayVolume`]; both write
    /// the composed bay the image builder writes.
    fn install_bay(&self, id: &str) {
        let node = self.node();
        let p = payloads(id);
        let r = refs(&p);
        if self.uboot {
            let mut volume = BayVolume::open(&node).unwrap();
            if volume.slot_bay(id).is_err() {
                let text = bootimage::extlinux_text(&p[3]).unwrap();
                let mut protected = self.uboot_protected(&mut volume);
                // The environment names no default until the board is assembled: the slots already
                // installed are the ones it would name (first the default, then the previous).
                let named = protected.clone();
                let mut held = ["os-1", "os-2", "os-3"]
                    .into_iter()
                    .filter(|other| *other != id)
                    .filter_map(|other| volume.slot_bay(other).ok())
                    .filter_map(|(dir, _)| dir.rsplit('/').next().and_then(bay::set_of))
                    .filter(|set| !named.names(*set));
                if protected.default.is_none() {
                    protected.default = held.next();
                }
                if protected.previous.is_none() {
                    protected.previous = held.next();
                }
                volume
                    .install_slot_with(id, &r, Some(&text), &protected)
                    .unwrap();
            }
        } else {
            let mut boot = Boot::open(&node).unwrap();
            if boot.slot_bay(id).is_err() {
                boot.install_slot(id, &r).unwrap();
            }
        }
    }

    /// The U-Boot environment's protected bays, as slot-init reads the environment: the default's bay
    /// and the trial's bay (found through the volume's records), and a trial with attempts left.
    fn uboot_protected(&self, volume: &mut BayVolume) -> lemnos_slot_store::bays::Protected {
        // No environment partition yet (a board's slots are installed before its environment is written):
        // nothing is protected by it.
        let node = self.env.dev.join("mmcblk0");
        let vars: Vec<(String, String)> = (|| {
            let (mut dev, bytes) = FileEnv::open_sized(&node).ok()?;
            let geometry = Place::gpt(1024).ok()?.geometry(&mut dev, bytes).ok()?;
            let (_, vars) = uboot_env::load(&mut dev, &geometry).ok()??;
            Some(vars)
        })()
        .unwrap_or_default();
        let get = |name: &str| {
            vars.iter()
                .find(|(n, _)| n == name)
                .map(|(_, v)| v.clone())
                .filter(|v| !v.is_empty())
        };
        let bay = |slot: Option<String>, volume: &mut BayVolume| {
            slot.and_then(|s| volume.slot_bay(&s).ok())
                .and_then(|(dir, _)| {
                    dir.rsplit('/')
                        .next()
                        .and_then(lemnos_slot_store::bays::set_of)
                })
        };
        let trial = get("trial");
        let attempts: u8 = get("trial_attempts")
            .and_then(|a| a.parse().ok())
            .unwrap_or(0);
        lemnos_slot_store::bays::Protected {
            default: bay(get("default"), volume),
            previous: get("previous_bay").and_then(|b| bay::set_of(&b)),
            trial: bay(trial.clone(), volume),
            pending: trial
                .filter(|_| attempts > 0)
                .map(|slot| lemnos_slot_store::boot_raw::Trial { slot, attempts }),
        }
    }

    /// Frees the bay of `id` by its record alone: the bay's files stay on the image.
    fn free_bay(&self, id: &str) {
        Boot::open(&self.node()).unwrap().free_slot(id).unwrap();
    }

    /// Writes `bytes` (at most one sector) over the start of a payload file of `id`'s bay, in place. The
    /// bay's record keeps the stored length and hash, so the file no longer matches what was installed.
    fn edit_bay_file(&self, id: &str, file: &str, bytes: &[u8]) {
        assert!(bytes.len() <= 512, "one sector");
        let (dir, _) = if self.uboot {
            BayVolume::open(&self.node()).unwrap().slot_bay(id).unwrap()
        } else {
            Boot::open(&self.node()).unwrap().slot_bay(id).unwrap()
        };
        let handle = OpenOptions::new()
            .read(true)
            .write(true)
            .open(self.node())
            .unwrap();
        let mut dev = FileSectors::new(handle, 0);
        let found = bootfat::locate_path(&mut dev, &format!("{dir}/{file}"), 4096).unwrap();
        let mut sector = [0u8; 512];
        sector[..bytes.len()].copy_from_slice(bytes);
        dev.write(found.first_lba, &sector).unwrap();
    }

    /// Garbage over both copies of the trial record, so it reads as no record.
    fn tear_trial_record(&self) {
        let handle = OpenOptions::new()
            .read(true)
            .write(true)
            .open(self.node())
            .unwrap();
        let mut dev = FileSectors::new(handle, 0);
        let records = Records::place_named(&mut dev).unwrap();
        let (trial, _) = records.lbas();
        let sector = [0xA5u8; 512];
        dev.write(trial, &sector).unwrap();
        dev.write(trial + 1, &sector).unwrap();
    }

    /// A root file of the boot partition, read through the FAT volume (`None` when it is not there).
    fn boot_file(&self, name: &str) -> Option<String> {
        let mut handle = fs::File::open(self.node()).unwrap();
        bootcheck::fat_read(&mut handle, name)
            .unwrap()
            .map(|bytes| String::from_utf8(bytes).unwrap())
    }

    /// The Pi form's board with `os-1` (previous) and `os-2` (default). Both slots are in bays, the
    /// pointers name them, and the data partition's state says the same.
    fn new() -> Self {
        Self::with_root(Vec::new())
    }

    /// As [`Board::new`], with extra files at the root of the boot partition (the forms the image
    /// does not produce, which a test asserts are refused).
    fn with_root(extra: Vec<(&'static str, Vec<u8>)>) -> Self {
        let board = Self::fresh(tryboot_image(extra), false);
        board.slot("os-1", 1);
        board.slot("os-2", 2);
        board.set_pointer(Pointer::Default, "os-2");
        board
    }

    /// The board around a boot partition image: its devices, the data partition, the command line and
    /// the data partition's state. The slots and pointers are the caller's.
    fn fresh(boot_image: Vec<u8>, uboot: bool) -> Self {
        static NEXT: AtomicU32 = AtomicU32::new(0);
        let root = std::env::temp_dir().join(format!(
            "lemnos-slot-init-{}-{}",
            std::process::id(),
            NEXT.fetch_add(1, Ordering::Relaxed)
        ));
        let _ = fs::remove_dir_all(&root);
        let env = Env {
            root: root.clone(),
            sys: root.join("sys"),
            dev: root.join("dev"),
            wait: Duration::from_millis(100),
            rescue_wait: Duration::from_secs(30),
        };
        let board = Self {
            _dir: Root(root.clone()),
            layout: Layout::new(root.join("data"), root.join("boot")),
            env,
            nand: None,
            dm_targets: Some(vec!["verity".into()]),
            uboot,
        };
        // A kernel with every piece of the chain built in.
        board.kernel(&["ext4", "vfat", "erofs"]);
        fs::create_dir_all(board.env.dev.clone()).unwrap();
        let mut mbr = vec![0u8; 512];
        mbr[440..444].copy_from_slice(&0x1234_abcdu32.to_le_bytes());
        mbr[450] = 0x0c;
        mbr[510..512].copy_from_slice(&[0x55, 0xaa]);
        board.write("dev/mmcblk0", &mbr);
        board.write("dev/mmcblk0p1", &boot_image);
        // The disk sits under the SD controller, whose device-tree node is `/soc/mmc@7e202000`; the
        // chain states U-Boot's path of the controller (here the kernel's own path), which the
        // command line's table maps to that controller.
        board.write("sys/firmware/devicetree/base/soc/mmc@7e202000/.keep", b"");
        board.write(
            "proc/device-tree/chosen/lemnos,boot-source",
            b"/soc/mmc@7e202000\0",
        );
        let controller = root.join("sys/devices/sd-host");
        fs::create_dir_all(&controller).unwrap();
        std::os::unix::fs::symlink(
            root.join("sys/firmware/devicetree/base/soc/mmc@7e202000"),
            controller.join("of_node"),
        )
        .unwrap();
        board.write("dev/mmcblk0p2", &ext("lemnos-data", false));
        fs::create_dir_all(root.join("sys/class/block")).unwrap();
        std::os::unix::fs::symlink(
            "../../devices/sd-host/mmcblk0",
            root.join("sys/class/block/mmcblk0"),
        )
        .unwrap();
        for n in 1..=2 {
            let name = format!("mmcblk0p{n}");
            board.write(
                &format!("sys/devices/sd-host/mmcblk0/{name}/partition"),
                format!("{n}\n").as_bytes(),
            );
            std::os::unix::fs::symlink(
                format!("../../devices/sd-host/mmcblk0/{name}"),
                root.join("sys/class/block").join(&name),
            )
            .unwrap();
        }
        board.cmdline("os-2", &hash("os-2"));
        board.write("proc/sys/kernel/osrelease", b"6.12.0-board\n");
        board.write(
            "data/board/slots/state.env",
            b"DEFAULT=os-2\nPREVIOUS=os-1\nSTATE=confirmed\n",
        );
        board
    }

    /// The kernel's proc files: the filesystems named, and every other piece present.
    fn kernel(&self, filesystems: &[&str]) {
        let mut text = String::from("nodev\tsysfs\n");
        for fs in filesystems {
            text.push_str(&format!("\t{fs}\n"));
        }
        self.write("proc/filesystems", text.as_bytes());
        self.write("proc/misc", b"235 hwrng\n236 device-mapper\n");
        self.write(
            "proc/devices",
            b"Character devices:\n  1 mem\nBlock devices:\n  7 loop\n",
        );
        self.write(
            "proc/crypto",
            b"name         : sha256\ndriver       : sha256-generic\n",
        );
    }

    fn write(&self, path: &str, bytes: &[u8]) {
        let path = self.env.at(path);
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(path, bytes).unwrap();
    }

    /// The kept reason, read raw from the image's reason record.
    fn reason(&self) -> String {
        lemnos_slot_store::boot_raw::open_records(&self.node())
            .unwrap()
            .reason()
            .unwrap()
            .unwrap_or_default()
    }

    fn read(&self, path: &str) -> String {
        fs::read_to_string(self.env.at(path)).unwrap_or_default()
    }

    fn cmdline(&self, slot: &str, roothash: &str) {
        self.write(
            "proc/cmdline",
            format!("console=tty1 rootwait os.slot={slot} os.roothash={roothash} os.src./soc/mmc@7e202000=/soc/mmc@7e202000 panic=5\n")
                .as_bytes(),
        );
    }

    /// An installed slot: manifest, image, record, and boot directory.
    fn slot(&self, id: &str, seq: u64) {
        // The bay first: the manifest's hash is of the bytes the bay holds.
        self.install_bay(id);
        self.manifest(id, id, "");
        let size = BLOCK + tree_bytes(1);
        assert_eq!(tree_bytes(1), 0, "one data block has no tree");
        self.write(&format!("data/slots/{id}.erofs"), &vec![0u8; size as usize]);
        self.write(
            &format!("data/board/slots/{id}.meta"),
            format!("GOOD=yes\nSEQ={seq}\n").as_bytes(),
        );
    }

    fn manifest(&self, file: &str, id: &str, extra: &str) {
        let sha = hash("x0");
        // Every bay file is hashed as its payload (the stored bytes, unpadded), as the bundle does.
        let boot = boot_manifest_files(id);
        let text = format!(
            "{{\"schema\":3,\"id\":\"{id}\",\"product\":\"an-os\",\"version\":\"2.0\",\"board\":\"board-a\",{extra}\
             \"image\":{{\"size\":{},\"sha256\":\"{sha}\"}},\
             \"verity\":{{\"root_hash\":\"{}\",\"salt\":\"{sha}\",\"data_blocks\":1,\"hash_offset\":{BLOCK}}},\
             \"boot\":{boot}}}",
            BLOCK + tree_bytes(1),
            hash(id),
        );
        self.write(&format!("data/slots/{file}.json"), text.as_bytes());
    }

    fn remove_slot(&self, id: &str) {
        fs::remove_file(self.env.at(&format!("data/slots/{id}.json"))).unwrap();
        fs::remove_file(self.env.at(&format!("data/slots/{id}.erofs"))).unwrap();
    }

    fn boot(&self, refuse: &[&'static str]) -> (Fake, String) {
        self.boot_cut(refuse, None)
    }

    /// As [`Board::boot`], with the U-Boot environment's first write cut after `cut` bytes.
    fn boot_cut(&self, refuse: &[&'static str], cut: Option<usize>) -> (Fake, String) {
        let fake = Fake {
            root: self.env.root.clone(),
            calls: RefCell::new(Vec::new()),
            logs: RefCell::new(Vec::new()),
            refuse: refuse.to_vec(),
            nand: self.nand.clone().map(|ubi| ubi::Fake {
                ubi,
                refuse: std::sync::Mutex::new(Vec::new()),
            }),
            dm: self.dm_targets.clone(),
            cut: Cell::new(cut),
        };
        let why = boot(&fake, &self.env);
        (fake, why)
    }

    /// The same board with its record in U-Boot's environment: the boot partition holds
    /// `uboot-env.txt` (`locator`), and the environment partition, `device` bytes long, is at
    /// `/dev/disk/by-partuuid/<UBOOT_UUID>`. Both copies hold `default=os-2` (copy one active).
    fn uboot(locator: &str, blocks: u64) -> Self {
        // The image with both slots installed is built once per locator and thread (the cut sweep
        // makes thousands of boards): a later board starts from those bytes, and `slot` then finds
        // each bay already holding its slot.
        thread_local! {
            static ASSEMBLED: RefCell<Vec<(String, Vec<u8>)>> = const { RefCell::new(Vec::new()) };
        }
        let cached = ASSEMBLED.with(|c| {
            c.borrow()
                .iter()
                .find(|(l, _)| l == locator)
                .map(|(_, image)| image.clone())
        });
        let board = Self::fresh(cached.clone().unwrap_or_else(|| uboot_image(locator)), true);
        board.slot("os-1", 1);
        board.slot("os-2", 2);
        if cached.is_none() {
            let image = fs::read(board.node()).unwrap();
            ASSEMBLED.with(|c| c.borrow_mut().push((locator.to_string(), image)));
        }
        board.write(
            "dev/mmcblk0",
            &Self::gpt_disk(&[(ENV_TYPE_BYTES, 64, 63 + blocks)]),
        );
        board
    }

    /// A GPT disk with `parts`, the MBR's disk signature and boot marker kept; each environment
    /// partition holds the two copies at its top (see [`Board::uboot`]).
    fn gpt_disk(parts: &[([u8; 16], u64, u64)]) -> Vec<u8> {
        let end = parts.iter().map(|p| p.2).max().unwrap() + 34;
        let mut image = gpt::image(parts, end);
        image[440..444].copy_from_slice(&0x1234_abcdu32.to_le_bytes());
        image[510..512].copy_from_slice(&[0x55, 0xaa]);
        for (kind, first, last) in parts {
            if *kind != ENV_TYPE_BYTES {
                continue;
            }
            if let Ok(g) = Geometry::in_partition(1024, *first, last - first + 1) {
                for (at, serial) in [(g.offset, 6), (g.offset_redund, 5)] {
                    let at = at as usize;
                    image[at..at + 1024].copy_from_slice(&env_copy(&[("default", "os-2")], serial));
                }
            }
        }
        image
    }

    /// The raw disk bytes, for a check that nothing was written.
    fn uboot_vars_raw(&self) -> Vec<u8> {
        fs::read(self.env.dev.join("mmcblk0")).unwrap()
    }

    /// The environment's variables as U-Boot's rule reads them, sorted.
    fn uboot_vars(&self) -> Vec<(String, String)> {
        let node = self.env.dev.join("mmcblk0");
        let (mut dev, bytes) = FileEnv::open_sized(&node).unwrap();
        let geometry = Place::gpt(1024).unwrap().geometry(&mut dev, bytes).unwrap();
        let (_, mut vars) = uboot_env::load(&mut dev, &geometry)
            .unwrap()
            .expect("an environment");
        vars.sort();
        vars
    }

    /// The same board on raw NAND: the data and boot directories are UBIFS volumes (here plain
    /// directories), the images static volumes, and the record the volume `boot-record`.
    fn nand() -> Self {
        let mut board = Self::new();
        let ubi = Ubi {
            sys: board.env.sys.clone(),
            dev: board.env.dev.clone(),
            device: "ubi0".into(),
        };
        let device = ubi::Fake::new(ubi.clone(), 64 << 20);
        device.put("data", b"");
        device.put("boot", b"");
        for id in ["os-1", "os-2"] {
            let file = board.env.at(&format!("data/slots/{id}.erofs"));
            device.put(&ubi::image_volume(id), &fs::read(&file).unwrap());
            fs::remove_file(file).unwrap();
        }
        board.kernel(&["ubifs", "erofs"]);
        device.put(
            ubi::RECORD_VOLUME,
            b"default=os-2\ntrial=\ntrial_attempts=0\n",
        );
        // NAND keeps each slot's boot files under `slots/<id>` (the stopgap until the UBI bay form,
        // requirements section 10.1): plain files here, the same bytes as the bay's command line.
        for id in ["os-1", "os-2"] {
            let p = payloads(id);
            for (i, r) in bay::ROLES.iter().enumerate() {
                board.write(&format!("boot/slots/{id}/{}", r.path), &p[i]);
            }
        }
        board.write(
            "proc/cmdline",
            format!("os.slot=os-2 os.roothash={}", hash("os-2")).as_bytes(),
        );
        board.layout.ubi = Some(ubi.clone());
        board.nand = Some(ubi);
        board
    }

    fn record_volume(&self) -> String {
        String::from_utf8(
            self.layout
                .ubi
                .as_ref()
                .unwrap()
                .read(ubi::RECORD_VOLUME)
                .unwrap(),
        )
        .unwrap()
    }

    fn meta(&self, id: &str) -> Meta {
        Meta::load(&self.layout, id)
    }

    fn state(&self) -> State {
        State::load(&self.layout)
    }

    /// The board's default is untouched: slot-init never writes it.
    fn default_kept(&self) {
        assert_eq!(self.pointer(Pointer::Default).as_deref(), Some("os-2"));
        assert_eq!(self.state().default, "os-2");
    }
}

/// An ext4 superblock's first 2 KiB: its label, and whether it records errors.
fn ext(label: &str, errors: bool) -> Vec<u8> {
    let mut head = vec![0u8; 2048];
    head[1024 + 56..1024 + 58].copy_from_slice(&0xef53u16.to_le_bytes());
    head[1024 + 58] = if errors { 2 } else { 1 };
    head[1024 + 120..1024 + 120 + label.len()].copy_from_slice(label.as_bytes());
    head
}

