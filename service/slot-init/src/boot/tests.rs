/// What `boot.cmd`'s third step hands on when it started the previous slot because the default's
/// files could not be started: a property of `/chosen` in the device tree.
fn loader_fallback(board: &Board, value: &str) {
    board.write(crate::boot::DEFAULT_FAILED, format!("{value}\0").as_bytes());
}

/// The boot loader started the previous slot as its fallback (U-Boot form): the previous boots as a
/// trial the daemon judges, the default is marked failed with the loader's reason, and nothing is
/// written to the boot record or the environment.
#[test]
fn started_on_previous_as_the_loaders_fallback_it_is_a_trial_and_the_default_is_marked() {
    let board = Board::uboot(&uboot_locator(), 64);
    board.cmdline("os-1", &hash("os-1"));
    loader_fallback(&board, "files");
    let before = board.uboot_vars_raw();
    let (fake, why) = board.boot(&[]);
    assert_eq!(why, "", "{:?}", fake.logs.borrow());
    assert_eq!(fake.last(), "switch_root newroot");
    // The same marks a trial boot carries.
    assert_eq!(board.read("data/board/slots/trial-init"), "os-1\n");
    assert_eq!(
        board.read("newroot/data/board/slots/trial-started"),
        "os-1\n"
    );
    assert_eq!(board.read("newroot/data/board/slots/booted"), "os-1\n");
    // The state's trial is the previous slot, as for any trial, so the daemon confirms it (it then
    // becomes the default); until then the default is unchanged.
    let state = board.state();
    assert_eq!(state.trial, "os-1");
    assert_eq!(state.default, "os-2");
    assert_eq!(
        state.error,
        "slot os-2 can't start: the boot loader could not load the default's files"
    );
    // The default is marked failed, once, with the reason.
    let meta = board.meta("os-2");
    assert_eq!(meta.get("FAILED"), "yes");
    assert_eq!(meta.get("FAILURES"), "1");
    assert_eq!(
        meta.get("FAIL_REASON"),
        "the boot loader could not load the default's files"
    );
    assert_ne!(board.meta("os-1").get("FAILED"), "yes");
    // Nothing was written to the environment.
    assert_eq!(board.uboot_vars_raw(), before);
}

