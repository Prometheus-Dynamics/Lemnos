//! Hardware defaults for the back end blocks, as the BCM2712 back end takes them.
//!
//! Every table here is a fact the hardware needs to pass data through or to run a block with a
//! known-good setting, and is transcribed from the open-source libpisp (BSD-2-Clause, Copyright (C)
//! 2021 - 2023 Raspberry Pi Ltd) at commit `c77865739bbde5be918d5a7692c8a8050e0abc25`:
//!
//! - `src/libpisp/backend/backend_default_config.json`: the colour encodings (`colour_encoding`),
//!   the debin filter (`debin`), the demosaic and false-colour settings (`demosaic`,
//!   `false_colour`), the resampler filters (`resample.filters`, with the downscale thresholds of
//!   `resample.smart_selection`) and the sharpening filters (`sharpen`).
//! - The colour matrices are generated by `utils/colourspace_calcs.py` at the same commit: a 4.10
//!   matrix (`* 1024`) and offsets in units of 2^-18 (`* 2^18`). The test module recomputes them
//!   from the documented BT.601, BT.709 and BT.2020 luma coefficients.
//!
//! The values are copied as numbers. No code or comments from libpisp are used.

