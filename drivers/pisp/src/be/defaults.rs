/// A colour encoding: the RGB to YCbCr matrix and its inverse, as the pipeline runs them.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Encoding {
    /// Full-range BT.601 (JPEG). The libpisp default; full range on the BCM2712 C1.
    Jpeg,
    /// Limited-range BT.601 (SMPTE 170M).
    Smpte170m,
    /// Limited-range BT.709.
    Rec709,
    /// Full-range BT.709.
    Rec709Full,
    /// Limited-range BT.2020.
    Bt2020,
    /// Full-range BT.2020.
    Bt2020Full,
}

impl Encoding {
    /// Every encoding, in the order of the libpisp table.
    pub const ALL: [Encoding; 6] = [
        Encoding::Jpeg,
        Encoding::Smpte170m,
        Encoding::Rec709,
        Encoding::Rec709Full,
        Encoding::Bt2020,
        Encoding::Bt2020Full,
    ];

    /// The RGB to YCbCr matrix (`ycbcr`).
    pub const fn forward(self) -> BeCcmConfig {
        match self {
            Encoding::Jpeg => FWD_JPEG,
            Encoding::Smpte170m => FWD_SMPTE170M,
            Encoding::Rec709 => FWD_REC709,
            Encoding::Rec709Full => FWD_REC709_FULL,
            Encoding::Bt2020 => FWD_BT2020,
            Encoding::Bt2020Full => FWD_BT2020_FULL,
        }
    }

    /// The YCbCr to RGB matrix (`ycbcr_inverse`).
    pub const fn inverse(self) -> BeCcmConfig {
        match self {
            Encoding::Jpeg => INV_JPEG,
            Encoding::Smpte170m => INV_SMPTE170M,
            Encoding::Rec709 => INV_REC709,
            Encoding::Rec709Full => INV_REC709_FULL,
            Encoding::Bt2020 => INV_BT2020,
            Encoding::Bt2020Full => INV_BT2020_FULL,
        }
    }

    /// The libpisp name of the encoding (its key in `colour_encoding`).
    pub const fn name(self) -> &'static str {
        match self {
            Encoding::Jpeg => "jpeg",
            Encoding::Smpte170m => "smpte170m",
            Encoding::Rec709 => "rec709",
            Encoding::Rec709Full => "rec709_full",
            Encoding::Bt2020 => "bt2020",
            Encoding::Bt2020Full => "bt2020_full",
        }
    }
}

