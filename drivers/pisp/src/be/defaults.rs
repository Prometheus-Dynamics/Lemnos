/// The resampler's filters, by name, with the smart-selection thresholds of libpisp's
/// `resample.smart_selection`: the filter for a downscale is the first of these whose threshold
/// is at least the downscale; past the last threshold, the last filter.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ResampleFilter {
    /// `lanczos3`.
    Lanczos3,
    /// `lanczos2`.
    Lanczos2,
    /// `michel-netravali`.
    MichelNetravali,
    /// `bicubic-spline`: not used by the smart selection, available by name.
    BicubicSpline,
}

impl ResampleFilter {
    /// The coefficients (`[phase * 6 + tap]`, s.10).
    pub const fn coefficients(self) -> &'static [i16; BE_RESAMPLE_FILTER_SIZE] {
        match self {
            ResampleFilter::Lanczos3 => &LANCZOS3,
            ResampleFilter::Lanczos2 => &LANCZOS2,
            ResampleFilter::MichelNetravali => &MICHEL_NETRAVALI,
            ResampleFilter::BicubicSpline => &BICUBIC_SPLINE,
        }
    }

    /// The filter the smart selection picks for a downscale factor (`input / output`).
    pub fn for_downscale(downscale: f64) -> Self {
        if downscale <= SELECT_DOWNSCALE[0] {
            ResampleFilter::Lanczos3
        } else if downscale <= SELECT_DOWNSCALE[1] {
            ResampleFilter::Lanczos2
        } else {
            ResampleFilter::MichelNetravali
        }
    }
}

/// The smart-selection thresholds (libpisp `resample.smart_selection.downscale`).
