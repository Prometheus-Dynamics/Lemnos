//! The kernel test needs a configuration this library really builds, so that the module's checks
//! are known to accept what the library makes, and not just what a test wrote by hand. This writes
//! one as a C header and fails if the committed header differs.
//!
//! `LEMNOS_BLESS=1` rewrites the header.

use std::fmt::Write as _;
use std::path::PathBuf;

use lemnos_driver_pisp::be::BackEnd;
use lemnos_driver_pisp::format::{compute_stride_align, formats};
use lemnos_driver_pisp::uapi::{BayerOrder, BeCcmConfig, BeTilesConfig, ImageFormatConfig, Wire};

const WIDTH: u16 = 1280;
const HEIGHT: u16 = 800;
/// Where in the test's registered region the images go.
const OUTPUT_OFFSET: u64 = 2 << 20;

/// A valid RGB-to-YCbCr matrix, standing in for whatever a caller would choose.
const CSC: BeCcmConfig = BeCcmConfig {
    coeffs: [306, 601, 117, -173, -339, 512, 512, -429, -83],
    pad: [0; 2],
    offsets: [0, 33554432, 33554432],
};

fn config() -> BeTilesConfig {
    let mut input = ImageFormatConfig {
        width: WIDTH,
        height: HEIGHT,
        format: formats::BAYER16,
        ..Default::default()
    };
    compute_stride_align(&mut input, 64);
    BackEnd::simple_bayer(
        input,
        BayerOrder::Bggr,
        4096,
        (1.5, 1.0, 1.8),
        None,
        formats::NV12,
        Some(CSC),
    )
    .prepare()
    .expect("a configuration the library accepts")
}

fn header() -> String {
    let cfg = config();
    let mut bytes = vec![0u8; BeTilesConfig::SIZE];
    cfg.write_to(&mut bytes).expect("exactly its size");
    let luma = u64::from(cfg.config.output_format[0].image.stride as u32) * u64::from(HEIGHT);

    let mut out = String::new();
    out.push_str(concat!(
        "/* SPDX-License-Identifier: GPL-2.0 */\n",
        "/*\n",
        " * Generated by drivers/pisp/tests/kernel_fixture.rs: a Bayer-to-NV12 job from the\n",
        " * configuration library, as the non-zero words of struct pisp_be_tiles_config.\n",
        " */\n",
        "#ifndef LEMNOS_PISP_BE_FIXTURE_H\n",
        "#define LEMNOS_PISP_BE_FIXTURE_H\n\n",
        "static const struct { unsigned int at, value; } fixture_words[] = {\n",
    ));
    let (words, _) = bytes.as_chunks::<4>();
    for (i, word) in words.iter().enumerate() {
        let value = u32::from_le_bytes(*word);
        if value != 0 {
            writeln!(out, "\t{{ {}, 0x{value:08x} }},", i * 4).expect("a String");
        }
    }
    out.push_str("};\n\n");
    write!(
        out,
        concat!(
            "static void fixture_fill(struct pisp_be_tiles_config *c, uint64_t *addr,\n",
            "\t\t\t uint64_t pool, uint64_t region)\n",
            "{{\n",
            "\t(void)pool;\n",
            "\tmemset(c, 0, sizeof(*c));\n",
            "\tmemset(addr, 0, sizeof(uint64_t) * LEMNOS_PISP_BE_ADDRS);\n",
            "\tfor (size_t i = 0; i < sizeof(fixture_words) / sizeof(*fixture_words); i++)\n",
            "\t\tmemcpy((char *)c + fixture_words[i].at, &fixture_words[i].value, 4);\n",
            "\taddr[0] = region;\n",
            "\taddr[LEMNOS_PISP_BE_ADDR_OUTPUT(0, 0)] = region + {output};\n",
            "\taddr[LEMNOS_PISP_BE_ADDR_OUTPUT(0, 1)] = region + {chroma};\n",
            "}}\n\n",
            "#endif\n",
        ),
        output = OUTPUT_OFFSET,
        chroma = OUTPUT_OFFSET + luma,
    )
    .expect("a String");
    out
}

#[test]
fn committed_header_is_what_the_library_builds() {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../kernel/test/lemnos_pisp_be_fixture.h");
    let want = header();
    if std::env::var_os("LEMNOS_BLESS").is_some() {
        std::fs::write(&path, &want).expect("the header is writable");
        return;
    }
    let got = std::fs::read_to_string(&path).expect("the header exists");
    assert!(got == want, "rerun with LEMNOS_BLESS=1 to regenerate");
}
