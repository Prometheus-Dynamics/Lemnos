//! The kernel test needs a configuration this library really builds, so that the module's checks
//! are known to accept what the library makes, and not just what a test wrote by hand. This writes
//! one as the guest check's fixture module (`testing/crates/pisp-fe-check/src/fixture.rs`) and
//! fails if the committed module differs.
//!
//! `LEMNOS_BLESS=1` rewrites the module.

use std::fmt::Write as _;
use std::path::PathBuf;

use lemnos_driver_pisp::fe::FrontEnd;
use lemnos_driver_pisp::format::formats;
use lemnos_driver_pisp::uapi::{
    BayerOrder, Branch, FeConfig, ImageFormatConfig, Wire, fe_enable as en,
};

fn config() -> FeConfig {
    let mut fe = FrontEnd::new(64, 4, BayerOrder::Bggr);
    fe.set_output_format(
        Branch::Zero,
        ImageFormatConfig {
            format: formats::BAYER16,
            ..Default::default()
        },
    );
    fe.enable(en::output(0) | en::AWB_STATS, true);
    fe.prepare().expect("a configuration the library accepts")
}

fn module() -> String {
    let mut bytes = vec![0u8; FeConfig::SIZE];
    config().write_to(&mut bytes).expect("exactly its size");
    let mut out = String::from(concat!(
        "//! The fixture the check copies into a configuration slot: one `struct pisp_fe_config` that the\n",
        "//! configuration library builds (a 64x4 job with output 0 and white balance statistics).\n",
        "//!\n",
        "//! Generated by `drivers/pisp/tests/fe_kernel_fixture.rs`, which fails if this file differs from\n",
        "//! what the library builds; `LEMNOS_BLESS=1` rewrites it. The length is the configuration's size\n",
        "//! (the kernel tree's `struct pisp_fe_config`): the array's type enforces it.\n\n",
        "#[rustfmt::skip]\n",
    ));
    writeln!(out, "pub const FIXTURE: [u8; {}] = [", bytes.len()).expect("to a string");
    for line in bytes.chunks(16) {
        out.push_str("   ");
        for b in line {
            write!(out, " 0x{b:02x},").expect("to a string");
        }
        out.push('\n');
    }
    out.push_str("];\n");
    out
}

#[test]
fn the_kernel_tests_fixture_is_what_the_library_builds() {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../testing/crates/pisp-fe-check/src/fixture.rs");
    let want = module();
    if std::env::var_os("LEMNOS_BLESS").is_some() {
        std::fs::write(&path, &want).expect("the fixture can be written");
    }
    let have = std::fs::read_to_string(&path).expect("the committed fixture module");
    assert_eq!(have, want, "run with LEMNOS_BLESS=1 and commit the result");
}
