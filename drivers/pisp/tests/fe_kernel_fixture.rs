//! The kernel test needs a configuration this library really builds, so that the module's checks
//! are known to accept what the library makes, and not just what a test wrote by hand. This writes
//! one as a C header and fails if the committed header differs.
//!
//! `LEMNOS_BLESS=1` rewrites the header.

use std::fmt::Write as _;
use std::path::PathBuf;

use lemnos_driver_pisp::fe::FrontEnd;
use lemnos_driver_pisp::format::formats;
use lemnos_driver_pisp::uapi::{
    BayerOrder, Branch, FeConfig, ImageFormatConfig, Wire, fe_enable as en,
};

fn config() -> FeConfig {
    let mut fe = FrontEnd::new(64, 4, BayerOrder::Bggr);
    fe.set_output_format(
        Branch::Zero,
        ImageFormatConfig {
            format: formats::BAYER16,
            ..Default::default()
        },
    );
    fe.enable(en::output(0) | en::AWB_STATS, true);
    fe.prepare().expect("a configuration the library accepts")
}

fn header() -> String {
    let mut bytes = vec![0u8; FeConfig::SIZE];
    config().write_to(&mut bytes).expect("exactly its size");
    let mut out = String::from(concat!(
        "/* SPDX-License-Identifier: GPL-2.0 */\n",
        "/*\n",
        " * Generated by drivers/pisp/tests/fe_kernel_fixture.rs: a 64x4 job with output 0 and\n",
        " * white balance statistics from the configuration library, as\n",
        " * struct pisp_fe_config.\n",
        " */\n",
        "#ifndef LEMNOS_PISP_FE_FIXTURE_H\n",
        "#define LEMNOS_PISP_FE_FIXTURE_H\n\n",
        "static const unsigned char lemnos_pisp_fe_fixture[] = {\n",
    ));
    for line in bytes.chunks(12) {
        out.push('\t');
        for (i, b) in line.iter().enumerate() {
            let sep = if i + 1 == line.len() { "," } else { ", " };
            write!(out, "0x{b:02x}{sep}").expect("to a string");
        }
        out.push('\n');
    }
    out.push_str("};\n\n#endif\n");
    out
}

#[test]
fn the_kernel_tests_fixture_is_what_the_library_builds() {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../kernel/test/lemnos_pisp_fe_fixture.h");
    let want = header();
    if std::env::var_os("LEMNOS_BLESS").is_some() {
        std::fs::write(&path, &want).expect("the fixture can be written");
    }
    let have = std::fs::read_to_string(&path).expect("the committed fixture");
    assert_eq!(have, want, "run with LEMNOS_BLESS=1 and commit the result");
}
