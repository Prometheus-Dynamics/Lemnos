//! Layout pins for the VEPU541 H.265 modules: every register's region, word, words and access,
//! every field's word, lsb, width, sign and writability, and every address register's word and
//! alignment, as the header gives them. The values come from the model generated from the header
//! (a throwaway extractor), which gcc and clang confirmed bit for bit. A change to a layout must
//! change its pin, on purpose.

use super::super::layout::{Access, AddressReg, Field, Region, Register};
use super::super::vepu541_h265::{l2, ret, set};

fn check_reg(r: Register, region: Region, access: Access, word: u16, words: u16) {
    assert_eq!(
        (r.region, r.access, r.word, r.words),
        (region, access, word, words),
        "{}",
        r.name
    );
}

fn check_field(
    f: Field,
    word: u16,
    lsb: u8,
    width: u8,
    signed: bool,
    writable: bool,
    values: &[u32],
) {
    assert_eq!(
        (f.word, f.lsb, f.width, f.signed, f.writable, f.values),
        (word, lsb, width, signed, writable, values)
    );
}

fn check_addr(a: AddressReg, word: u16, align: u32) {
    assert_eq!((a.word, a.align), (word, align));
}

