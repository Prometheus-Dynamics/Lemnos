#[test]
fn registers_sit_at_their_probed_words() {
    for &(r, word, words) in REGISTERS {
        assert_eq!((r.word, r.words), (word, words), "{}", r.name);
    }
}

#[test]
fn fields_sit_at_their_probed_bits() {
    for &(f, word, lsb, width, writable) in FIELDS {
        assert_eq!(
            (f.word, f.lsb, f.width, f.writable),
            (word, lsb, width, writable)
        );
        assert!(matches!(f.region, Region::Class(_)));
    }
}

#[test]
fn address_registers_sit_at_their_probed_words() {
    for &(a, word, align) in ADDRESSES {
        assert_eq!((a.word, a.align), (word, align));
    }
}

#[test]
fn classes_are_the_kernel_spans() {
    for (class, &(first, words, writable)) in VEPU580_CLASSES.iter().zip(CLASSES.iter()) {
        assert_eq!(
            (class.first, class.words, class.writable),
            (first, words, writable)
        );
    }
}

#[test]
fn every_register_lies_in_its_class_with_its_access() {
    for &(r, _, _) in REGISTERS {
        let Region::Class(index) = r.region else {
            panic!("{}", r.name)
        };
        let class = VEPU580_CLASSES[usize::from(index)];
        let end = u32::from(class.first) + u32::from(class.words);
        assert!(
            r.word >= class.first && u32::from(r.word) + u32::from(r.words) <= end,
            "{}",
            r.name
        );
        let want = if class.writable {
            Access::ReadWrite
        } else {
            Access::ReadOnly
        };
        assert_eq!(r.access, want, "{}", r.name);
    }
}

#[test]
fn read_only_status_and_debug_classes_are_not_writable() {
    for index in [7, 8] {
        assert!(!VEPU580_CLASSES[index].writable);
    }
    for &(r, _, _) in REGISTERS {
        if matches!(r.region, Region::Class(7 | 8)) {
            assert_eq!(r.access, Access::ReadOnly, "{}", r.name);
        }
    }
    for &(f, _, _, _, writable) in FIELDS {
        if matches!(f.region, Region::Class(7 | 8)) {
            assert!(!writable && !f.writable);
        }
    }
}

#[test]
fn the_highest_writable_word_is_in_the_osd_class() {
    let highest = REGISTERS
        .iter()
        .filter(|(r, _, _)| r.access == Access::ReadWrite)
        .map(|(r, _, _)| r.word + r.words - 1)
        .max();
    assert_eq!(highest, Some(3359));
    let osd = VEPU580_CLASSES[6];
    assert!((3359) >= osd.first && (3359) < osd.first + osd.words);
}
