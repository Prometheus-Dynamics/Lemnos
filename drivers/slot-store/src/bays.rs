pub const SETS: u8 = 3;
/// The per-set record, two sectors (`bayinfo.rec`).
pub const INFO_NAME: &str = "bayinfo.rec";
/// Its size on the partition.
pub const INFO_BYTES: u64 = 1024;
/// The pointer files at the partition's root: two sectors each ([`firmware::POINTER_FILE_BYTES`]).
pub const POINTER_BYTES: u64 = firmware::POINTER_FILE_BYTES as u64;
/// The default and previous pointers.
pub const DEFAULT_POINTER: &str = "default.txt";
/// The previous pointer.
pub const PREVIOUS_POINTER: &str = "previous.txt";
/// The trial pointer (`trial.txt`), which `tryboot.txt` includes.
pub const TRIAL_POINTER: &str = "trial.txt";
/// The trial record (the pending trial), two sectors, at the partition's root.
pub const TRIAL_RECORD: &str = "trial.rec";
/// The layout version this code writes and reads (`contracts/slot-layout.toml`).
pub const LAYOUT_VERSION: u8 = 6;
/// The overlay marker of the firmware form: `overlays/README` in a set makes `os_prefix` apply to
/// overlays. Its text says where it comes from; the firmware checks only that it exists.
pub const OVERLAY_README: &str = "overlays/README";
/// The overlay marker's text.
pub const OVERLAY_README_TEXT: &str = "Generated by lemnos-ctl boot-partition: this file makes os_prefix apply to overlays (raspberrypi/documentation config_txt/config_txt_boot.adoc, overlay_prefix).\n";
/// The U-Boot form's composed boot entry, under each set.
pub const EXTLINUX: &str = "extlinux/extlinux.conf";
/// Its largest size.
pub const EXTLINUX_BYTES: u64 = 4096;

/// One payload role: its name, and its file in a slot bundle (`boot.files`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Role {
    /// The build role (`kernel`, `initramfs`, `device-tree`, `cmdline`, `board-overlay`).
    pub role: &'static str,
    /// The file's name in a bundle, and (except the device tree, which a set stores under the
    /// board's device tree names) its path under a set.
    pub path: &'static str,
}

/// The five payload roles, in the order the install takes them.
pub const ROLES: [Role; 5] = [
    Role {
        role: "kernel",
        path: "kernel8.img",
    },
    Role {
        role: "initramfs",
        path: "initramfs.cpio",
    },
    Role {
        role: "device-tree",
        path: "board.dtb",
    },
    Role {
        role: "cmdline",
        path: "cmdline.txt",
    },
    Role {
        role: "board-overlay",
        path: "overlays/lemnos-board.dtbo",
    },
];

/// The role files' names in a bundle, in [`ROLES`] order.
pub fn stored_files() -> [&'static str; 5] {
    std::array::from_fn(|i| ROLES[i].path)
}

/// The root file that names a board's bay members: the form, the device tree names, the firmware
/// overlays and files, and the config digest. Every image has one.
pub const FIRMWARE_LIST: &str = "firmware-overlays.txt";

/// The path under a bay set of a firmware overlay named `name`: `overlays/<name>.dtbo`.
pub fn firmware_path(name: &str) -> String {
    format!("overlays/{name}.dtbo")
}

/// A firmware overlay's name: 1 to 40 letters, digits, `-` or `_`. It is the file's name without
/// `.dtbo`, and the name a `dtoverlay=` line gives.
pub fn valid_firmware_name(name: &str) -> bool {
    !name.is_empty()
        && name.len() <= 40
        && name
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_')
}

/// A file name a set stores directly (a device tree name, a firmware file): 1 to 64 letters,
/// digits, `-`, `_` or `.`, not starting with `.`.
pub fn valid_file_name(name: &str) -> bool {
    !name.is_empty()
        && name.len() <= 64
        && !name.starts_with('.')
        && name
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_' || b == b'.')
}

/// The digest of a board's firmware config lines: SHA-256 of each line followed by a newline. The
/// bundle carries it, and the boot partition's [`FIRMWARE_LIST`] holds it. `None` for no lines.
pub fn config_digest(lines: &[String]) -> Option<String> {
    if lines.is_empty() {
        return None;
    }
    let mut text = String::new();
    for line in lines {
        text.push_str(line);
        text.push('\n');
    }
    Some(crate::bundle::hex(&sha(text.as_bytes())))
}

/// The two forms a set is laid out for.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Form {
    /// The Raspberry Pi firmware: `overlays/README` in each set.
    Firmware,
    /// U-Boot: `extlinux/extlinux.conf` in each set, composed from the command line.
    Uboot,
}

/// The bay layout of a board: each role's largest file (in roles order, a multiple of the sector
/// size), the names the device tree is stored under, the firmware overlays and files the board
/// declares (each as large as the board overlay's bay at most), and the form.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Layout {
    /// The largest file of each role, in bytes.
    pub bytes: [u64; 5],
    /// The names the device tree payload is stored under, in the set's directory: the firmware's
    /// default names for the board (each a copy of the same file).
    pub dtbs: Vec<String>,
    /// Each firmware overlay: its path under the set (`overlays/<name>.dtbo`) and its largest size.
    pub firmware: Vec<(String, u64)>,
    /// Each firmware file (`overlays/overlay_map.dtb`, ...): its path under the set and its largest size.
    pub files: Vec<(String, u64)>,
    /// The digest of the firmware config lines (see [`config_digest`]), `None` for a board with none.
    pub config: Option<String>,
    /// The form.
    pub form: Form,
}

impl Layout {
    /// A firmware-form layout of the five roles, the device tree stored as `board.dtb`, refused by
    /// name when a size is zero or not a whole number of sectors.
    pub fn new(bytes: [u64; 5]) -> Result<Self, String> {
        for (r, &b) in ROLES.iter().zip(bytes.iter()) {
            if b == 0 || b % SECTOR as u64 != 0 {
                return Err(format!(
                    "bay for {}: {b} bytes is not a whole number of {SECTOR}-byte sectors",
                    r.role
                ));
            }
        }
        Ok(Self {
            bytes,
            dtbs: vec!["board.dtb".to_string()],
            firmware: Vec::new(),
            files: Vec::new(),
            config: None,
            form: Form::Firmware,
        })
    }

    /// The layout with the board's firmware overlays `names` and its config digest.
    pub fn with_firmware(mut self, names: &[String], config: Option<String>) -> Self {
        let size = self.bytes[4];
        self.firmware = names.iter().map(|n| (firmware_path(n), size)).collect();
        self.config = config;
        self
    }

    /// The layout with the device tree stored under `names`.
    pub fn with_dtbs(mut self, names: &[String]) -> Self {
        self.dtbs = names.to_vec();
        self
    }

    /// The layout with the firmware files `names` (each under `overlays/`).
    pub fn with_files(mut self, names: &[String]) -> Self {
        let size = self.bytes[4];
        self.files = names
            .iter()
            .map(|n| (format!("overlays/{n}"), size))
            .collect();
        self
    }

    /// The layout in form `form`.
    pub fn with_form(mut self, form: Form) -> Self {
        self.form = form;
        self
    }

    /// The number of payloads an install takes: the five roles, the firmware overlays, the files.
    pub fn count(&self) -> usize {
        5 + self.firmware.len() + self.files.len()
    }

    /// Each payload's name in a bundle, in payload order.
    pub fn paths(&self) -> Vec<String> {
        (0..self.count()).map(|i| self.member_path(i)).collect()
    }

    /// Payload `i`'s name in a bundle.
    pub fn member_path(&self, i: usize) -> String {
        let f = self.firmware.len();
        if i < 5 {
            ROLES[i].path.to_string()
        } else if i < 5 + f {
            self.firmware[i - 5].0.clone()
        } else {
            self.files[i - 5 - f].0.clone()
        }
    }

    /// Payload `i`'s largest size in bytes.
    pub fn member_bytes(&self, i: usize) -> u64 {
        let f = self.firmware.len();
        if i < 5 {
            self.bytes[i]
        } else if i < 5 + f {
            self.firmware[i - 5].1
        } else {
            self.files[i - 5 - f].1
        }
    }

    /// The files a set holds for `payloads` (in payload order), in the order they are written: the
    /// kernel, the initramfs, the device tree under each name, the command line, the board overlay,
    /// the firmware overlays and files, then the form's generated file.
    pub fn written(&self, payloads: &[&[u8]]) -> Result<Vec<(String, Vec<u8>)>, String> {
        if payloads.len() != self.count() {
            return Err(format!(
                "{} boot files are given and this board's boot partition stores {}",
                payloads.len(),
                self.count()
            ));
        }
        let mut out: Vec<(String, Vec<u8>)> = vec![
            (ROLES[0].path.into(), payloads[0].to_vec()),
            (ROLES[1].path.into(), payloads[1].to_vec()),
        ];
        for name in &self.dtbs {
            out.push((name.clone(), payloads[2].to_vec()));
        }
        out.push((ROLES[3].path.into(), payloads[3].to_vec()));
        out.push((ROLES[4].path.into(), payloads[4].to_vec()));
        for (i, payload) in payloads.iter().enumerate().take(self.count()).skip(5) {
            out.push((self.member_path(i), payload.to_vec()));
        }
        match self.form {
            Form::Firmware => {
                out.push((
                    OVERLAY_README.into(),
                    OVERLAY_README_TEXT.as_bytes().to_vec(),
                ));
            }
            Form::Uboot => {
                out.push((
                    EXTLINUX.into(),
                    crate::bootimage::extlinux_text(payloads[3])?,
                ));
            }
        }
        if out.len() > MAX_MEMBERS {
            return Err(format!(
                "a set of this board holds {} files, more than a record's {MAX_MEMBERS}",
                out.len()
            ));
        }
        Ok(out)
    }

    /// Which payload each written file is, in [`Layout::written`] order: `Some(i)` for a copy of
    /// payload `i`, `None` for the form's generated file.
    pub fn sources(&self) -> Vec<Option<usize>> {
        let mut out = vec![Some(0), Some(1)];
        out.extend(self.dtbs.iter().map(|_| Some(2)));
        out.push(Some(3));
        out.push(Some(4));
        out.extend((5..self.count()).map(Some));
        out.push(None);
        out
    }

    /// The set's subdirectories, in the order its files first name them.
    pub fn subdirs(&self) -> Vec<String> {
        let mut out: Vec<String> = Vec::new();
        for path in self.names() {
            if let Some((d, _)) = path.split_once('/')
                && !out.iter().any(|o| o == d)
            {
                out.push(d.to_string());
            }
        }
        out
    }

    /// The paths a set's files have, in written order.
    pub fn names(&self) -> Vec<String> {
        let empty: Vec<&[u8]> = vec![&[]; self.count()];
        self.written(&empty)
            .map(|w| w.into_iter().map(|(p, _)| p).collect())
            .unwrap_or_default()
    }

    /// The largest size of each written file, in [`Layout::written`] order: the region is sized for
    /// all of them at once.
    pub fn caps(&self) -> Vec<u64> {
        let mut out = vec![self.bytes[0], self.bytes[1]];
        out.extend(self.dtbs.iter().map(|_| self.bytes[2]));
        out.push(self.bytes[3]);
        out.push(self.bytes[4]);
        out.extend(self.firmware.iter().map(|(_, b)| *b));
        out.extend(self.files.iter().map(|(_, b)| *b));
        out.push(match self.form {
            Form::Firmware => OVERLAY_README_TEXT.len() as u64,
            Form::Uboot => EXTLINUX_BYTES,
        });
        out
    }

    /// The directory entries each of a set's directories needs, `.` and `..` included: the set's
    /// own (with the record, the subdirectories and `reserve`), then each subdirectory, by name.
    pub fn dir_entries(&self) -> Vec<(String, usize)> {
        let names = self.names();
        let entries = |name: &str| -> usize {
            if crate::fatimage::is_83(name) {
                1
            } else {
                1 + name.encode_utf16().count().div_ceil(13)
            }
        };
        // The kept entries (`.`, `..`, the record, the subdirectories) fill whole sectors of their
        // own, the files and `reserve` start on the next (bayfat's directory form).
        let per_sector = SECTOR / 32;
        let mut kept = 2 + entries(INFO_NAME);
        let mut own = entries(bayfat::RESERVE);
        let mut subs: Vec<(String, usize)> = Vec::new();
        for path in &names {
            match path.split_once('/') {
                None => own += entries(path),
                Some((dir, file)) => match subs.iter_mut().find(|(d, _)| d == dir) {
                    Some((_, n)) => *n += entries(file),
                    None => {
                        kept += entries(dir);
                        subs.push((
                            dir.to_string(),
                            2usize.next_multiple_of(per_sector) + entries(file),
                        ));
                    }
                },
            }
        }
        let mut out = vec![(String::new(), kept.next_multiple_of(per_sector) + own)];
        out.extend(subs);
        out
    }
}

/// The [`FIRMWARE_LIST`] text of a layout: `form`, one `dtb` line per device tree name, `config`
/// when the board declares config lines, one `overlay` line per firmware overlay and one `file` line
/// per firmware file, each in the board's order.
pub fn firmware_list_text(layout: &Layout) -> String {
    let mut out = format!(
        "form {}\n",
        match layout.form {
            Form::Firmware => "firmware",
            Form::Uboot => "uboot",
        }
    );
    for d in &layout.dtbs {
        out.push_str(&format!("dtb {d}\n"));
    }
    if let Some(digest) = &layout.config {
        out.push_str(&format!("config {digest}\n"));
    }
    for (path, _) in &layout.firmware {
        let name = path
            .trim_start_matches("overlays/")
            .trim_end_matches(".dtbo");
        out.push_str(&format!("overlay {name}\n"));
    }
    for (path, _) in &layout.files {
        out.push_str(&format!("file {}\n", path.trim_start_matches("overlays/")));
    }
    out
}

/// What [`FIRMWARE_LIST`] says: the form, the device tree names, the overlay names, the file
/// names and the config digest.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Declared {
    /// The form.
    pub form: Form,
    /// The device tree names.
    pub dtbs: Vec<String>,
    /// The firmware overlay names.
    pub overlays: Vec<String>,
    /// The firmware file names.
    pub files: Vec<String>,
    /// The config digest.
    pub config: Option<String>,
}

/// Reads [`FIRMWARE_LIST`]'s text. A line of no known form, a repeated `form` or `config`, a bad or
/// repeated name, or no `form` or no `dtb` line is refused by name.
pub fn parse_firmware_list(text: &str) -> Result<Declared, String> {
    let mut form = None;
    let mut d = Declared {
        form: Form::Firmware,
        dtbs: Vec::new(),
        overlays: Vec::new(),
        files: Vec::new(),
        config: None,
    };
    for line in text.lines() {
        let bad = |what: &str| format!("{FIRMWARE_LIST}: the {what} line {line:?} is not valid");
        if let Some(f) = line.strip_prefix("form ") {
            if form.is_some() {
                return Err(bad("form"));
            }
            form = Some(match f {
                "firmware" => Form::Firmware,
                "uboot" => Form::Uboot,
                _ => return Err(bad("form")),
            });
        } else if let Some(n) = line.strip_prefix("dtb ") {
            if !valid_file_name(n) || d.dtbs.iter().any(|x| x == n) {
                return Err(bad("dtb"));
            }
            d.dtbs.push(n.to_string());
        } else if let Some(digest) = line.strip_prefix("config ") {
            if d.config.is_some() || !crate::manifest::is_hex(digest, 64) {
                return Err(bad("config"));
            }
            d.config = Some(digest.to_string());
        } else if let Some(n) = line.strip_prefix("overlay ") {
            if !valid_firmware_name(n) || d.overlays.iter().any(|x| x == n) {
                return Err(bad("overlay"));
            }
            d.overlays.push(n.to_string());
        } else if let Some(n) = line.strip_prefix("file ") {
            if !valid_file_name(n) || d.files.iter().any(|x| x == n) {
                return Err(bad("file"));
            }
            d.files.push(n.to_string());
        } else {
            return Err(format!(
                "{FIRMWARE_LIST}: the line {line:?} is none of form, dtb, config, overlay or file"
            ));
        }
    }
    d.form = form.ok_or_else(|| format!("{FIRMWARE_LIST} has no form line"))?;
    if d.dtbs.is_empty() {
        return Err(format!(
            "{FIRMWARE_LIST} names no device tree (no dtb line)"
        ));
    }
    Ok(d)
}

/// The `boot.files` entries that the declared set `declared` (bundle names) does not name, in the
/// manifest's order.
pub fn unstored<'a>(boot_files: &'a [(String, String)], declared: &[String]) -> Vec<&'a str> {
    boot_files
        .iter()
        .map(|(name, _)| name.as_str())
        .filter(|name| !declared.iter().any(|d| d == name))
        .collect()
}

/// The refusal for a manifest whose `boot.files` is not exactly the declared set `declared` (the
/// bundle names: the five role files, the board's firmware overlays and files). A file the set does
/// not name and a named file the list lacks are each refused by name; `Ok` when the two are the same
/// set. The install makes it before any write.
pub fn refuse_unstored(
    slot: &str,
    boot_files: &[(String, String)],
    declared: &[String],
) -> Result<(), String> {
    let stores = declared.join(", ");
    let extra = unstored(boot_files, declared);
    if extra.is_empty() {
        if let Some(unlisted) = declared
            .iter()
            .find(|path| !boot_files.iter().any(|(name, _)| name == *path))
        {
            return Err(format!(
                "{slot}: boot.files does not list {unlisted:?}, which this board's boot partition stores (it stores: {stores}): nothing was written, the default keeps booting"
            ));
        }
        return Ok(());
    }
    let listed: Vec<String> = extra.iter().map(|name| format!("{name:?}")).collect();
    Err(format!(
        "{slot}: boot.files lists {}, which this board's boot partition does not store (it stores: {stores}): nothing was written, the default keeps booting",
        listed.join(", "),
    ))
}

