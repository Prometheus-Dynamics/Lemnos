//! Payload bays, layout version 6: a slot's boot files sit in one of three bay sets on the boot
//! partition, `slots/bay0/` to `slots/bay2/`, each file at its exact size under the name the firmware
//! reads. A set is the directory a pointer names (`os_prefix=slots/bayN/`).
//!
//! A set owns, for the life of the image, a contiguous region of clusters aligned to whole FAT
//! sectors, its directories and its record (`bayinfo.rec`). An install creates the set's files in
//! the region and the directory entries that name them, and writes nothing outside the set
//! ([`crate::bayfat`]). Order of an install (each step durable before the next):
//! 1. refuse, before any write, when a trial is pending, when the set is the previous's or the
//!    trial's bay, when a payload is larger than its role's bay, when the files do not fit the
//!    region, or when the set is the default's and holds the slot with a boot file whose stored
//!    hash differs from the bundle's (the answer names the file);
//! 2. (a) write the set's record empty (it keeps the region), so the set holds no slot;
//! 3. (b-e) the data, the region's FAT sectors (second copy, then first), the directories (the
//!    `reserve` entry last), then every file read back through the FAT parsed again;
//! 4. (f) commit the record (the slot, each file's path, length and hash), read it back;
//! 5. point `previous.txt` at the old default's set, then `default.txt` at the new set. A pointer is
//!    two sectors holding the same `os_prefix` line; the second sector is written first.
//!
//! A cut anywhere leaves the default booting (nothing it reads is written), the cut set
//! uncommitted, and every sector outside the set as it was; the next install rewrites the set whole.

use crate::bayfat::{self, Member, Region};
use crate::boot_raw::{self, Trial};
