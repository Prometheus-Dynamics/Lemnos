/// The set a pointer names (`bayN`), `None` for any other name.
pub fn set_of(name: &str) -> Option<u8> {
    let n: u8 = name.strip_prefix("bay")?.parse().ok()?;
    (n < SETS).then_some(n)
}

/// What an install did.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Done {
    /// The payloads are in the set, committed, and the pointers name it.
    Installed,
    /// The set already is the default and holds this slot with every boot file's stored hash equal to
    /// the payload's: nothing was written.
    AlreadyInstalled,
}

/// Why an install did not finish.
#[derive(Debug)]
pub enum Error {
    /// Refused before any write, or stopped before a commit: the answer, with its reason.
    Refused(String),
    /// The device failed, or a read-back did not match what was written. Nothing was committed.
    Device(String),
}

impl std::fmt::Display for Error {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Error::Refused(why) | Error::Device(why) => f.write_str(why),
        }
    }
}

fn io_err(e: std::io::Error) -> Error {
    Error::Device(e.to_string())
}

fn sha(bytes: &[u8]) -> [u8; 32] {
    Sha256::digest(bytes).into()
}

/// The first byte of every record this layout and any later one writes. A record of layout version 5
/// or before begins with its slot name's length (0 to 64), so it can never begin with this byte and
/// is never read as a record of this layout.
pub const RECORD_TAG: u8 = b'L';
const _: () = assert!(RECORD_TAG as usize > crate::store::MAX_ID_BYTES);

/// The most files a set holds: what a record has room for.
pub const MAX_MEMBERS: usize = 30;

/// A set's record: its region, and, when committed, the slot in it, each file's stored length and
/// the first eight bytes of its SHA-256 (in [`Layout::written`] order; the paths are the layout's),
/// and the SHA-256 of the whole list ([`list_digest`]). It fits one two-copy record.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Info {
    /// The set's region.
    pub region: Region,
    /// The slot, `None` for an empty set.
    pub slot: Option<String>,
    /// Each file's length and hash prefix.
    pub members: Vec<(u64, [u8; 8])>,
    /// The SHA-256 of the list of paths, lengths and hashes.
    pub digest: [u8; 32],
}

/// The SHA-256 a record keeps over its files: each file's path, a NUL, its length (eight bytes, little
/// endian) and its SHA-256, in order.
pub fn list_digest(files: &[(String, u64, [u8; 32])]) -> [u8; 32] {
    let mut h = Sha256::new();
    for (path, len, hash) in files {
        h.update(path.as_bytes());
        h.update([0]);
        h.update(len.to_le_bytes());
        h.update(hash);
    }
    h.finalize().into()
}

impl Info {
    /// An empty set's record over `region`.
    pub fn empty(region: Region) -> Self {
        Self {
            region,
            slot: None,
            members: Vec::new(),
            digest: [0; 32],
        }
    }

    /// The committed record of `slot` over `region` for `files` (path, bytes) in written order.
    pub fn committed(region: Region, slot: &str, files: &[(String, Vec<u8>)]) -> Self {
        let full: Vec<(String, u64, [u8; 32])> = files
            .iter()
            .map(|(p, b)| (p.clone(), b.len() as u64, sha(b)))
            .collect();
        Self {
            region,
            slot: Some(slot.to_string()),
            members: full
                .iter()
                .map(|(_, len, h)| (*len, h[..8].try_into().expect("eight bytes")))
                .collect(),
            digest: list_digest(&full),
        }
    }

    /// The record's bytes: [`RECORD_TAG`], the version, the region (first cluster and count, four bytes each), the
    /// slot (one length byte, 0 for none), the file count (one byte), each file's length (four bytes)
    /// and hash prefix, then the list digest.
    pub fn encode(&self) -> Vec<u8> {
        let mut out = vec![RECORD_TAG, LAYOUT_VERSION];
        out.extend_from_slice(&(self.region.start as u32).to_le_bytes());
        out.extend_from_slice(&(self.region.clusters as u32).to_le_bytes());
        let slot = self.slot.as_deref().unwrap_or("");
        out.push(slot.len() as u8);
        out.extend_from_slice(slot.as_bytes());
        out.push(self.members.len() as u8);
        for (len, prefix) in &self.members {
            out.extend_from_slice(&(*len as u32).to_le_bytes());
            out.extend_from_slice(prefix);
        }
        out.extend_from_slice(&self.digest);
        out
    }

    /// The record from its bytes; `None` for any other shape or version.
    pub fn decode(bytes: &[u8]) -> Option<Self> {
        if bytes.get(..2)? != [RECORD_TAG, LAYOUT_VERSION] {
            return None;
        }
        let word = |at: usize| -> Option<u64> {
            Some(u64::from(u32::from_le_bytes(
                bytes.get(at..at + 4)?.try_into().ok()?,
            )))
        };
        let region = Region {
            start: word(2)?,
            clusters: word(6)?,
        };
        let n = *bytes.get(10)? as usize;
        let mut at = 11;
        let slot = if n == 0 {
            None
        } else {
            let s = std::str::from_utf8(bytes.get(at..at + n)?)
                .ok()?
                .to_string();
            if !crate::store::valid_id(&s) {
                return None;
            }
            Some(s)
        };
        at += n;
        let count = *bytes.get(at)? as usize;
        at += 1;
        let mut members = Vec::with_capacity(count);
        for _ in 0..count {
            let len = word(at)?;
            let prefix: [u8; 8] = bytes.get(at + 4..at + 12)?.try_into().ok()?;
            members.push((len, prefix));
            at += 12;
        }
        let digest: [u8; 32] = bytes.get(at..at + 32)?.try_into().ok()?;
        at += 32;
        if slot.is_none() && !members.is_empty() {
            return None;
        }
        (at == bytes.len()).then_some(Self {
            region,
            slot,
            members,
            digest,
        })
    }
}

/// Compares a set's record with what `payloads` would write ([`Layout::written`]). Writes nothing.
/// The first file that differs is named, in the words `bay<N> holds boot file <path> with a
/// different hash than slot.json says`.
pub fn compare_hashes(
    layout: &Layout,
    set: u8,
    info: &Info,
    payloads: &[&[u8]],
) -> Result<(), String> {
    let want = layout.written(payloads)?;
    if want.len() != info.members.len() {
        return Err(format!(
            "bay{set} holds {} boot files and the bundle makes {}: build the image from this bundle",
            info.members.len(),
            want.len()
        ));
    }
    for ((path, bytes), (len, prefix)) in want.iter().zip(&info.members) {
        if *len != bytes.len() as u64 || sha(bytes)[..8] != prefix[..] {
            return Err(format!(
                "bay{set} holds boot file {path} with a different hash than slot.json says"
            ));
        }
    }
    let full: Vec<(String, u64, [u8; 32])> = want
        .iter()
        .map(|(p, b)| (p.clone(), b.len() as u64, sha(b)))
        .collect();
    if list_digest(&full) != info.digest {
        return Err(format!(
            "bay{set} holds boot files whose list digest differs from what slot.json makes"
        ));
    }
    Ok(())
}

/// Reads the pointer file's effective set: the last whole line of its two sectors (the one form,
/// [`firmware::pointer_file_slot`]). `None` when neither sector holds a whole line.
pub fn read_pointer<D: Sectors>(dev: &mut D, lba: u64) -> Result<Option<u8>, Error> {
    let mut file = [0u8; POINTER_BYTES as usize];
    for (k, chunk) in file.chunks_mut(SECTOR).enumerate() {
        dev.read(lba + k as u64, chunk.try_into().expect("a whole sector"))
            .map_err(io_err)?;
    }
    Ok(firmware::pointer_file_slot(&file).and_then(|name| set_of(&name)))
}

/// Writes the pointer file to name `set`: the second sector, then the first.
pub fn write_pointer<D: Sectors>(dev: &mut D, lba: u64, set: u8) -> Result<(), Error> {
    let file = firmware::pointer_file(&format!("bay{set}")).expect("bay names are valid ids");
    for k in [1usize, 0] {
        let at = k * SECTOR;
        dev.write(
            lba + k as u64,
            file[at..at + SECTOR].try_into().expect("a whole sector"),
        )
        .map_err(io_err)?;
    }
    Ok(())
}

/// The partition's placed records and pointers.
pub struct Placed {
    /// Each set's record, first sector.
    pub info: Vec<u64>,
    /// The default pointer's first sector.
    pub default: u64,
    /// The previous pointer's first sector.
    pub previous: u64,
    /// The trial record's first sector.
    pub trial: u64,
    /// The trial pointer's first sector (`trial.txt`).
    pub trial_pointer: u64,
}

/// The bays the caller says are protected. A bay named here is never written or freed, and an install
/// is refused while `pending` is set.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Protected {
    /// The set the default pointer names.
    pub default: Option<u8>,
    /// The set the previous pointer names.
    pub previous: Option<u8>,
    /// The set the trial names (the trial pointer on the Pi form).
    pub trial: Option<u8>,
    /// A trial with attempts left: nothing is installed while it is pending.
    pub pending: Option<Trial>,
}

impl Protected {
    /// The Pi firmware form's protected sets, read from the volume's pointer files and trial record.
    pub fn from_volume<D: ReadAt + Sectors>(dev: &mut D) -> Result<Self, Error> {
        let placed = place(dev).map_err(Error::Refused)?;
        let pending = pending_trial(dev, placed.trial)?;
        // The trial pointer names a bay only while a trial record exists.
        let trial = match pending {
            Some(_) => read_pointer(dev, placed.trial_pointer)?,
            None => None,
        };
        Ok(Self {
            default: read_pointer(dev, placed.default)?,
            previous: read_pointer(dev, placed.previous)?,
            trial,
            pending,
        })
    }

    /// Whether `set` is named by any protected entry.
    pub fn names(&self, set: u8) -> bool {
        [self.default, self.previous, self.trial].contains(&Some(set))
    }
}

/// Locates every set's record and the pointers, reading the volume only.
pub fn place<D: ReadAt>(dev: &mut D) -> Result<Placed, String> {
    let info = place_sets(dev)?;
    let mut at = |path: &str, want: u64| -> Result<u64, String> {
        bootfat::locate_path(dev, path, want)
            .map(|f| f.first_lba)
            .map_err(|e: Refusal| format!("{path}: {e}"))
    };
    Ok(Placed {
        info,
        default: at(DEFAULT_POINTER, POINTER_BYTES)?,
        previous: at(PREVIOUS_POINTER, POINTER_BYTES)?,
        trial: at(TRIAL_RECORD, INFO_BYTES)?,
        trial_pointer: at(TRIAL_POINTER, POINTER_BYTES)?,
    })
}

/// The current trial, if one is pending: its slot and attempts.
pub fn pending_trial<D: Sectors>(dev: &mut D, lba: u64) -> Result<Option<Trial>, Error> {
    let pair = Pair::at(lba);
    let cur = pair
        .read(dev, Kind::TRIAL)
        .map_err(|e| Error::Device(e.to_string()))?;
    Ok(cur.and_then(|c| boot_raw::decode_trial(&c.payload)))
}

/// Each set's record, first sector (the U-Boot form keeps its pointers in the environment, so it
/// places only these).
pub fn place_sets<D: ReadAt>(dev: &mut D) -> Result<Vec<u64>, String> {
    (0..SETS)
        .map(|set| {
            let path = format!("{}/{INFO_NAME}", set_dir(set));
            bootfat::locate_path(dev, &path, INFO_BYTES)
                .map(|f| f.first_lba)
                .map_err(|e: Refusal| format!("{path}: {e}"))
        })
        .collect()
}

/// The sectors set `set` owns: what an install or a free of it may write (its region's data, the
/// region's FAT sectors in each copy, its directories and its record), read from its record.
pub fn set_sectors<D: Sectors + ReadAt>(dev: &mut D, set: u8) -> Result<Vec<u64>, String> {
    let lba = *place_sets(dev)?
        .get(usize::from(set))
        .ok_or_else(|| format!("there is no set {set}"))?;
    let info = read_info(dev, lba)
        .map_err(|e| e.to_string())?
        .ok_or_else(|| format!("{}: neither copy is a record", set_dir(set)))?;
    crate::bayfat::owned_sectors(dev, &set_dir(set), INFO_NAME, info.region)
}

/// The argument checks of an install, before any read or write: the set, the slot id, the number of
/// payloads, and each payload against its role's bay. A refusal names the reason and writes nothing.
pub fn check_install(
    layout: &Layout,
    set: u8,
    slot: &str,
    payloads: &[&[u8]],
) -> Result<(), Error> {
    if set >= SETS {
        return Err(Error::Refused(format!(
            "bay set {set} does not exist: there are {SETS}"
        )));
    }
    if !crate::store::valid_id(slot) {
        return Err(Error::Refused(format!("{slot:?} is not a slot id")));
    }
    if payloads.len() != layout.count() {
        return Err(Error::Refused(format!(
            "{slot}: {} boot files are given and this board's boot partition stores {}: nothing was written",
            payloads.len(),
            layout.count()
        )));
    }
    for i in 0..layout.count() {
        if payloads[i].len() as u64 > layout.member_bytes(i) {
            let what = if i < 5 {
                ROLES[i].role.to_string()
            } else {
                layout.member_path(i)
            };
            let bay = if i < 5 {
                ROLES[i].role.to_string()
            } else {
                "board's firmware overlay".to_string()
            };
            return Err(Error::Refused(format!(
                "{slot}: the {what} payload is {} bytes but its bay holds {}: nothing was written, \
                 the default keeps booting; rebuild the image with a larger {bay} bay or a smaller payload",
                payloads[i].len(),
                layout.member_bytes(i),
            )));
        }
    }
    Ok(())
}

/// Steps a to f of an install, for one set: the record emptied, the files and their filesystem
/// records written and read back ([`bayfat::write_set`]), then the record committed and read back.
/// Nothing a pointer names is touched.
pub fn commit_set<D: Sectors + ReadAt>(
    dev: &mut D,
    layout: &Layout,
    set: u8,
    info_lba: u64,
    slot: &str,
    payloads: &[&[u8]],
) -> Result<(), Error> {
    let written = layout
        .written(payloads)
        .map_err(|e| Error::Refused(format!("{slot}: {e}: nothing was written")))?;
    let current = read_info(dev, info_lba)?.ok_or_else(|| {
        Error::Refused(format!(
            "bay{set}'s record names no region: the boot partition was not made for layout version \
             {LAYOUT_VERSION}: nothing was written"
        ))
    })?;
    let region = current.region;
    // The plan first: files that do not fit the region are refused with nothing written.
    let members: Vec<Member<'_>> = written
        .iter()
        .map(|(p, b)| Member { path: p, bytes: b })
        .collect();
    let v = bootfat::volume(dev).map_err(|e| Error::Device(e.to_string()))?;
    region.check(&v).map_err(Error::Refused)?;
    bayfat::plan(&v, region, &members).map_err(|e| Error::Refused(format!("{slot}: {e}")))?;
    // a. The record emptied: the set holds no slot while its files change.
    if current.slot.is_some() {
        Pair::at(info_lba)
            .write(dev, Kind::BAY_INFO, &Info::empty(region).encode())
            .map_err(|e| Error::Device(e.to_string()))?;
    }
    // b-e.
    let dirs = layout.subdirs();
    let dirs: Vec<&str> = dirs.iter().map(String::as_str).collect();
    bayfat::write_set(dev, &set_dir(set), INFO_NAME, region, &dirs, &members)
        .map_err(Error::Device)?;
    // f. The commit.
    let record = Info::committed(region, slot, &written);
    Pair::at(info_lba)
        .write(dev, Kind::BAY_INFO, &record.encode())
        .map_err(|e| Error::Device(e.to_string()))?;
    if read_info(dev, info_lba)?.as_ref() != Some(&record) {
        return Err(Error::Device(format!(
            "{slot}: the set's record did not read back"
        )));
    }
    Ok(())
}

/// Installs `payloads` (in payload order) as slot `slot` into bay set `set`, and makes it the
/// default; the previous default becomes the previous.
pub fn install<D: Sectors + ReadAt>(
    dev: &mut D,
    layout: &Layout,
    set: u8,
    slot: &str,
    payloads: &[&[u8]],
) -> Result<Done, Error> {
    let protected = Protected::from_volume(dev)?;
    let done = stage_with(dev, layout, set, slot, payloads, &protected)?;
    if done == Done::Installed {
        make_default(dev, set, &protected)?;
    }
    Ok(done)
}

/// The install's write part, which moves no pointer.
pub fn stage<D: Sectors + ReadAt>(
    dev: &mut D,
    layout: &Layout,
    set: u8,
    slot: &str,
    payloads: &[&[u8]],
) -> Result<Done, Error> {
    let protected = Protected::from_volume(dev)?;
    stage_with(dev, layout, set, slot, payloads, &protected)
}

/// [`stage`] with the caller's protected sets. A default set with no committed slot takes the
/// install in place; every other protected bay is refused.
pub fn stage_with<D: Sectors + ReadAt>(
    dev: &mut D,
    layout: &Layout,
    set: u8,
    slot: &str,
    payloads: &[&[u8]],
    protected: &Protected,
) -> Result<Done, Error> {
    check_install(layout, set, slot, payloads)?;
    if let Some(t) = &protected.pending {
        return Err(Error::Refused(format!(
            "slot {} is on trial with {} attempts left: nothing was written; wait until the trial \
             is promoted or falls back, then install {slot} again",
            t.slot, t.attempts
        )));
    }
    let info_lba = place_sets(dev).map_err(Error::Refused)?[set as usize];
    if protected.default == Some(set) {
        match read_info(dev, info_lba)? {
            Some(Info {
                slot: Some(held), ..
            }) if held == slot => {
                let info = read_info(dev, info_lba)?.expect("read above");
                compare_hashes(layout, set, &info, payloads).map_err(|why| {
                    Error::Refused(format!(
                        "{why}: nothing was written, the default keeps booting"
                    ))
                })?;
                return Ok(Done::AlreadyInstalled);
            }
            Some(Info { slot: Some(_), .. }) => {
                return Err(Error::Refused(format!(
                    "bay{set} is the default and does not hold {slot}: nothing was written"
                )));
            }
            _ => {}
        }
    } else if protected.previous == Some(set) {
        return Err(Error::Refused(format!(
            "bay{set} is the previous slot's bay: a new install takes one of the other bays"
        )));
    } else if protected.trial == Some(set) {
        return Err(Error::Refused(format!(
            "bay{set} is the trial's bay: a new install takes one of the other bays"
        )));
    }
    commit_set(dev, layout, set, info_lba, slot, payloads)?;
    Ok(Done::Installed)
}

/// Makes `set` the default and the old default (`protected.default`) the previous: previous first,
/// then default. The set must hold a committed slot.
pub fn make_default<D: Sectors + ReadAt>(
    dev: &mut D,
    set: u8,
    protected: &Protected,
) -> Result<(), Error> {
    let placed = place(dev).map_err(Error::Refused)?;
    if !matches!(
        read_info(dev, placed.info[set as usize])?,
        Some(Info { slot: Some(_), .. })
    ) {
        return Err(Error::Refused(format!(
            "bay{set} holds no committed record: nothing was pointed at it"
        )));
    }
    if let Some(d) = protected.default
        && d != set
    {
        write_pointer(dev, placed.previous, d)?;
    }
    write_pointer(dev, placed.default, set)
}

/// The set that holds `slot`'s committed record, `None` when no set does.
pub fn set_of_slot<D: ReadAt + Sectors>(dev: &mut D, slot: &str) -> Result<Option<u8>, Error> {
    let sets = place_sets(dev).map_err(Error::Refused)?;
    for set in 0..SETS {
        if let Some(Info {
            slot: Some(held), ..
        }) = read_info(dev, sets[set as usize])?
            && held == slot
        {
            return Ok(Some(set));
        }
    }
    Ok(None)
}

/// The set an install of `slot` takes: the set that already holds it, else the first set no
/// pointer names. Refused by name when every set is named.
pub fn choose_set<D: ReadAt + Sectors>(
    dev: &mut D,
    slot: &str,
    protected: &Protected,
) -> Result<u8, Error> {
    if let Some(set) = set_of_slot(dev, slot)? {
        return Ok(set);
    }
    (0..SETS).find(|set| !protected.names(*set)).ok_or_else(|| {
        Error::Refused(format!(
            "{slot}: every bay set is named by a pointer: nothing was written"
        ))
    })
}

/// Frees a set by its record alone: the record then holds no slot (and keeps the region).
pub fn free_set<D: Sectors + ReadAt>(
    dev: &mut D,
    set: u8,
    protected: &Protected,
) -> Result<(), Error> {
    if protected.names(set) {
        return Err(Error::Refused(format!(
            "bay{set} is named by a protected entry (default, previous or trial): it is not freed"
        )));
    }
    let lba = place_sets(dev).map_err(Error::Refused)?[set as usize];
    let info = read_info(dev, lba)?.ok_or_else(|| {
        Error::Refused(format!(
            "bay{set}'s record names no region: the boot partition was not made for layout version {LAYOUT_VERSION}"
        ))
    })?;
    Pair::at(lba)
        .write(dev, Kind::BAY_INFO, &Info::empty(info.region).encode())
        .map_err(|e| Error::Device(e.to_string()))?;
    Ok(())
}

/// The layout an image was built with, from its [`FIRMWARE_LIST`] and its sets' regions. A device
/// has no board file, so each role's largest size is taken as the region's size: the region is
/// what bounds an install there.
pub fn discover<D: ReadAt + Sectors>(dev: &mut D) -> Result<Layout, String> {
    let text = bootfat::read_file(dev, FIRMWARE_LIST, 4096)
        .map_err(|e| format!("{FIRMWARE_LIST}: {e}"))?;
    let text = String::from_utf8(text).map_err(|_| format!("{FIRMWARE_LIST} is not text"))?;
    let d = parse_firmware_list(&text)?;
    let v = bootfat::volume(dev).map_err(|e| e.to_string())?;
    let mut region_bytes = u64::MAX;
    for (set, lba) in place_sets(dev)?.into_iter().enumerate() {
        let info = read_info(dev, lba).map_err(|e| e.to_string())?.ok_or_else(|| {
            format!(
                "bay{set}'s record names no region: the boot partition was not made for layout version {LAYOUT_VERSION}"
            )
        })?;
        info.region.check(&v)?;
        region_bytes = region_bytes.min(info.region.clusters * v.spc * SECTOR as u64);
    }
    let layout = Layout::new([region_bytes; 5])?
        .with_dtbs(&d.dtbs)
        .with_firmware(&d.overlays, d.config)
        .with_files(&d.files)
        .with_form(d.form);
    Ok(layout)
}

/// The set's record at `lba`: `Ok(Ok(info))` when it is this layout version's, `Ok(Err(why))` naming
/// what is there instead (no record, another layout version's, or the form before layout version 6),
/// `Err` when it can't be read. Reads only.
pub fn record_or_why<D: Sectors>(dev: &mut D, lba: u64) -> Result<Result<Info, String>, String> {
    let cur = Pair::at(lba)
        .read(dev, Kind::BAY_INFO)
        .map_err(|e| e.to_string())?;
    Ok(match &cur {
        None => Err("neither copy is a record".to_string()),
        Some(c) => match Info::decode(&c.payload) {
            Some(info) => Ok(info),
            None => Err(match c.payload.as_slice() {
                [RECORD_TAG, v, ..] if *v != LAYOUT_VERSION => {
                    format!("its record is layout version {v}")
                }
                [RECORD_TAG, ..] => "its record is not a record of its layout version".to_string(),
                _ => "its record is in the form before layout version 6 (layout version 5 and \
                      before begin with the slot name's length)"
                    .to_string(),
            }),
        },
    })
}

/// Whether every set's record is this layout version's: `Ok(None)` when each is, `Ok(Some(why))`
/// naming the first set whose record is not (a partition made for another layout version, which
/// nothing here writes), `Err` when a record can't be read to say. Reads only.
pub fn records_version<D: ReadAt + Sectors>(dev: &mut D) -> Result<Option<String>, String> {
    let sets = match place_sets(dev) {
        Ok(sets) => sets,
        Err(why) => return Ok(Some(why)),
    };
    for (set, lba) in sets.into_iter().enumerate() {
        let path = format!("{}/{INFO_NAME}", set_dir(set as u8));
        if let Err(found) = record_or_why(dev, lba).map_err(|e| format!("{path}: {e}"))? {
            return Ok(Some(format!(
                "{path}: {found}, and this code reads and writes only layout version \
                 {LAYOUT_VERSION}: the boot partition was made for another layout, nothing is \
                 written to it"
            )));
        }
    }
    Ok(None)
}

/// The set's record, `None` when neither copy is one.
pub fn read_info<D: Sectors>(dev: &mut D, lba: u64) -> Result<Option<Info>, Error> {
    let cur = Pair::at(lba)
        .read(dev, Kind::BAY_INFO)
        .map_err(|e| Error::Device(e.to_string()))?;
    Ok(cur.and_then(|c| Info::decode(&c.payload)))
}

/// Reads every file of a committed set (the layout names them) and checks it against the record:
/// the slot, or the first file that does not match.
pub fn check_set<D: Sectors + ReadAt>(
    dev: &mut D,
    layout: &Layout,
    set: u8,
    info: &Info,
) -> Result<String, String> {
    let slot = info
        .slot
        .clone()
        .ok_or_else(|| format!("bay{set} holds no committed record"))?;
    let names = layout.names();
    if names.len() != info.members.len() {
        return Err(format!(
            "bay{set} ({slot}): its record lists {} files and the layout names {}",
            info.members.len(),
            names.len()
        ));
    }
    let mut full = Vec::with_capacity(names.len());
    for (path, (len, prefix)) in names.iter().zip(&info.members) {
        let at = format!("{}/{path}", set_dir(set));
        let bytes = bootfat::read_file(dev, &at, *len)
            .map_err(|e| format!("bay{set} ({slot}): {path}: {e}"))?;
        let hash = sha(&bytes);
        if bytes.len() as u64 != *len || hash[..8] != prefix[..] {
            return Err(format!(
                "bay{set} ({slot}): the {path} file does not match its record"
            ));
        }
        full.push((path.clone(), *len, hash));
    }
    if list_digest(&full) != info.digest {
        return Err(format!(
            "bay{set} ({slot}): its files' list digest does not match its record"
        ));
    }
    Ok(slot)
}

/// What the boot chain reads from a pointer: the set it names, the slot in that set, and whether each
/// file's stored bytes match the record.
pub fn boot_view<D: Sectors + ReadAt>(
    dev: &mut D,
    layout: &Layout,
    pointer_lba: u64,
) -> Result<(u8, String), String> {
    let placed = place(dev)?;
    let set = read_pointer(dev, pointer_lba)
        .map_err(|e| e.to_string())?
        .ok_or_else(|| "the pointer holds no whole line".to_string())?;
    let info = read_info(dev, placed.info[set as usize])
        .map_err(|e| e.to_string())?
        .ok_or_else(|| format!("bay{set} holds no committed record"))?;
    let slot = check_set(dev, layout, set, &info)?;
    Ok((set, slot))
}

/// The bay a slot's files are in: the set's directory (`slots/bayN`) and each file's path and stored
/// length from the set's committed record. Refused by name when no set holds the slot.
pub fn slot_bay_on<D: ReadAt + Sectors>(
    dev: &mut D,
    layout: &Layout,
    slot: &str,
) -> Result<(String, Vec<(String, u64)>), String> {
    let set = set_of_slot(dev, slot)
        .map_err(|e| e.to_string())?
        .ok_or_else(|| format!("slot {slot} has no bay on the boot partition: nothing names it"))?;
    let sets = place_sets(dev)?;
    let info = read_info(dev, sets[set as usize])
        .map_err(|e| e.to_string())?
        .ok_or_else(|| format!("bay{set} holds no committed record"))?;
    let names = layout.names();
    if names.len() != info.members.len() {
        return Err(format!(
            "bay{set}: its record lists {} files and the layout names {}",
            info.members.len(),
            names.len()
        ));
    }
    Ok((
        set_dir(set),
        names
            .into_iter()
            .zip(info.members.iter().map(|(len, _)| *len))
            .collect(),
    ))
}

/// Lays out each empty set's directories in the form every install writes (the kept entries alone
/// in their sectors, then `reserve`), so that no install ever rewrites the sector that holds the
/// record's entry or a subdirectory's `.` and `..`: the image builder's step after the empty
/// records. A set that holds a slot is left as it is.
pub fn lay_out_empty_sets<D: Sectors + ReadAt>(dev: &mut D, layout: &Layout) -> Result<(), String> {
    let dirs = layout.subdirs();
    let dirs: Vec<&str> = dirs.iter().map(String::as_str).collect();
    for (set, lba) in place_sets(dev)?.into_iter().enumerate() {
        let info = read_info(dev, lba)
            .map_err(|e| e.to_string())?
            .ok_or_else(|| format!("{}: no record", set_dir(set as u8)))?;
        if info.slot.is_none() {
            bayfat::write_set(dev, &set_dir(set as u8), INFO_NAME, info.region, &dirs, &[])?;
        }
    }
    Ok(())
}

/// Writes each set's empty record over the region its `reserve` holds: the image builder's last
/// step before the first install. The region is read from the volume the builder made.
pub fn write_empty_records<D: Sectors + ReadAt>(dev: &mut D) -> Result<(), String> {
    let v = bootfat::volume(dev).map_err(|e| e.to_string())?;
    let cb = v.spc * SECTOR as u64;
    let lbas = place_sets(dev)?;
    for (set, lba) in lbas.into_iter().enumerate() {
        let path = format!("{}/{}", set_dir(set as u8), bayfat::RESERVE);
        let size = bootfat::size_of_path(dev, &path).map_err(|e| format!("{path}: {e}"))?;
        let found = bootfat::locate_path(dev, &path, size).map_err(|e| format!("{path}: {e}"))?;
        let start = (found.first_lba - v.data_start) / v.spc + 2;
        let region = Region {
            start,
            clusters: size / cb,
        };
        region.check(&v)?;
        Pair::at(lba)
            .write(dev, Kind::BAY_INFO, &Info::empty(region).encode())
            .map_err(|e| e.to_string())?;
    }
    Ok(())
}

/// Test seam (feature `testing`, and this crate's own tests): `img` with every set's record
/// rewritten in the form of layout version 5: `bay0` committed to `slot` (its name's length, the
/// name, each role's length and SHA-256), the others empty (`[0]`). The result is a partition another
/// layout version made, which [`records_version`] refuses by name.
#[cfg(any(test, feature = "testing"))]
pub fn as_layout_5(img: &[u8], slot: &str) -> Vec<u8> {
    let mut dev = Mem(img.to_vec());
    let sets = place_sets(&mut dev).unwrap();
    for (set, lba) in sets.into_iter().enumerate() {
        let payload = if set == 0 {
            let mut out = vec![slot.len() as u8];
            out.extend_from_slice(slot.as_bytes());
            for i in 0..5u64 {
                out.extend_from_slice(&(4096 * (i + 1)).to_le_bytes());
                out.extend_from_slice(&[i as u8; 32]);
            }
            out
        } else {
            vec![0]
        };
        Pair::at(lba)
            .write(&mut dev, Kind::BAY_INFO, &payload)
            .unwrap();
    }
    dev.0
}

/// An in-memory partition for [`as_layout_5`].
#[cfg(any(test, feature = "testing"))]
struct Mem(Vec<u8>);

#[cfg(any(test, feature = "testing"))]
impl ReadAt for Mem {
    fn read_at(&mut self, offset: u64, buf: &mut [u8]) -> std::io::Result<()> {
        let at = offset as usize;
        buf.copy_from_slice(&self.0[at..at + buf.len()]);
        Ok(())
    }
}

#[cfg(any(test, feature = "testing"))]
impl Sectors for Mem {
    fn read(&mut self, lba: u64, buf: &mut crate::twocopy::Sector) -> std::io::Result<()> {
        let at = lba as usize * SECTOR;
        buf.copy_from_slice(&self.0[at..at + SECTOR]);
        Ok(())
    }

    fn write(&mut self, lba: u64, buf: &crate::twocopy::Sector) -> std::io::Result<()> {
        let at = lba as usize * SECTOR;
        self.0[at..at + SECTOR].copy_from_slice(buf);
        Ok(())
    }
}

