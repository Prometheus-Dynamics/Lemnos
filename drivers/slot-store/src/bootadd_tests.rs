#[test]
fn a_broken_allocator_is_refused_by_the_write_list_check_before_anything_is_given_back() {
    let parts = small_parts();
    let old = small_old(Vec::new());
    let owned = payloads(&parts, 10);
    let members = refs(&owned);
    let req = request("ours-10", 0, false, &members);
    // The mutation: the rule is right except once, when the fifth allocation (a record file) is
    // given the first cluster of the old kernel8.img.
    let victim = survey(&old).unwrap().find("kernel8.img").unwrap().first;
    let calls = std::cell::Cell::new(0u32);
    let broken = |free: &[bool], need: u64| {
        calls.set(calls.get() + 1);
        if calls.get() == 5 {
            Some(victim)
        } else {
            first_fit(free, need)
        }
    };
    let err = add_to_with(&parts, &old, &req, &broken).unwrap_err();
    assert!(
        err.contains(&format!(
            "would touch an existing file's cluster: cluster {victim} belongs to KERNEL8.IMG"
        )) && err.ends_with("the edit is refused and nothing was written"),
        "{err}"
    );
    // A subtler one: the first run is given one cluster too low, so the first new file starts on
    // the last cluster of the last old file.
    let calls = std::cell::Cell::new(0u32);
    let off_by_one = |free: &[bool], need: u64| {
        calls.set(calls.get() + 1);
        first_fit(free, need).map(|c| if calls.get() == 1 { c - 1 } else { c })
    };
    let err = add_to_with(&parts, &old, &req, &off_by_one).unwrap_err();
    assert!(
        err.contains("would touch an existing file's cluster: cluster 303 belongs to KERNEL8.IMG"),
        "{err}"
    );
    // The real rule on the same inputs passes.
    add_to_with(&parts, &old, &req, &first_fit).unwrap();
}

