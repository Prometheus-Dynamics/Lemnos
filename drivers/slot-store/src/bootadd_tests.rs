//! Tests of adding this system's boot files to a dump of another system's boot partition. The old
//! system is [`fatimage::foreign_system`]: the reference board's geometry, 44 files of the sizes
//! such a partition holds, seeded contents. The refusals run on a small volume.

use super::*;
use crate::bays::{Info, Layout};
use crate::fatadd::{Class, Existing, first_fit, survey};
use crate::fatimage::{self, FOREIGN_SLOT, foreign_system, seeded};
use sha2::{Digest, Sha256};

/// The reference board's bays, and the root text a board's generator gives (stand-ins).
fn board_parts() -> Parts {
    parts_of(Layout::new([11_534_336, 1_048_576, 90_112, 4096, 4096]).unwrap())
}

/// The same board declaring two firmware overlays, whose long names share their first six letters.
fn overlay_parts() -> Parts {
    let names = ["disable-bt-pi5".to_string(), "disable-wifi-pi5".to_string()];
    let lines = [
        "dtoverlay=disable-bt-pi5".to_string(),
        "dtoverlay=disable-wifi-pi5".to_string(),
    ];
    let config = bays::config_digest(&lines);
    parts_of(
        Layout::new([11_534_336, 1_048_576, 90_112, 4096, 4096])
            .unwrap()
            .with_firmware(&names, config),
    )
}

/// Small bays, for the small volume.
fn small_parts() -> Parts {
    parts_of(Layout::new([64 * 1024, 16 * 1024, 8192, 4096, 4096]).unwrap())
}

fn parts_of(layout: Layout) -> Parts {
    Parts {
        family: Family::Tryboot,
        layout,
        root: vec![
            ("slot-layout.toml", b"version = 6\n".to_vec()),
            (
                "config.txt",
                b"# Generated by lemnos-ctl test\nkernel_watchdog_timeout=15\ninclude default.txt\n".to_vec(),
            ),
            (
                "tryboot.txt",
                b"# Generated by lemnos-ctl test\nkernel_watchdog_timeout=15\ninclude trial.txt\n".to_vec(),
            ),
        ],
    }
}

/// A slot's members for `parts`, seeded by `seed`: each well inside its bay.
fn payloads(parts: &Parts, seed: u64) -> Vec<Vec<u8>> {
    (0..parts.layout.count())
        .map(|i| {
            let bay = parts.layout.member_bytes(i) as usize;
            if i == 3 {
                format!("console=serial0,115200 root=lemnos seed={seed}\n").into_bytes()
            } else {
                seeded(seed * 100 + i as u64, bay - bay / 5 - 7)
            }
        })
        .collect()
}

fn refs(p: &[Vec<u8>]) -> Vec<&[u8]> {
    p.iter().map(Vec::as_slice).collect()
}

fn request<'a>(
    slot: &'a str,
    set: u8,
    replace_trial: bool,
    payloads: &'a [&'a [u8]],
) -> Request<'a> {
    Request {
        slot,
        set,
        replace_trial,
        payloads,
    }
}

/// Every file of a volume: its entry (path, first cluster, size, chain, place of its directory
/// entry) and its bytes.
fn contents(image: &[u8]) -> Vec<(Existing, Vec<u8>)> {
    let sv = survey(image).unwrap();
    let mut mem = Mem(image.to_vec());
    sv.entries
        .iter()
        .filter(|e| !e.is_dir)
        .map(|e| {
            (
                e.clone(),
                bootfat::read_file(&mut mem, &e.path, u64::MAX).unwrap(),
            )
        })
        .collect()
}

/// The 32 bytes of the directory entry of `path`.
fn entry_bytes(image: &[u8], path: &str) -> Vec<u8> {
    let at = survey(image).unwrap().find(path).unwrap().at;
    image[at..at + 32].to_vec()
}

fn bad_lines(findings: &[Finding]) -> Vec<&str> {
    findings
        .iter()
        .filter(|f| !f.ok)
        .map(|f| f.text.as_str())
        .collect()
}

/// Asserts what every add must leave: each old file with the same entry, chain and bytes; both FAT
/// copies equal; each new file one run of exactly its size.
fn assert_old_untouched_and_new_whole(old: &[u8], out: &Outcome) {
    let before = contents(old);
    let after = contents(&out.image);
    for (entry, bytes) in &before {
        if out
            .replaced
            .iter()
            .any(|r| r.name.eq_ignore_ascii_case(&entry.path))
        {
            continue;
        }
        let (now, now_bytes) = after
            .iter()
            .find(|(e, _)| e.path == entry.path)
            .unwrap_or_else(|| panic!("{} is still there", entry.path));
        assert_eq!(
            now, entry,
            "{}: the same entry, first cluster, size and chain",
            entry.path
        );
        assert!(now_bytes == bytes, "{}: byte-identical", entry.path);
    }
    let geo = survey(&out.image).unwrap().geo;
    let fat = geo.fat_sectors as usize * 512;
    let first = geo.reserved as usize * 512;
    assert!(
        out.image[first..first + fat] == out.image[first + fat..first + 2 * fat],
        "both FAT copies are equal"
    );
    let mut mem = Mem(out.image.clone());
    // The reserve shrinks when the install puts the files in: it is checked against its region by
    // the verification, not by the size it was added at.
    for a in out
        .added
        .iter()
        .filter(|a| !a.is_dir && !a.path.ends_with("/reserve"))
    {
        let found = bootfat::locate_path(&mut mem, &a.path, a.size)
            .unwrap_or_else(|e| panic!("{}: {e}", a.path));
        assert_eq!(found.first_lba, geo.cluster_lba(a.first), "{}", a.path);
        assert_eq!(
            a.clusters,
            a.size.div_ceil(geo.cluster_bytes() as u64).max(1),
            "{}",
            a.path
        );
    }
}

#[test]
fn the_stand_in_has_the_reference_boards_geometry_and_44_files() {
    let old = foreign_system();
    let sv = survey(&old).unwrap();
    let g = sv.geo;
    assert_eq!(
        (
            g.spc,
            g.reserved,
            g.fats,
            g.root_entries,
            g.fat_sectors,
            g.total,
            g.clusters
        ),
        (4, 1, 2, 512, 158, 161_792, 40_360)
    );
    let files: Vec<&Existing> = sv.entries.iter().filter(|e| !e.is_dir).collect();
    assert_eq!(files.len(), 44);
    assert_eq!(
        files.iter().map(|e| u64::from(e.size)).sum::<u64>(),
        14_466_541
    );
    for (path, size) in [
        ("config.txt", 405),
        ("default.txt", 55),
        ("trial.txt", 55),
        ("tryboot.txt", 318),
    ] {
        assert_eq!(sv.find(path).unwrap().size, size, "{path}");
    }
    assert!(
        sv.find(&format!("slots/{FOREIGN_SLOT}/overlays/README"))
            .is_some()
    );
}

/// A path inside a bay set other than its record: what an install writes (the files and `reserve`).
fn set_content(path: &str) -> bool {
    let p = path.to_ascii_lowercase();
    p.starts_with("slots/bay") && !p.ends_with("/bayinfo.rec")
}

#[test]
fn the_files_added_are_the_builders_own_without_default_txt_and_config_txt() {
    let parts = overlay_parts();
    let owned = payloads(&parts, 1);
    // The fresh image of the same board: its files are the list, plus the two that are kept.
    let fresh = bootimage::build(&parts, 161_792 * 512, "a", &refs(&owned)).unwrap();
    // A set's files and its reserve are the install's, not the builder's list.
    let mut built: Vec<(String, u64)> = survey(&fresh)
        .unwrap()
        .entries
        .iter()
        .filter(|e| !e.is_dir && !set_content(&e.path))
        .map(|e| (e.path.to_ascii_lowercase(), u64::from(e.size)))
        .collect();
    let mut listed: Vec<(String, u64)> = file_list(&parts)
        .unwrap()
        .into_iter()
        .map(|(p, s)| (p.to_ascii_lowercase(), s))
        .collect();
    assert!(
        !listed
            .iter()
            .any(|(p, _)| p == "default.txt" || p == "config.txt")
    );
    listed.push(("default.txt".into(), 1024));
    listed.push(("config.txt".into(), parts.root[1].1.len() as u64));
    built.sort();
    listed.sort();
    assert_eq!(listed, built);
    // And an add to a volume with none of them adds exactly the list, in its order.
    let old = foreign_system();
    let out = add_to(&parts, &old, &request("ours-1", 0, true, &refs(&owned))).unwrap();
    let added: Vec<(String, u64)> = out
        .added
        .iter()
        .filter(|a| !a.is_dir && !set_content(&a.path))
        .map(|a| (a.path.clone(), a.size))
        .chain(out.replaced.iter().map(|r| (r.name.clone(), r.size)))
        .collect();
    let mut want = file_list(&parts).unwrap();
    let mut got = added;
    want.sort();
    got.sort();
    assert_eq!(got, want);
}

#[test]
fn adding_to_the_old_system_leaves_every_old_file_at_its_clusters_and_our_reader_opens_every_new_one()
 {
    let parts = overlay_parts();
    let old = foreign_system();
    let owned = payloads(&parts, 1);
    let out = add_to(&parts, &old, &request("ours-1", 0, false, &refs(&owned))).unwrap();
    assert_eq!(out.mode, Mode::Added);
    assert_old_untouched_and_new_whole(&old, &out);
    // The two files the old system boots from: the same directory entries, byte for byte.
    for name in ["config.txt", "default.txt", "trial.txt", "tryboot.txt"] {
        assert_eq!(
            entry_bytes(&out.image, name),
            entry_bytes(&old, name),
            "{name}"
        );
    }
    assert!(out.replaced.is_empty());
    assert_eq!(out.left, ["trial.txt", "tryboot.txt"]);

    // Our reader: every set placed, set 0 committed with the slot, the others empty.
    let mut mem = Mem(out.image.clone());
    let sets = bays::place_sets(&mut mem).unwrap();
    let info = bays::read_info(&mut mem, sets[0])
        .unwrap()
        .expect("bay0 has a record");
    assert_eq!(info.slot.as_deref(), Some("ours-1"));
    for (path, bytes) in parts.layout.written(&refs(&owned)).unwrap() {
        assert_eq!(
            bootfat::read_file(&mut mem, &format!("slots/bay0/{path}"), u64::MAX).unwrap(),
            bytes,
            "{path} is exact"
        );
    }
    for set in [1, 2] {
        let info = bays::read_info(&mut mem, sets[set]).unwrap();
        assert_eq!(info.and_then(|i| i.slot), None, "bay{set} is empty");
    }
    assert_eq!(bays::set_of_slot(&mut mem, "ours-1").unwrap(), Some(0));
    // The bay volume the boot-file check opens (the bays and reason.rec), and the layout it reads.
    let volume = crate::boot_raw::BayVolume::on(Mem(out.image.clone())).unwrap();
    // The device reads the names from the member list; its caps are the regions' (it needs none).
    assert_eq!(volume.bay_layout().names(), parts.layout.names());
    // Every record and pointer by the 8.3 name the raw locator looks up.
    for name in [
        crate::boot_raw::TRIAL_FILE,
        crate::boot_raw::REASON_FILE,
        crate::boot_raw::EPISODES_FILE,
        crate::boot_raw::COUNT_FILE,
        b"SECURE  REC",
        crate::boot_raw::PREVIOUS_POINTER,
    ] {
        bootfat::locate(&mut mem, name, 1024)
            .unwrap_or_else(|e| panic!("{}: {e}", String::from_utf8_lossy(name)));
    }
    // The firmware overlays of the slot's set, by the paths the layout gives (their long names
    // share six letters, so their short names differ by ~N), each at its exact size.
    for (k, name) in ["disable-bt-pi5", "disable-wifi-pi5"].iter().enumerate() {
        let path = format!("slots/bay0/overlays/{name}.dtbo");
        bootfat::locate_path(&mut mem, &path, owned[5 + k].len() as u64)
            .unwrap_or_else(|e| panic!("{path}: {e}"));
    }

    // The verification: exactly the expected lines are BAD, and they are these.
    assert_eq!(
        out.expected_bad,
        ["default.txt", "config.txt", "trial.txt", "tryboot.txt"]
    );
    let again = bootimage::verify(&mut mem, &parts);
    assert_eq!(again, out.findings);
    let config = parts.root[1].1.len();
    let tryboot = parts.root[2].1.len();
    assert_eq!(
        bad_lines(&again),
        [
            "default.txt: record file is 55 bytes, expected 1024: the image is not ours"
                .to_string(),
            "trial.txt: record file is 55 bytes, expected 1024: the image is not ours".to_string(),
            format!("config.txt: file is 405 bytes, more than the {config} allowed"),
            format!("tryboot.txt: file is 318 bytes, more than the {tryboot} allowed"),
        ]
    );
    assert!(
        again
            .iter()
            .any(|f| f.ok && f.text == "bay0 (ours-1): its 8 files match their record")
    );
    // The free map: shorter by what was added. Each region starts on a whole FAT sector, so it
    // may leave one free gap before it: at most one run more per set.
    let taken: u64 = out.added.iter().map(|a| a.clusters).sum();
    assert_eq!(out.free_after.clusters, out.free_before.clusters - taken);
    assert_eq!(out.free_before.runs, 1);
    assert!(
        out.free_after.runs <= 1 + u64::from(bays::SETS),
        "{:?}",
        out.free_after
    );
}

#[test]
fn the_changed_sector_list_is_complete_and_exact_and_the_undo_file_restores_the_dump() {
    let parts = board_parts();
    let old = foreign_system();
    let owned = payloads(&parts, 2);
    let out = add_to(&parts, &old, &request("ours-2", 0, true, &refs(&owned))).unwrap();
    // Only the listed sectors, applied to a fresh copy of the old volume, give the result.
    let mut applied = old.clone();
    let mut listed = vec![false; old.len() / 512];
    for c in &out.changes {
        let (from, to) = (c.lba as usize * 512, (c.lba + c.count) as usize * 512);
        applied[from..to].copy_from_slice(&out.image[from..to]);
        assert_eq!(c.old, <[u8; 32]>::from(Sha256::digest(&old[from..to])));
        assert_eq!(
            c.new,
            <[u8; 32]>::from(Sha256::digest(&out.image[from..to]))
        );
        for s in c.lba..c.lba + c.count {
            assert!(!listed[s as usize], "sector {s} is listed once");
            listed[s as usize] = true;
        }
    }
    assert!(applied == out.image, "the list is complete");
    // Exact: a sector is listed if and only if it differs.
    for (s, &is_listed) in listed.iter().enumerate() {
        let differs = old[s * 512..(s + 1) * 512] != out.image[s * 512..(s + 1) * 512];
        assert_eq!(is_listed, differs, "sector {s}");
    }
    // The classes: both FAT copies, the root, the old `slots` directory, new directories and files.
    // No sector of an old file's cluster, and nothing before the first FAT.
    let sv = survey(&old).unwrap();
    for c in &out.changes {
        assert!(
            c.lba >= sv.geo.reserved,
            "the boot sector is not in the list"
        );
        if c.lba >= sv.geo.data_start {
            for s in c.lba..c.lba + c.count {
                let cluster = (s - sv.geo.data_start) / sv.geo.spc + 2;
                match c.class {
                    Class::NewFile | Class::NewDir => {
                        assert!(sv.free[cluster as usize], "sector {s}")
                    }
                    Class::Dir => assert!(sv.owner_of(cluster).unwrap().is_dir, "sector {s}"),
                    other => panic!("sector {s} is in the data area with class {other}"),
                }
            }
        }
    }
    let dirs: Vec<&crate::fatadd::Change> = out
        .changes
        .iter()
        .filter(|c| c.class == Class::Dir)
        .collect();
    assert_eq!(dirs.len(), 1, "one old directory gained entries: slots");
    assert_eq!(
        dirs[0].lba,
        sv.geo.cluster_lba(sv.find("slots").unwrap().chain[0])
    );
    // The undo file gives the original back, byte for byte.
    assert!(fatadd::apply_undo(&out.image, &out.undo).unwrap() == old);
    // The same inputs give the same three outputs.
    let again = add_to(&parts, &old, &request("ours-2", 0, true, &refs(&owned))).unwrap();
    assert!(again.image == out.image && again.undo == out.undo);
    assert_eq!(again.changes, out.changes);
    assert_eq!(again.added, out.added);
}

#[test]
fn replace_trial_rewrites_the_two_entries_in_place_and_its_inverse_restores_the_dump() {
    let parts = board_parts();
    let old = foreign_system();
    let owned = payloads(&parts, 3);
    let out = add_to(&parts, &old, &request("ours-3", 1, true, &refs(&owned))).unwrap();
    assert_old_untouched_and_new_whole(&old, &out);
    assert!(out.left.is_empty());
    assert_eq!(out.expected_bad, ["default.txt", "config.txt"]);
    assert_eq!(bad_lines(&out.findings).len(), 2);
    let before = survey(&old).unwrap();
    let after = survey(&out.image).unwrap();
    let mut mem = Mem(out.image.clone());
    let names: Vec<&str> = out.replaced.iter().map(|r| r.name.as_str()).collect();
    assert_eq!(names, ["trial.txt", "tryboot.txt"]);
    for r in &out.replaced {
        let was = before.find(&r.name).unwrap();
        let now = after.find(&r.name).unwrap();
        assert_eq!(now.at, was.at, "{}: the same slot in the directory", r.name);
        // The entry's name, attributes and times are the old system's; its place and size are new.
        let (a, b) = (&old[was.at..was.at + 32], &out.image[was.at..was.at + 32]);
        assert_eq!(a[..20], b[..20]);
        assert_eq!(a[22..26], b[22..26]);
        // The old content: its hash is reported, its clusters are free and still hold it.
        let old_bytes = bootfat::read_file(&mut Mem(old.clone()), &r.name, u64::MAX).unwrap();
        assert_eq!(r.old_sha256, <[u8; 32]>::from(Sha256::digest(&old_bytes)));
        assert_eq!((r.old_size, r.old_first), (u64::from(was.size), was.first));
        for &c in &was.chain {
            assert!(after.free[c as usize], "{}: cluster {c} is free", r.name);
            assert!(
                before.geo.entry(&out.image, 1, c) == 0,
                "in the second copy too"
            );
        }
        let at = before.geo.cluster_lba(was.first) as usize * 512;
        assert!(out.image[at..at + old_bytes.len()] == old_bytes[..]);
        bootfat::locate_path(&mut mem, &r.name, r.size).unwrap();
    }
    // trial.txt is our two-sector pointer and names the set the slot went into.
    let lba = bootfat::locate_path(&mut mem, "trial.txt", 1024)
        .unwrap()
        .first_lba;
    assert_eq!(bays::read_pointer(&mut mem, lba).unwrap(), Some(1));
    assert_eq!(
        mem.0[lba as usize * 512..lba as usize * 512 + 1024],
        firmware::pointer_file("bay1").unwrap()[..]
    );
    assert_eq!(
        bootfat::read_file(&mut mem, "tryboot.txt", u64::MAX).unwrap(),
        parts.root[2].1
    );
    assert!(
        out.findings
            .iter()
            .any(|f| f.ok && f.text == "trial.txt: names bay1")
    );
    assert!(
        out.findings
            .iter()
            .any(|f| f.ok && f.text == "tryboot.txt: holds its generated bytes")
    );
    // The slot is in set 1, sets 0 and 2 are empty.
    let sets = bays::place_sets(&mut mem).unwrap();
    assert_eq!(
        bays::read_info(&mut mem, sets[0])
            .unwrap()
            .and_then(|i| i.slot),
        None
    );
    assert_eq!(
        bays::read_info(&mut mem, sets[1])
            .unwrap()
            .and_then(|i| i.slot),
        Some("ours-3".to_string())
    );
    // The inverse.
    assert!(fatadd::apply_undo(&out.image, &out.undo).unwrap() == old);
}

#[test]
fn a_second_slot_goes_into_set_1_and_set_0_is_byte_identical_afterwards() {
    let parts = board_parts();
    let old = foreign_system();
    let first = payloads(&parts, 4);
    let second = payloads(&parts, 5);
    let one = add_to(&parts, &old, &request("ours-4", 0, false, &refs(&first))).unwrap();
    let two = add_to(
        &parts,
        &one.image,
        &request("ours-5", 1, true, &refs(&second)),
    )
    .unwrap();
    assert_eq!(two.mode, Mode::InstalledOnly);
    assert!(two.added.is_empty(), "no file is added: {:?}", two.added);
    // Everything the first run left, the old system's files and ours, is where and what it was.
    assert_old_untouched_and_new_whole(&old, &two);
    let mut a = Mem(one.image.clone());
    let mut b = Mem(two.image.clone());
    assert_eq!(
        bays::place_sets(&mut a).unwrap(),
        bays::place_sets(&mut b).unwrap(),
        "every record is at the same sector"
    );
    // Sets 0 and 2 own the same sectors and hold the same bytes there.
    for set in [0u8, 2] {
        let own = bays::set_sectors(&mut a, set).unwrap();
        assert_eq!(own, bays::set_sectors(&mut b, set).unwrap());
        for lba in own {
            let at = lba as usize * 512;
            assert!(
                one.image[at..at + 512] == two.image[at..at + 512],
                "bay{set} sector {lba}"
            );
        }
    }
    // Our reader reads both slots.
    assert_eq!(bays::set_of_slot(&mut b, "ours-4").unwrap(), Some(0));
    assert_eq!(bays::set_of_slot(&mut b, "ours-5").unwrap(), Some(1));
    for (set, slot) in [(0, "ours-4"), (1, "ours-5")] {
        let head = format!("bay{set} ({slot}): its ");
        assert!(
            two.findings.iter().any(|f| f.ok
                && f.text.starts_with(&head)
                && f.text.ends_with("match their record")),
            "{head}: {:?}",
            two.findings
        );
    }
    // The changes: set 1's own sectors, and the trial pair replaced; nothing of set 0.
    let geo = survey(&old).unwrap().geo;
    let own: std::collections::HashSet<u64> =
        bays::set_sectors(&mut b, 1).unwrap().into_iter().collect();
    for c in two.changes.iter().filter(|c| c.class == Class::OwnFile) {
        assert!(
            (c.lba..c.lba + c.count).all(|l| own.contains(&l)),
            "sectors {}+{} are set 1's own",
            c.lba,
            c.count
        );
    }
    assert!(two.changes.iter().any(|c| c.class == Class::OwnFile));
    assert!(
        two.changes
            .iter()
            .all(|c| c.class != Class::Dir && c.class != Class::NewDir)
    );
    assert!(two.changes.iter().all(|c| c.lba >= geo.reserved));
    assert_eq!(two.replaced.len(), 2);
    let lba = bootfat::locate_path(&mut b, "trial.txt", 1024)
        .unwrap()
        .first_lba;
    assert_eq!(bays::read_pointer(&mut b, lba).unwrap(), Some(1));
    // Undo of the second run gives the first run's result; of both, the dump.
    let back = fatadd::apply_undo(&two.image, &two.undo).unwrap();
    assert!(back == one.image);
    assert!(fatadd::apply_undo(&back, &one.undo).unwrap() == old);

    // An install into a set that holds a slot, and of a slot that is already in a set: refused.
    let err = add_to(
        &parts,
        &two.image,
        &request("ours-6", 1, false, &refs(&second)),
    )
    .unwrap_err();
    assert_eq!(
        err,
        "bay1 already holds the slot ours-5: --add-to installs into an empty bay set only: nothing was written"
    );
    let err = add_to(
        &parts,
        &two.image,
        &request("ours-4", 2, false, &refs(&first)),
    )
    .unwrap_err();
    assert_eq!(
        err,
        "the slot ours-4 is already in bay0: nothing was written"
    );
}

#[test]
fn bayinfo_rec_names_the_set_s_own_region_the_slot_and_each_file() {
    let parts = board_parts();
    let old = foreign_system();
    let owned = payloads(&parts, 6);
    let zero = add_to(&parts, &old, &request("ours-6", 0, false, &refs(&owned))).unwrap();
    let mut a = Mem(zero.image.clone());
    let sets = bays::place_sets(&mut a).unwrap();
    let info = bays::read_info(&mut a, sets[0]).unwrap().unwrap();
    let written = parts.layout.written(&refs(&owned)).unwrap();
    assert_eq!(info, Info::committed(info.region, "ours-6", &written));
    // The pair's newer copy is the committed record (the older is the emptied one of step a).
    let rec = bootfat::read_file(&mut a, &info_path(0), 1024).unwrap();
    let copies: Vec<_> = rec
        .chunks(512)
        .filter_map(|c| crate::twocopy::decode(c.try_into().unwrap()))
        .collect();
    assert!(
        copies
            .iter()
            .any(|c| c.kind == crate::twocopy::Kind::BAY_INFO && c.payload == info.encode()),
        "the committed record is one of the pair's copies"
    );
    // The region is the set's own: aligned, and holding the set's reserve.
    assert_eq!(info.region.start % crate::bayfat::FAT16_PER_SECTOR, 0);
    let own = bays::set_sectors(&mut a, 0).unwrap();
    let found =
        bootfat::locate_path(&mut a, "slots/bay0/kernel8.img", owned[0].len() as u64).unwrap();
    assert!(own.contains(&found.first_lba));
    // Another set's record names a different region.
    let other = bays::read_info(&mut a, sets[1]).unwrap().unwrap();
    assert_ne!(other.region, info.region);
}

