#[test]
fn a_volume_without_the_trial_pair_gets_ours_and_one_that_has_ours_keeps_it() {
    let parts = small_parts();
    let old = small_old(Vec::new());
    let owned = payloads(&parts, 12);
    // No trial.txt and no tryboot.txt on the old volume: both are added, without --replace-trial.
    let out = add_to(&parts, &old, &request("ours-12", 0, false, &refs(&owned))).unwrap();
    assert!(
        out.added
            .iter()
            .any(|a| a.path == "trial.txt" && a.size == 1024)
    );
    assert!(out.added.iter().any(|a| a.path == "tryboot.txt"));
    assert!(out.replaced.is_empty() && out.left.is_empty());
    assert_eq!(out.expected_bad, ["default.txt", "config.txt"]);
    // A second slot without --replace-trial: trial.txt is ours and names bay0; it is left, and it
    // is not a BAD line, because it reads as a pointer.
    let second = payloads(&parts, 13);
    let two = add_to(
        &parts,
        &out.image,
        &request("ours-13", 1, false, &refs(&second)),
    )
    .unwrap();
    assert_eq!(two.left, ["trial.txt"]);
    assert_eq!(two.expected_bad, ["default.txt", "config.txt"]);
    assert!(
        two.findings
            .iter()
            .any(|f| f.ok && f.text == "trial.txt: names bay0")
    );
    // With --replace-trial it names the new set.
    let two = add_to(
        &parts,
        &out.image,
        &request("ours-13", 1, true, &refs(&second)),
    )
    .unwrap();
    assert_eq!(two.replaced.len(), 1);
    assert!(
        two.findings
            .iter()
            .any(|f| f.ok && f.text == "trial.txt: names bay1")
    );
    assert!(fatadd::apply_undo(&two.image, &two.undo).unwrap() == out.image);
}

