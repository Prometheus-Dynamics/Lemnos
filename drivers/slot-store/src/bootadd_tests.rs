#[test]
fn a_name_of_ours_that_already_exists_is_refused_by_name() {
    let parts = small_parts();
    let owned = payloads(&parts, 7);
    let members = refs(&owned);
    let req = request("ours-7", 0, false, &members);
    // A record's name, with other content and size.
    let old = small_old(vec![Node::File {
        name: "reason.rec",
        data: seeded(3, 77),
    }]);
    let err = add_to(&parts, &old, &req).unwrap_err();
    assert_eq!(
        err,
        "reason.rec is already on the volume and is not a file of ours (record file is 77 bytes, expected 1024: the image is not ours): nothing was written"
    );
    // A bay's name, as a file of the right size in two pieces.
    let mut old = small_old(vec![Node::Dir {
        name: "slots",
        children: vec![Node::Dir {
            name: "bay0",
            children: vec![Node::File {
                name: "cmdline.txt",
                data: seeded(4, 4096),
            }],
        }],
    }]);
    let sv = survey(&old).unwrap();
    let chain = sv.find("slots/bay0/cmdline.txt").unwrap().chain.clone();
    // The file's 8 clusters, with the fourth one moved to a free cluster far away.
    let far = 9000u64;
    for copy in 0..sv.geo.fats {
        for (c, next) in [
            (chain[2], far as u16),
            (far, chain[4] as u16),
            (chain[3], 0),
        ] {
            let at = ((sv.geo.reserved + copy * sv.geo.fat_sectors) * 512 + c * 2) as usize;
            old[at..at + 2].copy_from_slice(&next.to_le_bytes());
        }
    }
    let err = add_to(&parts, &old, &req).unwrap_err();
    assert_eq!(
        err,
        "slots/bay0 is already on the volume and is not a bay set of ours (it holds no bayinfo.rec): nothing was written"
    );
    // A part of our files, as no run of the tool leaves them.
    let old = small_old(vec![Node::File {
        name: "reason.rec",
        data: vec![0; 1024],
    }]);
    let err = add_to(&parts, &old, &req).unwrap_err();
    assert_eq!(
        err,
        "reason.rec is already on the volume and slot-layout.toml is not: the dump holds a part of our files, which no run of this tool leaves: nothing was written"
    );
}

#[test]
fn a_dump_with_no_run_for_a_bay_file_is_refused_by_name_and_one_with_a_later_run_takes_it_whole() {
    let parts = small_parts();
    let owned = payloads(&parts, 8);
    let members = refs(&owned);
    let req = request("ours-8", 0, false, &members);
    let clusters = survey(&small_old(Vec::new())).unwrap().geo.clusters as usize;
    // The kernel bay is 128 clusters. Free: runs of 100 and 120 between kept files, then `tail`.
    let build = |tail: usize| {
        let used = 1 + 1 + 300 + 100 + 4 + 120 + 4;
        let mut old = small_old(vec![
            Node::File {
                name: "hole0.bin",
                data: seeded(3, 100 * 512),
            },
            Node::File {
                name: "keep0.bin",
                data: seeded(4, 4 * 512),
            },
            Node::File {
                name: "hole1.bin",
                data: seeded(5, 120 * 512),
            },
            Node::File {
                name: "keep1.bin",
                data: seeded(6, 4 * 512),
            },
            Node::File {
                name: "fill.bin",
                data: seeded(7, (clusters - used - tail) * 512),
            },
        ]);
        for name in ["hole0.bin", "hole1.bin"] {
            let sv = survey(&old).unwrap();
            let e = sv.find(name).unwrap().clone();
            old[e.at] = 0xE5;
            for c in e.chain {
                for copy in 0..sv.geo.fats {
                    let at = ((sv.geo.reserved + copy * sv.geo.fat_sectors) * 512 + c * 2) as usize;
                    old[at..at + 2].copy_from_slice(&[0, 0]);
                }
            }
        }
        old
    };
    // 220 clusters free and no run of 128.
    let old = build(0);
    assert_eq!(
        survey(&old).unwrap().free_map(),
        FreeMap {
            clusters: 220,
            runs: 2,
            longest: 120
        }
    );
    let err = add_to(&parts, &old, &req).unwrap_err();
    assert_eq!(
        err,
        "slots/bay0/reserve: the bay's region needs one run of 256 free clusters starting on a multiple of 256 (whole FAT sectors), and the volume has none: nothing is ever moved to make room: nothing was written"
    );
    // The same volume with a long run at its end: each kernel bay is found there, whole.
    let old = build(1000);
    let out = add_to(&parts, &old, &req).unwrap();
    assert_old_untouched_and_new_whole(&old, &out);
    let last = clusters as u64 + 2;
    let regions: Vec<&Added> = out
        .added
        .iter()
        .filter(|a| a.path.ends_with("/reserve"))
        .collect();
    assert_eq!(regions.len(), 3);
    for r in &regions {
        assert!(
            r.first >= last - 1000 && r.first % 256 == 0 && r.clusters % 256 == 0,
            "{}: {} +{}",
            r.path,
            r.first,
            r.clusters
        );
    }
    // The small files before it went into the first hole.
    assert!(out.added[0].first < 500, "{:?}", out.added[0]);
    assert_eq!(bad_lines(&out.findings).len(), 2);
}

#[test]
