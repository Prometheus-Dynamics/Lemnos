#[test]
fn the_built_image_pre_creates_the_restart_count_baseline_empty() {
    // The count's baseline is a two-copy record at the root, as trial.rec and episodes.rec are: both
    // copies all zero (no valid copy), so it reads as unknown until a baseline is written.
    let parts = tryboot_parts();
    let total = 161_792u64 * 512;
    let image = build(&parts, total, "a", &refs(&payloads())).unwrap();
    let mut mem = Mem(image.clone());
    let found =
        bootfat::locate_path(&mut mem, BASELINE_FILE, crate::boot_raw::RECORD_BYTES).unwrap();
    let at = found.first_lba as usize * 512;
    let len = crate::boot_raw::RECORD_BYTES as usize;
    assert_eq!(BASELINE_FILE, "count.rec");
    assert!(
        image[at..at + len].iter().all(|&b| b == 0),
        "the baseline record is empty"
    );
}

#[test]
fn the_three_pointers_name_the_bay_the_first_slot_is_installed_in() {
    let parts = tryboot_parts();
    let total = 161_792u64 * 512;
    let image = build(&parts, total, "a", &refs(&payloads())).unwrap();
    let mut mem = Mem(image.clone());
    let installed = bays::set_of_slot(&mut mem, &parts.layout, "a").unwrap();
    assert_eq!(installed, Some(FIRST_SET));
    for name in POINTERS {
        let found = bootfat::locate_path(
            &mut Mem(image.clone()),
            name,
            firmware::POINTER_FILE_BYTES as u64,
        )
        .unwrap();
        let mut file = vec![0u8; firmware::POINTER_FILE_BYTES];
        let at = found.first_lba as usize * 512;
        file.copy_from_slice(&image[at..at + firmware::POINTER_FILE_BYTES]);
        let mut bytes = [0u8; firmware::POINTER_FILE_BYTES];
        bytes.copy_from_slice(&file);
        assert_eq!(
            firmware::pointer_file_slot(&bytes).as_deref(),
            Some(bays::set_name(FIRST_SET).as_str()),
            "{name} names the installed bay"
        );
    }
}

/// A new image on a file, as the device's node would be: the record's first sector and the switch's
/// view through [`crate::security::BootSwitch`].
fn switch_image(name: &str) -> (std::path::PathBuf, std::path::PathBuf) {
    let dir = std::env::temp_dir().join(format!("lemnos-switch-{}-{name}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    let parts = tryboot_parts();
    let owned = payloads();
    let image = build(&parts, min_size(&parts).unwrap(), "a", &refs(&owned)).unwrap();
    let node = dir.join("boot.img");
    std::fs::write(&node, image).unwrap();
    (dir, node)
}

#[test]
fn a_new_image_reads_the_switch_off_at_generation_zero_and_round_trips_on_and_off() {
    use crate::security::{BootSwitch, Store};
    let (dir, node) = switch_image("round-trip");
    let switch = BootSwitch::new(&node);
    let first = switch.read().unwrap().unwrap();
    assert!(!first.on, "a new image reads off");
    let on = switch.write(true).unwrap();
    assert!(switch.read().unwrap().unwrap().on, "set on reads on");
    assert_eq!(switch.read().unwrap().unwrap().generation, on);
    let off = switch.write(false).unwrap();
    assert!(!switch.read().unwrap().unwrap().on, "set off reads off");
    assert!(
        off > on && on > first.generation,
        "each change is a newer generation"
    );
    let _ = std::fs::remove_dir_all(dir);
}

#[test]
fn a_torn_copy_of_the_switch_record_is_recovered_from_the_other_copy() {
    use crate::security::{BootSwitch, Store};
    let (dir, node) = switch_image("torn");
    let switch = BootSwitch::new(&node);
    switch.write(true).unwrap();
    let mut file = std::fs::OpenOptions::new()
        .read(true)
        .write(true)
        .open(&node)
        .unwrap();
    let name = crate::twocopy::Kind::SECURITY.file_name().unwrap();
    let first = crate::bootfat::locate(&mut file, name, crate::boot_raw::RECORD_BYTES)
        .unwrap()
        .first_lba;
    // Each copy is one sector; tear either one, and the switch still reads, from the other.
    for copy in 0..2u64 {
        let at = (first + copy) * 512;
        let saved = {
            use std::os::unix::fs::FileExt;
            let mut bytes = [0u8; 512];
            file.read_exact_at(&mut bytes, at).unwrap();
            bytes
        };
        {
            use std::os::unix::fs::FileExt;
            file.write_all_at(&[0u8; 512], at).unwrap();
        }
        assert!(
            switch.read().is_ok(),
            "copy {copy} torn: the other copy still reads"
        );
        {
            use std::os::unix::fs::FileExt;
            file.write_all_at(&saved, at).unwrap();
        }
    }
    let _ = std::fs::remove_dir_all(dir);
}

/// The first sector of the switch record's two copies on the node `node`.
fn switch_copies(node: &std::path::Path) -> u64 {
    let mut file = std::fs::File::open(node).unwrap();
    let name = crate::twocopy::Kind::SECURITY.file_name().unwrap();
    crate::bootfat::locate(&mut file, name, crate::boot_raw::RECORD_BYTES)
        .unwrap()
        .first_lba
}

/// Byte `at` of sector `lba` on `node`, and its value after `set`.
fn byte(node: &std::path::Path, lba: u64, at: usize) -> u8 {
    use std::os::unix::fs::FileExt;
    let mut one = [0u8; 1];
    std::fs::File::open(node)
        .unwrap()
        .read_exact_at(&mut one, lba * 512 + at as u64)
        .unwrap();
    one[0]
}

fn set(node: &std::path::Path, lba: u64, at: usize, value: u8) {
    use std::os::unix::fs::FileExt;
    std::fs::OpenOptions::new()
        .write(true)
        .open(node)
        .unwrap()
        .write_all_at(&[value], lba * 512 + at as u64)
        .unwrap();
}

#[test]
fn a_good_switch_record_checks_off_then_on() {
    use crate::security::{BootSwitch, Store};
    let (dir, node) = switch_image("check-good");
    let switch = BootSwitch::new(&node);
    let fresh = switch.check().expect("a fresh image's record reads");
    // The builder pre-creates both copies as off, at sequences 0 and 1: the newer one is read.
    assert!(!fresh.on && fresh.generation == 1, "good off: {fresh:?}");
    switch.write(true).unwrap();
    let on = switch.check().expect("a set record reads");
    assert!(on.on, "good on: {on:?}");
    let _ = std::fs::remove_dir_all(dir);
}

#[test]
fn a_missing_switch_record_is_missing_on_a_valid_volume() {
    use crate::security::{BootSwitch, RecordFault};
    let (dir, node) = switch_image("check-missing");
    // Rename the record's directory entry: the volume is still a valid FAT, with no SECURE.REC.
    let name = crate::twocopy::Kind::SECURITY.file_name().unwrap();
    let mut image = std::fs::read(&node).unwrap();
    let hits: Vec<usize> = image
        .windows(name.len())
        .enumerate()
        .filter(|(_, w)| *w == name)
        .map(|(at, _)| at)
        .collect();
    assert_eq!(hits.len(), 1, "one directory entry names the record");
    image[hits[0]] = b'X';
    std::fs::write(&node, &image).unwrap();
    assert_eq!(BootSwitch::new(&node).check(), Err(RecordFault::Missing));
    let _ = std::fs::remove_dir_all(dir);
}

#[test]
fn each_switch_record_copy_is_checked_alone_and_names_its_fault() {
    use crate::security::{BootSwitch, Store};
    let (dir, node) = switch_image("check-copies");
    let switch = BootSwitch::new(&node);
    switch.write(true).unwrap();
    let lba = switch_copies(&node);
    let copies = switch.copies().unwrap();
    assert_eq!(copies, [Ok(()), Ok(())], "both copies good on a new image");
    let before = byte(&node, lba, 9);
    set(&node, lba, 9, before ^ 0xFF);
    let copies = switch.copies().unwrap();
    assert!(
        copies[0].as_ref().unwrap_err().contains("CRC"),
        "the first copy names the CRC: {copies:?}"
    );
    assert_eq!(copies[1], Ok(()), "the second copy is still good");
    assert!(
        switch.check().is_ok(),
        "the device still reads one good copy"
    );
    set(&node, lba, 9, before);
    let _ = std::fs::remove_dir_all(dir);
}

#[test]
fn one_damaged_switch_record_copy_reads_from_the_other() {
    use crate::security::{BootSwitch, Store};
    let (dir, node) = switch_image("check-one");
    let switch = BootSwitch::new(&node);
    switch.write(true).unwrap();
    switch.write(false).unwrap();
    let lba = switch_copies(&node);
    // Both copies are valid now. Every byte of each copy is tried: a change anywhere breaks that
    // copy's magic, length or CRC, and the other copy reads.
    for copy in 0..2u64 {
        for at in 0..512 {
            let before = byte(&node, lba + copy, at);
            set(&node, lba + copy, at, before ^ 0xFF);
            assert!(
                switch.check().is_ok(),
                "copy {copy} byte {at} damaged: the other copy still reads"
            );
            set(&node, lba + copy, at, before);
        }
    }
    assert!(switch.check().is_ok());
    let _ = std::fs::remove_dir_all(dir);
}

#[test]
fn both_damaged_switch_record_copies_are_refused_naming_the_check() {
    use crate::security::{BootSwitch, RecordFault, Store};
    let (dir, node) = switch_image("check-both");
    let switch = BootSwitch::new(&node);
    switch.write(true).unwrap();
    switch.write(false).unwrap();
    let lba = switch_copies(&node);
    for at in 0..512 {
        let (before0, before1) = (byte(&node, lba, at), byte(&node, lba + 1, at));
        set(&node, lba, at, before0 ^ 0xFF);
        set(&node, lba + 1, at, before1 ^ 0xFF);
        match switch.check() {
            Err(RecordFault::Damaged(why)) => assert!(
                why.contains("neither copy is valid"),
                "byte {at}: the check that failed is named: {why}"
            ),
            other => panic!("byte {at}: both copies damaged must be refused, got {other:?}"),
        }
        set(&node, lba, at, before0);
        set(&node, lba + 1, at, before1);
    }
    assert!(switch.check().is_ok(), "restored copies read again");
    let _ = std::fs::remove_dir_all(dir);
}

