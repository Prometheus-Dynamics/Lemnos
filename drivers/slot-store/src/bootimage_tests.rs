//! Tests of the boot partition's image: the board geometry, the minimum size, determinism, the
//! first install, the verification, and the U-Boot form. The volumes are the real geometry (the
//! 79 MiB board partition) unless a test says otherwise.

use super::*;

/// The board's layout in bytes: the kernel in an 11 MiB bay, the initramfs in 1 MiB (a placeholder:
/// its size is unmeasured, requirements section 8.3), the dtb in 88 KiB, the overlay and the
/// command line in 4 KiB each.
fn board_layout() -> Layout {
    Layout::new([11 * 1024 * 1024, 1024 * 1024, 88 * 1024, 4096, 4096]).unwrap()
}

/// The Pi firmware's parts: the generated text stand-ins, and the README (its own length).
fn tryboot_parts() -> Parts {
    Parts {
        family: Family::Tryboot,
        layout: board_layout(),
        root: vec![
            (
                "config.txt",
                b"# Generated by lemnos-ctl test\nkernel_watchdog_timeout=15\n".to_vec(),
            ),
            ("tryboot.txt", b"# Generated by lemnos-ctl test\n".to_vec()),
            ("slot-layout.toml", b"version = 5\n".to_vec()),
        ],
        fixed: vec![Fixed {
            path: "overlays/README",
            bytes: b"Generated: os_prefix applies to overlays.\n".to_vec(),
            size: 42,
        }],
    }
}

/// The payloads of a slot: the kernel small enough for its bay.
fn payloads() -> [Vec<u8>; 5] {
    [
        vec![3; 4000],
        vec![4; 700],
        vec![5; 300],
        b"console=serial0 root=lemnos".to_vec(),
        vec![6; 200],
    ]
}

fn refs(p: &[Vec<u8>; 5]) -> [&[u8]; 5] {
    std::array::from_fn(|i| p[i].as_slice())
}

/// The board volume's header fields the firmware reads: the sectors per cluster, the two FAT
/// copies, the FAT's sectors, and the total.
fn bpb(image: &[u8]) -> (u8, u8, u16, u32) {
    (
        image[13],
        image[16],
        u16::from_le_bytes([image[22], image[23]]),
        u32::from_le_bytes(image[32..36].try_into().unwrap()),
    )
}

#[test]
fn the_board_partition_geometry_is_two_fats_of_158_sectors_and_40360_clusters() {
    let total = 161_792u64;
    assert_eq!(fatimage::cluster_sectors(total), 4, "2 KiB clusters");
    assert_eq!(
        fatimage::geometry(total, 4),
        (158, 40_360, 1 + 2 * 158 + 32)
    );
    let image = build(&tryboot_parts(), total * 512, "a", &refs(&payloads())).unwrap();
    assert_eq!(image.len() as u64, total * 512);
    let (spc, fats, fat_sectors, sectors) = bpb(&image);
    assert_eq!((spc, fats, fat_sectors, sectors), (4, 2, 158, 161_792));
    // The second FAT is a copy of the first.
    assert_eq!(
        image[512..512 + 158 * 512],
        image[(1 + 158) * 512..(1 + 2 * 158) * 512]
    );
}

#[test]
fn the_minimum_size_builds_and_verifies_and_one_sector_less_is_refused_by_name() {
    let parts = tryboot_parts();
    let min = min_size(&parts).unwrap();
    assert_eq!(min % 512, 0);
    let owned = payloads();
    let p = refs(&owned);
    let image = build(&parts, min, "a", &p).unwrap_or_else(|e| panic!("at the minimum: {e}"));
    let mut mem = Mem(image);
    assert!(verify(&mut mem, &parts).iter().all(|f| f.ok));
    let err = build(&parts, min - 512, "a", &p).unwrap_err();
    assert!(
        err.contains("below the minimum") && err.contains(&min.to_string()),
        "{err}"
    );
}

#[test]
fn the_image_is_byte_identical_for_the_same_inputs() {
    let parts = tryboot_parts();
    let total = 161_792u64 * 512;
    let a = build(&parts, total, "a", &refs(&payloads())).unwrap();
    let b = build(&parts, total, "a", &refs(&payloads())).unwrap();
    assert!(a == b, "the same inputs give the same bytes");
}

#[test]
fn the_first_slot_is_the_default_and_its_payloads_verify_after_the_install() {
    let parts = tryboot_parts();
    let image = build(&parts, 161_792 * 512, "a", &refs(&payloads())).unwrap();
    let mut mem = Mem(image.clone());
    let findings = verify(&mut mem, &parts);
    assert!(
        findings
            .iter()
            .any(|f| f.ok && f.text.contains("default.txt: names bay0")),
        "{findings:?}"
    );
    assert!(
        findings
            .iter()
            .any(|f| f.ok && f.text.contains("bay0 (a): the five payloads match")),
        "{findings:?}"
    );
    assert!(findings.iter().all(|f| f.ok), "{findings:?}");
    // A flipped byte in the kernel's bay is named by the verification.
    let mut bad = image;
    let kernel = fatimage_first_byte_of(&bad, "kernel8.img", 0);
    bad[kernel] ^= 0x40;
    let findings = verify(&mut Mem(bad), &parts);
    assert!(
        findings.iter().any(|f| !f.ok && f.text.contains("kernel")),
        "{findings:?}"
    );
}

/// The byte offset of the first byte of `name` in `bay0`, read from the volume's own tree: the
/// locator finds it, so the test does not compute a cluster by hand.
fn fatimage_first_byte_of(image: &[u8], name: &str, index: usize) -> usize {
    let mut mem = Mem(image.to_vec());
    let path = format!("slots/bay0/{name}");
    let want = match name {
        "kernel8.img" => board_layout().bytes[0],
        _ => unreachable!(),
    };
    let found = bootfat::locate_path(&mut mem, &path, want).unwrap();
    (found.first_lba as usize) * 512 + index
}

#[test]
fn a_payload_larger_than_its_bay_is_refused_by_name_before_anything_is_built() {
    let parts = tryboot_parts();
    let mut big = payloads();
    big[0] = vec![1; 12 * 1024 * 1024];
    let err = build(&parts, 161_792 * 512, "a", &refs(&big)).unwrap_err();
    assert!(err.contains("kernel") && err.contains("bay"), "{err}");
}

#[test]
fn a_size_that_is_not_whole_sectors_is_refused() {
    let err = build(&tryboot_parts(), 161_792 * 512 + 1, "a", &refs(&payloads())).unwrap_err();
    assert!(err.contains("whole number of 512-byte sectors"), "{err}");
}

#[test]
fn the_tree_of_the_pi_form_has_three_sets_with_five_payloads_a_readme_and_a_record_each() {
    let root = tree(&tryboot_parts());
    let Some(Node::Dir { children: sets, .. }) = root
        .iter()
        .find(|n| matches!(n, Node::Dir { name: "slots", .. }))
    else {
        panic!("no slots directory")
    };
    assert_eq!(sets.len(), SETS as usize);
    for set in sets {
        let Node::Dir { children, .. } = set else {
            panic!("a set is a directory")
        };
        let names: Vec<&str> = children
            .iter()
            .map(|n| match n {
                Node::File { name, .. } | Node::Dir { name, .. } => *name,
            })
            .collect();
        for want in [
            "kernel8.img",
            "initramfs.cpio",
            "board.dtb",
            "cmdline.txt",
            "overlays",
            "bayinfo.rec",
        ] {
            assert!(names.contains(&want), "{want} is in each set: {names:?}");
        }
    }
}

#[test]
fn the_uboot_form_composes_the_extlinux_file_from_the_command_line_and_verifies_it() {
    let parts = Parts {
        family: Family::UbootBlock,
        layout: board_layout(),
        root: vec![
            ("slot-layout.toml", b"version = 5\n".to_vec()),
            ("boot.cmd", b"# boot\n".to_vec()),
        ],
        fixed: vec![Fixed {
            path: EXTLINUX,
            bytes: Vec::new(),
            size: EXTLINUX_BYTES,
        }],
    };
    let owned = payloads();
    let p = refs(&owned);
    let image = build(&parts, 161_792 * 512, "a", &p).unwrap();
    let mut mem = Mem(image);
    let findings = verify(&mut mem, &parts);
    assert!(findings.iter().all(|f| f.ok), "{findings:?}");
    assert!(
        findings
            .iter()
            .any(|f| f.text.contains("extlinux.conf matches")),
        "{findings:?}"
    );
    let text = extlinux_text(&payloads()[3]).unwrap();
    assert!(String::from_utf8_lossy(&text).contains("APPEND console=serial0 root=lemnos\n"));
}

#[test]
fn the_uboot_form_refuses_a_gzip_kernel_by_name_and_writes_nothing() {
    let parts = Parts {
        family: Family::UbootBlock,
        layout: board_layout(),
        root: Vec::new(),
        fixed: Vec::new(),
    };
    let mut p = payloads();
    p[0] = vec![0x1F, 0x8B, 8, 0];
    let err = build(&parts, 161_792 * 512, "a", &refs(&p)).unwrap_err();
    assert!(
        err.contains("gzip-compressed") && err.contains("kernel_comp_addr_r"),
        "{err}"
    );
}

#[test]
fn a_command_line_on_two_lines_is_refused_for_the_extlinux_file() {
    assert!(extlinux_text(b"a\nb").is_err());
    assert!(extlinux_text(b"a b\n").is_ok());
}
