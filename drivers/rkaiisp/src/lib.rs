//! The Rockchip AI-ISP (`rkaiisp`), behind the vendor kernel's AI-ISP driver. No vendor library:
//! what runs on the block (the model's layout per run and its weights) is the caller's, carried
//! as bytes and never interpreted. The crate reads only the numbers the kernel turns into
//! indices, registers and the weights' read, to refuse the ones that would leave what it owns.
//!
//! - [`uapi`]: the vendor uAPI (parameter buffer, pool and queue structures, the private
//!   requests, the done event), transcribed with its source and pinned against the C compiler by
//!   `layout.rs` (generated by `layout-check/run.sh`).
//! - [`params`]: the checks a parameter buffer passes before the kernel sees it, each standing
//!   for an index or register the vendor driver takes unchecked.
//! - [`Aiisp`]: the parameter ring over a [`Device`]: the node set up, parameter buffers
//!   checked, copied into kernel buffers and queued, and taken back; a device failure closes it
//!   and backs off (250 ms doubling to an 8 s cap); it never gives up and never turns itself off.
//!
//! # What is not here, and why
//!
//! No operation reaches the block. The block's data channels read and write the pool's buffers
//! (`RKAIISP_CMD_INIT_BUFPOOL`: dma-bufs the ISP shares, with the planes' widths, heights,
//! offsets and strides; `RKAIISP_CMD_INIT_AIRMS_BUFPOOL`: buffers the kernel allocates from the
//! widths given), and how far each channel reaches is computed by the vendor driver from those
//! sizes together with each run's channel modes in the parameter buffer, then written to the
//! block's base, stride and height registers. The vendor driver checks none of it against the
//! buffers' real sizes, and nothing in the sources says how far the block reads for a given
//! register value (the right-edge slice extension and the odd-height flag among them). A safe
//! path would need that bound; without it, the pool, the queue (`RKAIISP_CMD_QUEUE_BUF`) and a
//! Linux [`Device`] over the parameter node (whose buffers set the channel modes) are left out.
//! The same sources show the kernel also takes the pool's buffer counts and the queue's indices
//! unchecked (arrays of 8), which a future pool path must check too.
//!
//! No contract is served: none of the merged contracts describes an AI-ISP.
//!
//! Hardware status: untested on board. Written from the vendor driver's source; the check is
//! `testing/board-runs/E10.md`.
//!
//! Provenance: new. Every fact is from rockchip-linux/kernel, branch `develop-6.1`, commit
//! `77168c8d5ab82399f65a80e9f807b50ba37cf483`: `include/uapi/linux/rk-aiisp-config.h`,
//! `include/uapi/linux/rk-isp2-config.h` and `drivers/media/platform/rockchip/aiisp/`
//! (`aiisp.c`, `aiisp.h`). The ring follows the shape of `drivers/rk-iep`.

