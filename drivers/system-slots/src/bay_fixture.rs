//! Test boot partitions made by the image builder (`lemnos_slot_store::bootimage::build`), the
//! same code `lemnos-ctl boot-partition` runs: a real FAT16 volume with its pre-created bay files,
//! pointers and records, written raw like a board's.

use lemnos_slot_store::bays;
use lemnos_slot_store::bootimage::{self, Family, Fixed, Parts};

/// The bays: small, so an image builds fast; each file's bay is at least what a test slot stores.
pub fn layout() -> bays::Layout {
    bays::Layout::new([8192, 4096, 4096, 4096, 4096]).unwrap()
}

/// A slot's five payloads in the roles' order.
pub fn payloads(id: &str) -> [Vec<u8>; 5] {
    [
        format!("kernel of {id}\n").into_bytes(),
        format!("initramfs of {id}\n").into_bytes(),
        format!("device tree of {id}\n").into_bytes(),
        format!("console=tty1 os.slot={id} panic=5\n").into_bytes(),
        format!("overlay of {id}\n").into_bytes(),
    ]
}

pub fn refs(p: &[Vec<u8>; 5]) -> [&[u8]; 5] {
    std::array::from_fn(|i| p[i].as_slice())
}

fn tryboot_parts() -> Parts {
    Parts {
        family: Family::Tryboot,
        layout: layout(),
        root: vec![
            ("config.txt", b"kernel_watchdog_timeout=15\n".to_vec()),
            ("tryboot.txt", b"# Generated by the test\n".to_vec()),
            ("slot-layout.toml", b"version = 5\n".to_vec()),
        ],
        fixed: Vec::new(),
    }
}

fn uboot_parts() -> Parts {
    Parts {
        family: Family::UbootBlock,
        layout: layout(),
        root: vec![("slot-layout.toml", b"version = 5\n".to_vec())],
        fixed: vec![Fixed {
            path: bootimage::EXTLINUX,
            bytes: Vec::new(),
            size: bootimage::EXTLINUX_BYTES,
        }],
    }
}

/// The Pi firmware's image with slot `first` installed in bay 0, all three pointers naming it.
pub fn tryboot_image(first: &str) -> Vec<u8> {
    let parts = tryboot_parts();
    let size = bootimage::min_size(&parts).unwrap();
    bootimage::build(&parts, size, first, &refs(&payloads(first))).unwrap()
}

/// The U-Boot form's image with slot `first` in bay 0 and its composed extlinux file.
pub fn uboot_image(first: &str) -> Vec<u8> {
    let parts = uboot_parts();
    let size = bootimage::min_size(&parts).unwrap();
    bootimage::build(&parts, size, first, &refs(&payloads(first))).unwrap()
}
