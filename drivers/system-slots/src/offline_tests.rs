//! The offline writer (`offline.rs`) against the daemon's own driver. The live reference is an
//! install, a trial and a confirm of the same bundle on a board whose boot partition is a copy of
//! the same image, with the same clock. The offline tree must equal it file for file, byte for
//! byte and mode for mode, and load in the driver as installed, confirmed and default.

