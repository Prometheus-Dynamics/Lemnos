/// The stand-in case (NOTICE 20): the writer's boot record is an in-memory copy, not a block device.
/// A boot partition that is not one fails in the writer by name, and the daemon's own record fails
/// the same way on the same bytes, so the stand-in is not what passes.
#[test]
fn a_file_that_is_not_a_boot_partition_fails_in_the_writer_and_in_the_live_record_alike() {
    let root = TempDir::new("offline-notboot");
    let (bundle, _) = bundle_and_payloads("os-1");
    let zeros = vec![0u8; 1 << 20];
    let err = offline(&root.0, "out", &bundle, &zeros, TIME).unwrap_err();
    assert!(err.starts_with("the boot image"), "{err}");
    let live_dir = root.0.join("live");
    fs::create_dir_all(&live_dir).unwrap();
    let (status, _) = live(&live_dir, &bundle, &zeros, TIME);
    assert_ne!(status, Status::OK, "the live record refuses the same bytes");
}

/// The default names a bay that does not hold the slot: the writer's confirm would make the bay
/// holding the slot the default, which the boot image does not say.
#[test]
fn a_default_that_would_change_to_another_bay_is_refused() {
    let root = TempDir::new("offline-default");
    let (bundle, payloads) = bundle_and_payloads("os-1");
    let (_, other) = bundle_and_payloads("os-2");
    // bay 0 holds os-2 and is the default; os-1 is also in the image, in bay 1.
    let mut boot = Boot::on(Mem(boot_image("os-2", &other))).unwrap();
    boot.install_slot("os-1", &bay_fixture::refs(&payloads)).unwrap();
    let image = boot.into_device().0;
    let err = offline(&root.0, "out", &bundle, &image, TIME).unwrap_err();
    assert!(
        err.contains("default.txt names bay0, which does not hold os-1"),
        "{err}"
    );
    assert!(!root.0.join("out").exists());
}
