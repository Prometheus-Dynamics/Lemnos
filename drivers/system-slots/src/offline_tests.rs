const TIME: &str = "2026-11-14T20:00:00Z";
const LATER: &str = "2027-01-02T03:04:05Z";
const BOOT_SOURCE: &str = "/soc/mmc@7e202000=/soc/mmc@7e202000";
const PIECE: usize = 64 * 1024;

/// The boot partition's image with `slot` in bay 0 and `payloads`: the same builder the boot
/// partition command runs, over the test layout.
fn boot_image(slot: &str, payloads: &[Vec<u8>; 5]) -> Vec<u8> {
    let parts = Parts {
        family: Family::Tryboot,
        layout: bay_fixture::layout(),
        root: vec![
            ("config.txt", b"kernel_watchdog_timeout=15\n".to_vec()),
            ("tryboot.txt", b"# Generated by the test\n".to_vec()),
            ("slot-layout.toml", b"version = 5\n".to_vec()),
        ],
        fixed: Vec::new(),
    };
    let size = bootimage::min_size(&parts).unwrap();
    bootimage::build(&parts, size, slot, &bay_fixture::refs(payloads)).unwrap()
}

fn board() -> OfflineBoard {
    OfflineBoard {
        id: BOARD.into(),
        boot_args: "board".into(),
        boot_sources: vec![BOOT_SOURCE.into()],
        layout: bay_fixture::layout(),
    }
}

fn trusted() -> Vec<TrustedKey> {
    vec![TrustedKey {
        key: key().verifying_key(),
        owner: "the build key".into(),
    }]
}

/// The live reference: the daemon's driver on a boot partition file that is a copy of `image`,
/// the bundle streamed in, tried, booted into and confirmed by `By::Auto`, at `time`.
fn live(dir: &Path, bundle: &[u8], image: &[u8], time: &str) -> (Status, String) {
    let node = dir.join("live-boot.img");
    fs::write(&node, image).unwrap();
    let layout = Layout::new(dir.join("data"), dir.join("boot-mount"));
    let tryboot = Tryboot {
        boot: dir.join("boot-mount"),
        node: Ok(node),
        restarter: Restarter {
            systemctl: PathBuf::from("/bin/true"),
            check: None,
        },
    };
    let mut slots = SystemSlots::new(layout.clone(), Box::new(tryboot), trusted());
    slots.partuuid = "1234abcd-02".into();
    slots.boot_args = board().boot_args;
    slots.boot_sources = board().boot_sources;
    slots.board_id = BOARD.into();
    slots.reserve = 0;
    slots.running = Some(String::new());
    security::with_enforced(false, || {
        store::with_clock(time, || {
            let job = slots.install(bundle.len() as u64, false, false).unwrap();
            for (i, piece) in bundle.chunks(PIECE).enumerate() {
                if let Err(status) = slots.write((i * PIECE) as u64, piece) {
                    return (status, String::new());
                }
            }
            let mut out = [0u8; 256];
            let id = match slots.job(job, &mut Reply::new(&mut out)) {
                JobState::Finished(Status::OK) => {
                    String::from_utf8_lossy(&out).trim_end_matches('\0').to_string()
                }
                JobState::Finished(status) => return (status, String::new()),
                JobState::Running { .. } => panic!("the install never ended"),
            };
            slots.trial(&id, false, false, false).unwrap();
            slots.running = Some(id.clone());
            slots.confirm_as(resolve::By::Auto).unwrap();
            (Status::OK, id)
        })
    })
}

/// Every path under `root` with its bytes (`None` for a directory) and its mode.
fn tree(root: &Path) -> BTreeMap<String, (Option<Vec<u8>>, u32)> {
    use std::os::unix::fs::PermissionsExt;
    let mut out = BTreeMap::new();
    let mut stack = vec![root.to_path_buf()];
    while let Some(dir) = stack.pop() {
        for entry in fs::read_dir(&dir).unwrap().flatten() {
            let path = entry.path();
            let rel = path.strip_prefix(root).unwrap().display().to_string();
            let mode = entry.metadata().unwrap().permissions().mode() & 0o7777;
            if path.is_dir() {
                out.insert(rel, (None, mode));
                stack.push(path);
            } else {
                out.insert(rel, (Some(fs::read(&path).unwrap()), mode));
            }
        }
    }
    out
}

/// The output of an offline write of `bundle` over `image` into a fresh directory under `dir`.
fn offline(dir: &Path, name: &str, bundle: &[u8], image: &[u8], time: &str) -> Result<PathBuf, String> {
    let out = dir.join(name);
    let keys = trusted();
    write_first_slot(FirstSlot {
        out: &out,
        bundle,
        boot_image: image.to_vec(),
        keys,
        board: board(),
        time,
        free: 1 << 40,
    })
    .map(|_| out)
}

#[test]
fn the_offline_tree_equals_a_live_install_trial_and_confirm_and_reads_as_default() {
    let root = TempDir::new("offline-live");
    let (bundle, payloads) = bundle_and_payloads("os-1");
    let image = boot_image("os-1", &payloads);

    let live_dir = root.0.join("live");
    fs::create_dir_all(&live_dir).unwrap();
    let (status, id) = live(&live_dir, &bundle, &image, TIME);
    assert_eq!(status, Status::OK);
    assert_eq!(id, "os-1");

    let out = offline(&root.0, "offline", &bundle, &image, TIME).unwrap();
    let mut live_tree = tree(&live_dir.join("data"));
    live_tree.remove("slots/.incoming");
    let offline_tree = tree(&out);
    assert!(!offline_tree.contains_key("slots/.incoming"), "no staging directory is left");
    assert_eq!(
        offline_tree.keys().collect::<Vec<_>>(),
        live_tree.keys().collect::<Vec<_>>(),
        "the same paths"
    );
    for (path, value) in &offline_tree {
        assert_eq!(value, &live_tree[path], "{path}: same bytes and mode");
    }

    // The output, loaded in the real driver over a copy of the boot image, reads as installed,
    // confirmed and default.
    let read_dir = root.0.join("read");
    fs::create_dir_all(&read_dir).unwrap();
    copy_tree(&out, &read_dir.join("data"));
    let node = read_dir.join("boot.img");
    fs::write(&node, &image).unwrap();
    let layout = Layout::new(read_dir.join("data"), read_dir.join("boot-mount"));
    let tryboot = Tryboot {
        boot: read_dir.join("boot-mount"),
        node: Ok(node),
        restarter: Restarter {
            systemctl: PathBuf::from("/bin/true"),
            check: None,
        },
    };
    let slots = SystemSlots::new(layout.clone(), Box::new(tryboot), trusted());
    let state = State::load(&layout);
    assert_eq!(state.default, "os-1");
    assert_eq!(state.state, "confirmed");
    assert!(state.trial.is_empty() && state.staged.is_empty());
    let meta = Meta::load(&layout, "os-1");
    assert_eq!(meta.get("GOOD"), "yes");
    assert!(!meta.failed());
    assert!(layout.image("os-1").exists(), "the image is in place");
    assert!(slots.list_json().contains("os-1"), "the driver lists the slot");
}

fn copy_tree(from: &Path, to: &Path) {
    for (path, (bytes, _)) in tree(from) {
        let target = to.join(&path);
        match bytes {
            None => fs::create_dir_all(&target).unwrap(),
            Some(bytes) => {
                fs::create_dir_all(target.parent().unwrap()).unwrap();
                fs::write(target, bytes).unwrap();
            }
        }
    }
    fs::create_dir_all(to).unwrap();
}

#[test]
fn the_same_inputs_give_the_same_bytes_and_another_time_changes_only_the_stamps() {
    let root = TempDir::new("offline-determinism");
    let (bundle, payloads) = bundle_and_payloads("os-1");
    let image = boot_image("os-1", &payloads);
    let a = tree(&offline(&root.0, "a", &bundle, &image, TIME).unwrap());
    let b = tree(&offline(&root.0, "b", &bundle, &image, TIME).unwrap());
    assert_eq!(a, b, "the same inputs give the same tree");
    let c = tree(&offline(&root.0, "c", &bundle, &image, LATER).unwrap());
    let changed: Vec<&String> = a
        .iter()
        .filter(|(path, value)| c.get(*path) != Some(value))
        .map(|(path, _)| path)
        .collect();
    assert!(!changed.is_empty(), "the stamps differ with another time");
    for path in changed {
        assert!(
            path == "board/slots/os-1.meta" || path == "board/slots/resolved.env",
            "only the stamps change, not {path}"
        );
    }
}

#[test]
fn files_are_0644_and_directories_0755_whatever_the_umask() {
    let root = TempDir::new("offline-modes");
    let (bundle, payloads) = bundle_and_payloads("os-1");
    let image = boot_image("os-1", &payloads);
    let out = offline(&root.0, "out", &bundle, &image, TIME).unwrap();
    for (path, (bytes, mode)) in tree(&out) {
        let want = if bytes.is_some() { 0o644 } else { 0o755 };
        assert_eq!(mode, want, "{path}");
    }
}

