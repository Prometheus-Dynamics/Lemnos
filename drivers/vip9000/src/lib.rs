//! The VeriSilicon VIP9000 neural accelerator, serving `npu/1`. No vendor library: what runs on
//! the block (a compiled program) is the caller's bytes, which Lemnos never parses or compiles.
//! The vendor's user-space runtime, its model tools and its compiled format are not used, read or
//! followed.
//!
//! - [`claim`]: the block through `lemnos.ko` (`kernel/lemnos_vip.c`): a claim on its node,
//!   programs loaded into the module (which checks them), slots, and runs from the job stream;
//!   [`claim::Served`], the contract on a claim and a stream.
//! - `npu` (Linux): [`Vip9000Driver`], the `#[driver]` type the daemon runs, bound from the board
//!   file: `route = "lemnos"` runs jobs through the module; `route = "vipcore"` binds to refuse.
//! - `linux` (Linux): the claim's node and session on `lemnos-driver-vip9000-sys`.
//! - [`confine`]: what each kernel path lets a job reach, as read from its source, and the check
//!   that a job's table maps only the job's own buffers. [`confine::LEMNOS`] has no gap;
//!   [`confine::VIPCORE`] and [`confine::GALCORE`] have gaps no user-space driver can close.
//! - [`uapi`], [`request`]: the vendor `vipcore` node's request number, commands, flags and
//!   structures, pinned against the C compiler by `layout.rs` (generated by
//!   `layout-check/run.sh`), and checked builders for the requests a run there would need, kept
//!   to show why that node is refused; [`Vip9000`]: the check of a vendor node over a [`Device`],
//!   which finds it unconfined.
//!
//! # How a job is confined
//!
//! A program can name any device address, so a job is confined only if the block's address
//! translation maps nothing but that job's buffers while it runs. `lemnos.ko` does that for a
//! block named in its `vip9000` parameter: per-job MMU tables built only from the stream's
//! registered dma-bufs, every program checked once in kernel memory to hold no command that
//! reaches the block's control registers, its MMU set-up or its command fetcher, a fault answered
//! by a reset and the job's frame published empty. See [`claim`] and `docs/kernel-module.md`.
//!
//! Hardware status: untested on board. The module path is checked in the QEMU harness against a
//! fake block; the board check is `testing/board-runs/H7a.md` (and `E33.md` for the vendor node).
//!
//! Provenance: new. Every fact is from the Radxa `allwinner-bsp` tree (github.com/radxa/
//! allwinner-bsp) at commit `a842bb8dc74608ba13975c97c31b9518f1976c01` (branch
//! `cubie-aiot-v1.5.0`): `drivers/npu/aw_nna_vip/vip2/` (VeriSilicon, dual MIT and GPL, used under
//! MIT), `drivers/npu/aw_nna_galcore/` (the vendor's other driver for the same compatible string),
//! `drivers/npu/aw_nna_vip/Kconfig` and `configs/linux-6.6/sun60iw2p1.dtsi`; each module names
//! its files. Interface facts only are transcribed; no code is copied. The shape follows
//! `drivers/rknpu`.

