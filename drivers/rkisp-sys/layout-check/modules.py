#!/usr/bin/env python3
"""Generates the module-bit tables of drivers/rkisp-sys/src/modules.rs from the vendor kernel's ISP
uAPI headers, and a C file that checks every value against the C compiler.

    modules.py <develop-6.1 include/uapi/linux> <out.rs> <out-check.c>

Each family's `#define <PREFIX>_MODULE_<NAME> <expr>` is resolved here: `_BITULL(ID)` /
`BIT_ULL(n)` give the bit, and an alias such as `ISP3X_MODULE_DPCC ISP2X_MODULE_DPCC` is followed.
The C file repeats each name as `_Static_assert(<name> == (1ULL << <bit>))`, so the Rust tables
are checked against the compiler's own reading of the headers, not against this script's.

Families: ISP2X (rk-isp2, rk-isp21: the ISP21 table), ISP3X (rk-isp3: ISP30), ISP32 (rk-isp32),
ISP39 (rk-isp39), ISP35 (rk-isp35). Rust names drop the family prefix; a name starting with a digit
(`3DLUT`) becomes `LUT3D`.
"""
import re
import sys

HEADERS = {
    "ISP2X": ["rk-isp2-config.h", "rk-isp21-config.h"],
    "ISP3X": ["rk-isp3-config.h"],
    "ISP32": ["rk-isp32-config.h"],
    "ISP39": ["rk-isp39-config.h"],
    "ISP35": ["rk-isp35-config.h"],
    "ISP33": ["rk-isp33-config.h"],
}
# Every header whose defines an alias may name (ISP35's names alias ISP33 and ISP39 ones).
ALL_HEADERS = ["rk-isp2-config.h", "rk-isp21-config.h", "rk-isp3-config.h", "rk-isp32-config.h",
               "rk-isp33-config.h", "rk-isp39-config.h", "rk-isp35-config.h"]
# Each table: the Rust name, the family whose defines it takes, and the families it extends.
TABLES = [
    ("module", "ISP2X", ["ISP2X"]),
    ("module30", "ISP3X", ["ISP3X"]),
    ("module32", "ISP32", ["ISP32"]),
    ("module39", "ISP39", ["ISP39"]),
    ("module35", "ISP35", ["ISP35"]),
]
DEFINE = re.compile(r"^#define\s+(\w+_MODULE_\w+)\s+(.+?)\s*$")
ID = re.compile(r"^#define\s+(ISP2X_ID_\w+)\s+\((\d+)\)\s*$")


def read(root, names):
    lines = []
    for n in names:
        with open(f"{root}/{n}", encoding="utf-8", errors="replace") as f:
            lines += f.read().splitlines()
    return lines


def resolve(name, defs, ids, depth=0):
    expr = defs[name]
    m = re.fullmatch(r"_?BIT_?ULL\((\d+)\)", expr)
    if m:
        return int(m.group(1))
    m = re.fullmatch(r"_BITULL\((ISP2X_ID_\w+)\)", expr)
    if m:
        return ids[m.group(1)]
    m = re.fullmatch(r"(\w+_MODULE_\w+)", expr)
    if m and depth < 8:
        return resolve(m.group(1), defs, ids, depth + 1)
    raise SystemExit(f"cannot resolve {name} = {expr}")


def rust_name(c_name, family):
    base = c_name[len(family) + len("_MODULE_"):]
    return "LUT3D" if base == "3DLUT" else base


def main():
    root, out_rs, out_c = sys.argv[1:4]
    lines = []
    ids = {}
    for fam in HEADERS:
        lines = read(root, HEADERS[fam])
        for l in lines:
            m = ID.match(l)
            if m:
                ids[m.group(1)] = int(m.group(2))
    defs = {}
    for l in read(root, ALL_HEADERS):
        m = DEFINE.match(l)
        if m:
            defs[m.group(1)] = m.group(2)
    fams = {}
    for name in defs:
        for fam in ("ISP2X", "ISP3X", "ISP32", "ISP33", "ISP35", "ISP39"):
            if name.startswith(f"{fam}_MODULE_"):
                fams.setdefault(fam, []).append(name)

    rs = [
        "//! The ISP module bits per generation, generated by `layout-check/modules.py` from the vendor",
        "//! kernel's develop-6.1 uAPI headers (rockchip-linux/kernel, `(GPL-2.0+ WITH Linux-syscall-note)",
        "//! OR MIT`; used here under MIT). Do not edit: rerun the script. `layout-check/modules.py` also",
        "//! writes the C check of every value below.",
        "",
    ]
    cc = [
        "/* Generated by layout-check/modules.py: every module bit against the C compiler. */",
        "#define BIT_ULL(n) (1ULL << (n))",
    ]
    for inc in ALL_HEADERS:
        cc.append(f"#include <linux/{inc}>")
    for table, fam, extends in TABLES:
        prefix = f"{fam}_MODULE_"
        names = sorted(
            {n for e in extends for n in fams[e] if n.startswith(f"{e}_MODULE_")},
            key=lambda n: resolve(n, defs, ids),
        )
        bits = {}
        for n in names:
            bit = resolve(n, defs, ids)
            if bit in bits and bits[bit] != n:
                raise SystemExit(f"{table}: {n} and {bits[bit]} share bit {bit}")
            bits[bit] = n
        rs.append(f"/// The `{fam}` module bits (`{fam}_MODULE_*` of the develop-6.1 headers).")
        rs.append(f"pub mod {table} {{")
        rust = []
        for n in names:
            bit = resolve(n, defs, ids)
            rn = rust_name(n, fam)
            rs.append(f"    /// `{n}`, bit {bit}.")
            rs.append(f"    pub const {rn}: u64 = 1 << {bit};")
            rust.append(rn)
            cc.append(f"_Static_assert({n} == (1ULL << {bit}), \"{n}\");")
        rs.append("    /// Every bit this table names.")
        rs.append("    pub const ALL: u64 = " + " | ".join(rust) + ";")
        rs.append("}")
        rs.append("")
    with open(out_rs, "w", encoding="utf-8") as f:
        f.write("\n".join(rs))
    with open(out_c, "w", encoding="utf-8") as f:
        f.write("\n".join(cc) + "\n")


if __name__ == "__main__":
    main()
