#!/usr/bin/env bash
# Regenerates src/isp21.rs (ISP21), src/isp3x.rs (ISP30) and src/isp35.rs (ISP35) from the vendor
# kernel's ISP uAPI headers. The headers are not kept in this repository; pass the two
# directories that hold them:
#
#   ./bindgen.sh <develop-5.10 include/uapi/linux> <develop-6.1 include/uapi/linux>
#
# From the first: rk-isp2-config.h, rk-isp21-config.h, rk-isp3-config.h, rk-isp32-config.h. From
# the second: rk-isp2-config.h, rk-isp33-config.h, rk-isp35-config.h, rk-isp39-config.h. Their own
# include of rk-camera-module.h is cut. Needs bindgen-cli and clang.
#
# Provenance: the dev branch's scripts/rkisp-bindgen.sh, unchanged in its bindgen options except
# that no `bytemuck` derive is added (this workspace takes no new dependency for it), so the
# structures derive bindgen's defaults: Debug, Copy, Clone.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
h510="$1"
h61="$2"
inc="$(mktemp -d)"
trap 'rm -rf "$inc"' EXIT
mkdir -p "$inc/linux"
for h in rk-isp2-config.h rk-isp21-config.h rk-isp3-config.h rk-isp32-config.h; do
    sed '/#include <linux\/rk-camera-module.h>/d' "$h510/$h" >"$inc/linux/$h"
done

gen() {
    local out="$1" header="$2" include="$3" types="$4" vars="$5"
    shift 5
    {
        for line in "$@"; do echo "$line"; done
        bindgen "$include/linux/$header" --use-core --no-layout-tests --no-doc-comments \
            --allowlist-type "$types" --allowlist-var "$vars" \
            -- -I "$include" -target aarch64-linux-gnu | sed -e '1d'
    } >"$out"
    rustfmt --edition 2024 "$out"
}

gen "$here/src/isp3x.rs" rk-isp3-config.h "$inc" 'isp3x_.*|rkisp3x_.*' \
    'ISP3X_.*|ISP2X_RAWAE.*|ISP2X_RAWHIST.*|ISP2X_HIST.*' \
    '//! @generated by bindgen from `rk-isp3-config.h` (and the `rk-isp21`/`rk-isp2`' \
    '//! headers it includes), rockchip-linux/kernel `develop-5.10` `include/uapi/linux`, licensed' \
    '//! `(GPL-2.0+ WITH Linux-syscall-note) OR MIT`; used here under MIT. Regenerate with' \
    '//! `bindgen.sh`; do not edit.' \
    '' \
    '#![allow(non_camel_case_types, non_upper_case_globals, dead_code, clippy::all, missing_docs)]' \
    ''

# ISP21 has its own LSC (8 sector sizes, no 16x16 flag), gamma (45 samples) and statistics
# wrapper, so its module is generated apart from ISP30's: the isp2x types it shares with ISP30
# are generated again in it.
gen "$here/src/isp21.rs" rk-isp21-config.h "$inc" 'isp21_.*|rkisp_isp21_.*' \
    'ISP21_.*|ISP2X_GAMMA_OUT_MAX_SAMPLES' \
    '//! @generated by bindgen from `rk-isp21-config.h` (and the `rk-isp2` header it' \
    '//! includes), rockchip-linux/kernel `develop-5.10` `include/uapi/linux`, licensed' \
    '//! `(GPL-2.0+ WITH Linux-syscall-note) OR MIT`; used here under MIT. Regenerate with' \
    '//! `bindgen.sh`; do not edit.' \
    '' \
    '#![allow(non_camel_case_types, non_upper_case_globals, dead_code, clippy::all, missing_docs)]' \
    ''

# ISP35: rk-isp35 includes rk-isp33, which includes rk-isp39, on top of the ISP32 chain, and
# develop-6.1's rk-isp2 differs from the develop-5.10 one, so the develop-6.1 headers are laid
# over a copy of the others.
inc61="$inc/61"
mkdir -p "$inc61/linux"
cp "$inc"/linux/*.h "$inc61/linux/"
for h in rk-isp2-config.h rk-isp33-config.h rk-isp35-config.h rk-isp39-config.h; do
    sed '/#include <linux\/rk-camera-module.h>/d' "$h61/$h" >"$inc61/linux/$h"
done
gen "$here/src/isp35.rs" rk-isp35-config.h "$inc61" 'isp35_.*|rkisp35_.*' 'ISP35_.*' \
    '//! @generated by bindgen from `rk-isp35-config.h` (and the ISP33, ISP39, ISP32, ISP3, ISP21' \
    '//! and ISP2 headers it includes), rockchip-linux/kernel `develop-6.1` `include/uapi/linux`, licensed' \
    '//! `(GPL-2.0+ WITH Linux-syscall-note) OR MIT`; used here under MIT. Regenerate with' \
    '//! `bindgen.sh`; do not edit.' \
    '//!' \
    "//! Bindgen output for the uAPI structures' bitfields: the accessors are unsafe by bindgen's" \
    '//! design. The types the ISP35 structures contain from the other headers are generated again' \
    '//! here, so this module stands alone.' \
    '' \
    '#![allow(non_camel_case_types, non_snake_case, non_upper_case_globals, dead_code, clippy::all, missing_docs)]' \
    '#![allow(clippy::undocumented_unsafe_blocks, clippy::multiple_unsafe_ops_per_block)]' \
    ''
