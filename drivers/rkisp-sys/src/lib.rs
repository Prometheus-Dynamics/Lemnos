//! The vendor kernel's `rkisp` driver's parameter and statistics buffers, as `#[repr(C)]` layouts:
//! ISP21 ([`isp21`], `rk-isp21-config.h`), ISP30 ([`isp3x`], `rk-isp3-config.h`), ISP32 ([`isp32`],
//! `rk-isp32-config.h`, with its lite statistics), ISP35 ([`isp35`], `rk-isp35-config.h`) and ISP39
//! ([`isp39`], `rk-isp39-config.h`), and the module bits each one's `module_ens` /
//! `module_en_update` / `module_cfg_update` masks take ([`modules`]).
//!
//! Layouts only: no device code, no tuning, no statistics math. A caller that fills a parameter
//! buffer or reads a statistics buffer uses these; the driver carries the bytes and only needs
//! their sizes (the `*_BYTES` constants). The sizes and the offsets of the blocks a caller reaches
//! first are checked at compile time against the C compiler's ([`layout`]), and the module bits
//! against the same headers by `layout-check/modules.py`.
//!
//! Provenance: the generated modules are bindgen's output, generated by `bindgen.sh` from the uAPI
//! headers of rockchip-linux/kernel (`develop-5.10` for ISP21 and ISP30, `develop-6.1` for ISP32,
//! ISP35 and ISP39), licensed `(GPL-2.0+ WITH Linux-syscall-note) OR MIT` and used here under MIT;
//! the headers are not kept here. Ported from the dev branch's `crates/lemnos-rkisp-sys` (its
//! generated files and `scripts/rkisp-bindgen.sh`); the one change is that the structures no longer
//! derive `bytemuck`'s traits, so the crate has no dependency.
//!
//! Byte views: [`bytes::Bytes`] converts each buffer structure to and from its bytes, so a caller
//! writes a field at its offset with no `unsafe` of its own. Its soundness argument is in the
//! `bytes` module and checked by `layout-check/field_types.py`.
//!
//! Unsafe code: bindgen's bitfield accessors in [`isp35`] and [`isp39`] (unsafe by bindgen's
//! design; each module's header allows the two lints they break), and the byte view's operations in
//! [`bytes`], each with a `SAFETY` comment.

#![no_std]

pub mod bytes;
pub mod isp21;
pub mod isp32;
pub mod isp35;
pub mod isp39;
pub mod isp3x;
mod layout;

use core::mem::size_of;

/// Bytes of an ISP21 parameter buffer (`struct isp21_isp_params_cfg`).
pub const ISP21_PARAMS_BYTES: usize = size_of::<isp21::isp21_isp_params_cfg>();
/// Bytes of an ISP21 statistics buffer (`struct rkisp_isp21_stat_buffer`).
pub const ISP21_STATS_BYTES: usize = size_of::<isp21::rkisp_isp21_stat_buffer>();
/// Bytes of an ISP30 parameter buffer (`struct isp3x_isp_params_cfg`).
pub const ISP30_PARAMS_BYTES: usize = size_of::<isp3x::isp3x_isp_params_cfg>();
/// Bytes of an ISP30 statistics buffer (`struct rkisp3x_isp_stat_buffer`).
pub const ISP30_STATS_BYTES: usize = size_of::<isp3x::rkisp3x_isp_stat_buffer>();
/// Bytes of an ISP35 parameter buffer (`struct isp35_isp_params_cfg`).
pub const ISP35_PARAMS_BYTES: usize = size_of::<isp35::isp35_isp_params_cfg>();
/// Bytes of an ISP35 statistics buffer (`struct rkisp35_stat_buffer`).
pub const ISP35_STATS_BYTES: usize = size_of::<isp35::rkisp35_stat_buffer>();
/// Bytes of an ISP32 parameter buffer (`struct isp32_isp_params_cfg`, shared by ISP_V32 and
/// ISP_V32_L).
pub const ISP32_PARAMS_BYTES: usize = size_of::<isp32::isp32_isp_params_cfg>();
/// Bytes of an ISP32 statistics buffer (`struct rkisp32_isp_stat_buffer`).
pub const ISP32_STATS_BYTES: usize = size_of::<isp32::rkisp32_isp_stat_buffer>();
/// Bytes of an ISP32 lite statistics buffer (`struct rkisp32_lite_stat_buffer`, ISP_V32_L).
pub const ISP32_LITE_STATS_BYTES: usize = size_of::<isp32::rkisp32_lite_stat_buffer>();
/// Bytes of an ISP39 parameter buffer (`struct isp39_isp_params_cfg`).
pub const ISP39_PARAMS_BYTES: usize = size_of::<isp39::isp39_isp_params_cfg>();
/// Bytes of an ISP39 statistics buffer (`struct rkisp39_stat_buffer`).
pub const ISP39_STATS_BYTES: usize = size_of::<isp39::rkisp39_stat_buffer>();

/// The module bits of each generation, generated from the develop-6.1 headers by
/// `layout-check/modules.py` (each value is checked against the C compiler there): [`module`] for
/// ISP21, [`module30`] for ISP30, [`module32`] for ISP32, [`module35`] for ISP35 and [`module39`]
/// for ISP39.
pub mod modules;
pub use modules::{module, module30, module32, module35, module39};

