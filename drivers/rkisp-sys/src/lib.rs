//! The vendor kernel's `rkisp` driver's parameter and statistics buffers for three ISP
//! generations, as `#[repr(C)]` layouts: ISP21 ([`isp21`], `rk-isp21-config.h`), ISP30
//! ([`isp3x`], `rk-isp3-config.h`) and ISP35 ([`isp35`], `rk-isp35-config.h`), with the module
//! bits ISP21 and ISP30 read from `module_ens` / `module_en_update` / `module_cfg_update`.
//!
//! Layouts only: no device code, no tuning, no statistics math. A caller that fills a parameter
//! buffer or reads a statistics buffer uses these; the driver carries the bytes and only needs
//! their sizes ([`ISP21_PARAMS_BYTES`] and the rest). The sizes and the offsets of the blocks a
//! caller reaches first are checked at compile time against the C compiler's ([`layout`]).
//!
//! Provenance: the three modules are bindgen's output, generated by `bindgen.sh` from the uAPI
//! headers of rockchip-linux/kernel (`develop-5.10` for ISP21 and ISP30, `develop-6.1` for ISP35),
//! licensed `(GPL-2.0+ WITH Linux-syscall-note) OR MIT` and used here under MIT; the headers are
//! not kept here. Ported from the dev branch's `crates/lemnos-rkisp-sys` (its generated files and
//! `scripts/rkisp-bindgen.sh`); the one change is that the structures no longer derive
//! `bytemuck`'s traits, so the crate has no dependency.
//!
//! Unsafe code: only bindgen's bitfield accessors in [`isp35`], unsafe by bindgen's design; the
//! module's header allows the two lints they break, and nothing else in the crate is unsafe.

#![no_std]

pub mod isp21;
pub mod isp35;
pub mod isp3x;
mod layout;

use core::mem::size_of;

/// Bytes of an ISP21 parameter buffer (`struct isp21_isp_params_cfg`).
pub const ISP21_PARAMS_BYTES: usize = size_of::<isp21::isp21_isp_params_cfg>();
/// Bytes of an ISP21 statistics buffer (`struct rkisp_isp21_stat_buffer`).
pub const ISP21_STATS_BYTES: usize = size_of::<isp21::rkisp_isp21_stat_buffer>();
/// Bytes of an ISP30 parameter buffer (`struct isp3x_isp_params_cfg`).
pub const ISP30_PARAMS_BYTES: usize = size_of::<isp3x::isp3x_isp_params_cfg>();
/// Bytes of an ISP30 statistics buffer (`struct rkisp3x_isp_stat_buffer`).
pub const ISP30_STATS_BYTES: usize = size_of::<isp3x::rkisp3x_isp_stat_buffer>();
/// Bytes of an ISP35 parameter buffer (`struct isp35_isp_params_cfg`).
pub const ISP35_PARAMS_BYTES: usize = size_of::<isp35::isp35_isp_params_cfg>();
/// Bytes of an ISP35 statistics buffer (`struct rkisp35_stat_buffer`).
pub const ISP35_STATS_BYTES: usize = size_of::<isp35::rkisp35_stat_buffer>();

/// A module's bit in an ISP21 or ISP30 parameter buffer's `module_*` masks (`ISP2X_ID_*` of
