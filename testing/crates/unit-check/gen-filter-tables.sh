#!/usr/bin/env bash
# Writes src/filter_tables.rs: systemd's system call groups, as this host's systemd expands them
# (`systemd-analyze syscall-filter`), and the x86_64 call numbers from a kernel tree's
# arch/x86/entry/syscalls/syscall_64.tbl (the guest's kernel). Both sources and their versions are
# recorded in the file. Run it again when either changes; the check reads only the file.
#
#   gen-filter-tables.sh <linux source tree>
set -euo pipefail
tree="$1"
here="$(cd "$(dirname "$0")" && pwd)"
tbl="$tree/arch/x86/entry/syscalls/syscall_64.tbl"
version="$(sed -n 's/^VERSION = //p;s/^PATCHLEVEL = //p;s/^SUBLEVEL = //p' "$tree/Makefile" | paste -sd.)"
systemd="$(systemctl --version | sed -n '1s/^systemd [0-9]* (\(.*\))$/\1/p')"
out="$here/src/filter_tables.rs"
{
  echo "//! Generated by gen-filter-tables.sh; do not edit."
  echo "//!"
  echo "//! Groups from \`systemd-analyze syscall-filter\` of systemd $systemd; x86_64 numbers from"
  echo "//! syscall_64.tbl of Linux $version (abi common and 64)."
  echo
  echo "/// The systemd that expanded the groups."
  echo "pub const SYSTEMD: &str = \"$systemd\";"
  echo "/// The kernel the x86_64 numbers are from."
  echo "pub const LINUX: &str = \"$version\";"
  echo
  echo "/// Each group and its members: call names, and other groups by their \`@\` name."
  echo "pub const GROUPS: &[(&str, &[&str])] = &["
  systemd-analyze syscall-filter 2>/dev/null | awk '
    /^@/ { if (g != "") print "    ]),"; g = $1; printf "    (\"%s\", &[\n", g; next }
    /^ *#/ || /^ *$/ { next }
    { gsub(/^ +/, ""); printf "        \"%s\",\n", $0 }
    END { if (g != "") print "    ]),"; }'
  echo "];"
  echo
  echo "/// x86_64 call numbers by name."
  echo "pub const X86_64: &[(&str, u32)] = &["
  awk '!/^#/ && NF >= 3 && ($2 == "common" || $2 == "64") { printf "    (\"%s\", %s),\n", $3, $1 }' "$tbl"
  echo "];"
} > "$out"
rustfmt --edition 2024 "$out"
echo "wrote $out (systemd $systemd, Linux $version)"
